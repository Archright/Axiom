suite "Rust lane vault manifest (#247) and pre-parsed outcome (#229)":
  test "#229: rustSubjectOutcomeParsed matches rustSubjectOutcome on fixture LLBC":
    let llbcPath = "tests/fixtures/rust/axiom_u64_probe/axiom_u64_probe.llbc"
    let subjectRoot = "tests/fixtures/rust/axiom_u64_probe"
    if not fileExists(llbcPath):
      skip()
    else:
      let llbcText = readFile(llbcPath)
      let parsed = parseJson(llbcText)
      let names = llbcFunDeclNamePaths(parsed)
      check names.len > 0
      let target = names[0].fullName
      let contract = rustSubjectInputContract(parsed, subjectRoot, "")
      let direct = rustSubjectOutcome(llbcText, target, subjectRoot = subjectRoot)
      let cached = rustSubjectOutcomeParsed(parsed, contract, target)
      check cached.producer.ok == direct.producer.ok
      check cached.agreement.verdict == direct.agreement.verdict
      check cached.agreement.nimDigest == direct.agreement.nimDigest

  test "#229: prepared-document resolution reproduces the frozen pre-refactor oracle":
    ## The refactor replaced the per-call document walk with a prepared form.
    ## Comparing the two new paths to EACH OTHER would be vacuous (both call
    ## the same code), so the oracle is frozen instead: llbc_resolution_golden.tsv
    ## was generated by the PRE-refactor implementation at a6805fc4 and records
    ## ok / error class / reason text / canonical digest for every addressable
    ## name, every bare last segment (the fallback rule), the empty name, two
    ## NotFound shapes and the ambiguity shapes in every fixture. Both new
    ## entry points must reproduce it byte-for-byte.
    const goldenPath = "tests/fixtures/rust/llbc_resolution_golden.tsv"
    let golden = readFile(goldenPath)
    var generated: string
    const fixtures = [
      "axiom_u64_probe", "axiom_rust_probe", "axiom_guard_probe",
      "axiom_impl_probe"]
    for fx in fixtures:
      let llbcPath = "tests/fixtures/rust/" & fx / (fx & ".llbc")
      if not fileExists(llbcPath): continue
      let parsed = parseJson(readFile(llbcPath))
      let preparedDoc = prepareLlbcDocument(parsed)
      check preparedDoc.ok
      var probes: seq[string] = @[]
      for d in llbcFunDeclNamePaths(parsed):
        probes.add(d.fullName)
        if d.lastSegment.len > 0: probes.add(d.lastSegment)
      probes.add("")
      probes.add("no_such_decl_anywhere")
      probes.add("serde_json::lexical::digit::add_digit")
      var seen: seq[string] = @[]
      for probe in probes:
        if seen.contains(probe): continue
        seen.add(probe)
        for path in [llbcFunctionToCanonical(parsed, probe),
                     llbcFunctionToCanonicalIn(preparedDoc, probe)]:
          let dg =
            if not path.ok: "-"
            else: sha256Hex($(%*{"modulePath": path.canonical.modulePath,
                                 "funcName": path.canonical.funcName,
                                 "returnPlace": path.canonical.returnPlace,
                                 "failureMode": $path.canonical.failureMode,
                                 "params": path.canonical.params.len,
                                 "body": path.canonical.body.len}))
          generated.add(fx & "\t" & probe & "\t" & $path.ok & "\t" &
                        $path.error & "\t" & path.reason & "\t" & dg & "\n")
    var goldenLines: seq[string] = @[]
    for line in golden.splitLines():
      if line.len > 0: goldenLines.add(line)
    var generatedLines: seq[string] = @[]
    for line in generated.splitLines():
      if line.len > 0: generatedLines.add(line)
    check goldenLines.len > 0
    check generatedLines.len == goldenLines.len * 2
    # Interleaved per probe: [single-target, prepared] each must equal the
    # frozen line for that probe.
    for i in 0 ..< goldenLines.len:
      check generatedLines[i * 2] == goldenLines[i]
      check generatedLines[i * 2 + 1] == goldenLines[i]

  test "#229: the document is prepared once, not once per candidate":
    ## The defect #229 measured was O(candidates x document): every target
    ## re-derived the intern tables and re-scanned every decl. The prepared
    ## form must therefore be reusable — resolving N names against ONE
    ## document must not depend on N for the derived state.
    let llbcPath = "tests/fixtures/rust/axiom_rust_probe/axiom_rust_probe.llbc"
    if not fileExists(llbcPath):
      skip()
    else:
      let parsed = parseJson(readFile(llbcPath))
      let doc = prepareLlbcDocument(parsed)
      check doc.ok
      check doc.decls.elems.len > 0
      check doc.nameKnown.len == doc.decls.elems.len
      check doc.fullNames.len == doc.decls.elems.len
      check doc.lastSegments.len == doc.decls.elems.len
      let first = llbcFunctionToCanonicalIn(doc, doc.fullNames[0])
      let again = llbcFunctionToCanonicalIn(doc, doc.fullNames[0])
      check first.reason == again.reason
      check first.ok == again.ok

  test "#229: a document that cannot be resolved fails identically for every name":
    ## A whole-document failure is a property of the document, so hoisting it
    ## must not turn it into a per-name accident: every target sees the same
    ## error/reason the per-call path produces.
    let broken = %*{"translated": {"crate_name": "x", "files": [],
                                   "fun_decls": []}}
    let doc = prepareLlbcDocument(broken)
    check doc.ok
    for probe in ["a", "b", "no_such_decl_anywhere"]:
      let direct = llbcFunctionToCanonical(broken, probe)
      let prepared = llbcFunctionToCanonicalIn(doc, probe)
      check prepared.reason == direct.reason
      check prepared.error == direct.error
    let malformed = %*{"has_errors": true, "translated": {}}
    let badDoc = prepareLlbcDocument(malformed)
    check not badDoc.ok
    let directBad = llbcFunctionToCanonical(malformed, "a")
    let preparedBad = llbcFunctionToCanonicalIn(badDoc, "a")
    check preparedBad.reason == directBad.reason
    check preparedBad.error == directBad.error

  test "#247: merging issued Rust certificate into vault manifest enables cert_export":
    let tmp = getTempDir() / ("ax_247_" & $getCurrentProcessId())
    let vaultDir = tmp / "vault"
    let outDir = tmp / "export"
    createDir(vaultDir)
    try:
      let irHash = sha256Hex("rust-lane-247-ir")
      let modulePath = "src/lib.rs"
      let fnName = "probe_crate::add_u8"
      let certBody = %*{
        "modulePath": modulePath,
        "functionName": fnName,
        "status": "certLeanVerified",
        "verificationTier": "lean-verified",
        "solverStatus": "",
        "kernel": true,
        "solverMeta": {"leanCompilerVerified": true, "z3Executed": false},
        "irHash": irHash,
        "leanSource": "theorem add_u8_post : True := trivial",
        "leanProposition": "True",
        "axiomsUsed": ["propext"]
      }
      writeFile(vaultDir / (irHash & ".json"), $certBody)
      let manifestPath = vaultDir / "manifest.json"
      var m = loadManifest(manifestPath)
      m.mergeResult(
        certBody.getOrDefault("functionName").getStr(),
        certBody.getOrDefault("modulePath").getStr(),
        irHash,
        certBody.getOrDefault("status").getStr(),
        "smLean")
      m.atomicWriteManifest(manifestPath)
      check fileExists(manifestPath)
      let exp = exportToDir(vaultDir, outDir)
      if not exp.ok:
        echo "EXPORT FAIL: codes=", exp.codes, " detail=", exp.detail
      check exp.ok
      check exp.certCount == 1
      check exp.codes.len == 0
    finally:
      removeDir(tmp)
