## Evidence file name from module path and function name.
# @axiom-hint: lean="modulePath.length ≥ 0 ∧ functionName.length ≥ 0" smt="(assert (and (>= (str.len modulePath) 0) (>= (str.len functionName) 0)))"
# @axiom-hint: smt="vacuous_primitive"  # axiom:certified-exempt(import-heuristic; annotate-then-purge DEBT#303)
func evidenceFileName*(modulePath: string; functionName: string): string {.noSideEffect, axiomTryImpl.} =
  let modulePart = modulePath.replace("/", "_").replace(".nim", "")
  let funcPart = functionName.replace("/", "_").replace("::", "_")
  modulePart & "_nim_" & funcPart & ".lean"

## Detect corrupted evidence: Nat.zero_le applied to Int-typed variables
## or trivial proving a non-True goal.
# @axiom-hint: lean="content.length ≥ 0" smt="(assert (and (>= (str.len content) 0)))"
func isCorruptedEvidence*(content: string): bool {.noSideEffect, axiomImpl.} =
  if content.len == 0:
    return false
  ## Pattern A: Int parameter + Nat.zero_le → type mismatch
  if content.contains(": Int") and content.contains("exact Nat.zero_le"):
    return true
  ## Pattern B: exact trivial on non-True goal
  if content.contains("exact trivial\n"):
    let theoremIdx = content.find("theorem ")
    if theoremIdx >= 0:
      let afterTheorem = content[theoremIdx .. ^1]
      let colonIdx = afterTheorem.find(" : ")
      if colonIdx >= 0:
        let remainder = afterTheorem[colonIdx + 3 .. ^1]
        let byIdx = remainder.find(" := by")
        if byIdx >= 0:
          let conclusion = remainder[0 ..< byIdx].strip()
          if conclusion != "True":
            return true
  return false

## Pre-flight static isolation gate.
## Scans generated Lean 4 theorem content for known syntactic impurities
## before allowing it into a bundle. Returns true if clean.
## Patterns:
##   - Bullet corruption (·) from legacy constructor paths
##   - Bare => in theorem statement (SMT implication mistranslation)
##   - Empty theorem body after := by
# @axiom-hint: smt="vacuous_primitive"  # axiom:certified-exempt(import-heuristic; annotate-then-purge DEBT#303)
func preFlightLeanCheck*(content: string): bool {.raises: [].} =
  if content.len == 0:
    return false
  ## Pattern A: bullet corruption (legacy constructor + ·)
  if content.contains("·"):
    return false
  ## Pattern B: bare => in theorem statement (not inside fun/match)
  let theoremIdx = content.find("theorem ")
  if theoremIdx >= 0:
    let afterTheorem = content[theoremIdx .. ^1]
    let byIdx = afterTheorem.find(" := by")
    if byIdx >= 0:
      let statement = afterTheorem[0 ..< byIdx]
      ## Detect bare => (implication arrow) in statement.
      ## Valid contexts: fun (x : T) => e, match ... => e
      ## Invalid context: theorem foo : P => Q := by
      if statement.contains(" => "):
        return false
  ## Pattern C: empty proof body
  if content.contains(" := by\n") and not content.contains(" := by\n  "):
    return false
  return true

## Detect high-quality evidence generated by leanstral or advanced pipeline.
## These must be preserved and never overwritten by primitive reconstructor.
# @axiom-hint: lean="content.length ≥ 0" smt="(assert (and (>= (str.len content) 0)))"
# @axiom-hint: smt="vacuous_primitive"  # axiom:certified-exempt(import-heuristic; annotate-then-purge DEBT#303)
func isHighQualityEvidence*(content: string): bool {.noSideEffect, axiomImpl.} =
  if content.len == 0:
    return false
  if content.contains("h_sys"): return true
  if content.contains("variable {α"): return true
  if content.contains("NimInt"): return true
  if content.contains("NimNat"): return true
  if content.contains("NimString"): return true
  if content.contains("aesop"): return true
  if content.contains("omega"): return true
  if content.contains("simpa"): return true
  if content.contains("_NEG"): return true
  return false

## Detect provenance from evidence content.
## Returns "leanstral" when leanstral markers are present, otherwise empty.
# @axiom-hint: lean="content.length ≥ 0" smt="(assert (and (>= (str.len content) 0)))"
# @axiom-hint: lean="ast_parse_failed_isolated" smt="(assert ast_parse_failed_isolated)"
# @axiom-hint: smt="vacuous_primitive"  # axiom:certified-exempt(import-heuristic; annotate-then-purge DEBT#303)
func detectProvenanceFromContent*(content: string): string {.noSideEffect, axiomImpl.} =
  if isHighQualityEvidence(content):
    return "leanstral"
  return ""

## Check if a certificate is protected by provenance metadata.
## Primary guard: reads certificate "provenance" field.
## Fallback: uses isHighQualityEvidence heuristics for legacy certs.
# @axiom-hint: lean="certPath.length ≥ 0 ∧ external_io_isolated" smt="(assert (and (>= (str.len certPath) 0) external_io_isolated))"
proc isProvenanceProtected*(certPath: string): bool  =
  let nodeOpt = readJsonFile(certPath)
  if nodeOpt.isNone:
    return false
  let node = nodeOpt.get()
  if node.kind != JObject:
    return false
  let provenance = node.getOrDefault("provenance").getStr("")
  if provenance == "leanstral":
    return true
  ## Legacy fallback: evidence without provenance metadata
  if provenance.len == 0:
    let modulePath = node.getOrDefault("modulePath").getStr("")
    let functionName = node.getOrDefault("functionName").getStr("")
    if modulePath.len > 0 and functionName.len > 0:
      let evidenceName = evidenceFileName(modulePath, functionName)
      var evidencePath = ""
      try:
        evidencePath = joinPath(getCurrentDir(), "logs", "evidence", evidenceName)
      except CatchableError:
        return false
      if fileExists(evidencePath):
        try:
          let readRes = readFileOpt(evidencePath)
          if readRes.isErr: discard
          let content = readRes.get
          return isHighQualityEvidence(content)
        except CatchableError:
          return false
  return false

## Enforce provenance gate before overwriting an existing certificate.
## Returns true if write is allowed (cert does not exist or is not protected).
## Returns false if the certificate is protected and must not be overwritten.
# @axiom-hint: lean="certPath.length ≥ 0 ∧ proposedProvenance.length ≥ 0" smt="(assert (and (>= (str.len certPath) 0) (>= (str.len proposedProvenance) 0)))"
proc enforceProvenanceBeforeWrite*(certPath: string; proposedProvenance: string  = ""): bool =
  if not fileExists(certPath):
    return true
  if isProvenanceProtected(certPath):
    return false
  return true

## Record a provenance overwrite attempt to the thread-local audit buffer.
## [AXIOM v0.6.8] Mid-pipeline disk I/O on provenance_overwrite.jsonl is
## permanently discontinued. Events are flushed atomically during
## commitUniverseIntegrityAndLock.
# @axiom-hint: lean="nodeId.length ≥ 0 ∧ reason.length ≥ 0" smt="(assert (and (>= (str.len nodeId) 0) (>= (str.len reason) 0)))"
# @axiom-hint: smt="vacuous_primitive"  # axiom:certified-exempt(import-heuristic; annotate-then-purge DEBT#303)
proc recordProvenanceOverwriteAttempt*(nodeId, reason: string) {.raises: [], axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect].} =
  let entry = %*{
    "timestamp": $getTime().utc,
    "reason": reason,
    "action": "blocked"
  }
  var ev = entry
  ev["nodeId"] = %nodeId
  threadProvenanceLog.add(ev)

# @axiom-hint: smt="vacuous_primitive"  # axiom:certified-exempt(import-heuristic; annotate-then-purge DEBT#303)
proc drainThreadProvenanceLog*(): seq[JsonNode] {.raises: [], axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect].} =
  ## Return and clear the current thread's provenance log buffer.
  result = threadProvenanceLog
  threadProvenanceLog = @[]

