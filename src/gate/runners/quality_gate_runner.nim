const
  QualityBaselinePath = "data/quality_gate_baseline.json"

# ─── Baseline ratchet ────────────────────────────────────────────────────────
# Group violations by "file::rule" and count, keyed identically in baseline.

func violationKey(file, rule: string): string {.raises: [].} =
  file & "::" & rule

func groupViolations(violations: seq[QualityViolation]): seq[(string, int)] {.raises: [].} =
  var counts = initTable[string, int]()
  for v in violations:
    counts.mgetOrPut(violationKey(v.file, v.rule), 0).inc
  var keys: seq[string] = @[]
  for k in counts.keys: keys.add(k)
  keys.sort()
  for k in keys:
    result.add((k, counts.getOrDefault(k, 0)))

proc loadBaseline(repoRoot: string): Table[string, int] {.raises: [].} =
  let path = repoRoot / QualityBaselinePath
  if not fileExists(path): return
  try:
    let data = parseJson(readFile(path))
    if data.hasKey("counts"):
      for k in data["counts"].keys:
        result[k] = data["counts"][k].getInt()
  except CatchableError, IOError, OSError: discard

func exceedBaseline(current: seq[(string, int)]; baseline: Table[string, int]): seq[(string, int, int)] =
  for (key, count) in current:
    let base = baseline.getOrDefault(key, 0)
    if count > base:
      result.add((key, count, base))

func summary(report: seq[(string, int, int)]): string =
  var items: seq[string] = @[]
  for (key, count, base) in report:
    items.add("    " & key & ": " & $count & " > baseline " & $base)
  items.join("\n")

proc saveBaseline(repoRoot: string; current: seq[(string, int)]) {.raises: [CatchableError, IOError, OSError].} =
  let path = repoRoot / QualityBaselinePath
  let parentDir = path.parentDir()
  if parentDir.len > 0 and not dirExists(parentDir):
    createDir(parentDir)
  var countsObj = newJObject()
  for (k, v) in current:
    countsObj[k] = newJInt(v)
  let payload = %*{
    "counts": countsObj,
    "source": "src/",
    "note": "Auto-generated by quality_gate_runner --update-baseline"
  }
  writeFile(path, $payload & "\n")

proc main()  =
  try:
    let args = commandLineParams()
    var fullTree = false
    var updateBaseline = false
    var files: seq[string] = @[]

    var i = 0
    while i < args.len:
      case args[i]
      of "--full-tree":
        fullTree = true
      of "--update-baseline":
        updateBaseline = true
      of "--files":
        if i + 1 < args.len:
          inc i
          for f in args[i].split(','):
            let trimmed = f.strip()
            if trimmed.len > 0:
              files.add(trimmed)
      of "--stdin-files":
        for line in stdin.readAll().splitLines():
          let trimmed = line.strip()
          if trimmed.len > 0:
            files.add(trimmed)
      else:
        files.add(args[i])
      inc i

    if files.len == 0 and not fullTree:
      logInfo("quality_gate_runner", "[quality-gate] SKIP -- no staged Nim files")
      quit(0)

    let violations = runQualityGate(stagedFiles = files, fullTree = fullTree)
    let current = groupViolations(violations)

    if updateBaseline:
      saveBaseline(getCurrentDir(), current)
      logInfo("quality_gate_runner", "[quality-gate] baseline updated (" &
              $current.len & " groups) at " & QualityBaselinePath)
      quit(0)

    let baseline = loadBaseline(getCurrentDir())
    if violations.len == 0:
      logInfo("quality_gate_runner", "[quality-gate] PASS -- no violations detected")
      quit(0)
    let above = exceedBaseline(current, baseline)
    if above.len == 0:
      logInfo("quality_gate_runner",
              "[quality-gate] PASS -- " & $violations.len &
              " violation(s), all at or below frozen baseline")
      quit(0)
    logInfo("quality_gate_runner",
            "[quality-gate] FAIL -- " & $above.len &
            " violation group(s) exceed frozen baseline:\n" & summary(above))
    quit(1)
  except Exception as e:
    logInfo("quality_gate_runner", "quality gate error: " & e.msg)
    quit(1)

when isMainModule:
  main()

