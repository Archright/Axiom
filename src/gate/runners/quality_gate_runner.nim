## Quality Gate Runner (L2 Functional)
##
## Entry point for the AST-based quality gate (DEBT#011).
## Replaces regex-based file pattern matching with Nim compiler
## PNode AST analysis for import dependency resolution.
##
## Baseline (ratchet) semantics:
##   Despite the "Static-First" func-ratio rule, the quality gate is itself a
##   proc-heavy I/O-boundary tool and the broader codebase carries pre-existing
##   violations (historically 506 under --full-tree). Freezing those known
##   violations into data/quality_gate_baseline.json lets the gate activate and
##   enforce monotonic improvement: violations are FAIL only when a (file, rule)
##   count EXCEEDS its baseline. The baseline can be refreshed deterministically
##   via `--update-baseline` (mirrors hermetic_test_gate ratchet).
##
## Usage:
##   quality_gate_runner [--full-tree] [--files path1,path2,...] [--update-baseline]
##
## Exit codes:
##   0 -- quality checks passed (at or below baseline)
##   1 -- a (file, rule) violation count exceeds baseline (or new violation)

