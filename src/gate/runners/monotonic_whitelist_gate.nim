## Monotonic impure_procedures_whitelist Ratchet Gate
##
## Ensures the impure_procedures_whitelist section in
## src/gate/architecture_policy.lock never grows. Decreases are allowed and
## encouraged; increases block the build.
##
## Usage:
##   monotonic_whitelist_gate              # compare against baseline
##   monotonic_whitelist_gate --update-baseline
##
## The baseline file (data/impure_procedures_whitelist_baseline.json) is the
## single source of truth. When the whitelist shrinks, run with
## --update-baseline and commit the updated baseline.

