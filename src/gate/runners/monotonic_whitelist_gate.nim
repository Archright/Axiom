axiomIoBoundary()

const
  GateTag = "[monotonic-whitelist]"
  LockRelPath = "src/gate/architecture_policy.lock"
  BaselineRelPath = "data/impure_procedures_whitelist_baseline.json"
  CeilingRelPath = "data/ratchet_ceiling.json"


func parseWhitelistCount(content: string): int =
  ## Return the number of entries in the [impure_procedures_whitelist] section.
  var inSection = false
  for line in content.splitLines():
    if line.strip() == "[impure_procedures_whitelist]":
      inSection = true
      continue
    if inSection:
      if line.startsWith("[") and not line.startsWith("[["):
        break
      if line.strip().startsWith("whitelist"):
        let parts = line.split("=", 1)
        if parts.len > 1:
          let value = parts[1].strip()
          # Count quoted entries: "entry"
          var i = 0
          while i < value.len:
            if value[i] == '"':
              inc i
              while i < value.len and value[i] != '"':
                inc i
              inc i  # skip closing quote
              inc result
            else:
              inc i


proc readLockContent(repoRoot: string): string {.axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect].} =
  let lockPath = repoRoot / LockRelPath
  if not fileExists(lockPath):
    logError("monotonic_whitelist_gate", $(GateTag) & " FAIL: lock file missing (" & $(LockRelPath) & ")")
    quit(1)
  result = readFile(lockPath)


proc loadBaselineCount(repoRoot: string): int {.axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect].} =
  ## Load baseline count. Returns -1 if baseline missing.
  let baselinePath = repoRoot / BaselineRelPath
  if not fileExists(baselinePath):
    return -1
  try:
    let data = parseJson(readFile(baselinePath))
    result = data["count"].getInt()
  except CatchableError:
    logError("monotonic_whitelist_gate", "Corrupt whitelist baseline = FAIL")
    result = -1


proc loadCeiling(repoRoot: string): int {.axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect].} =
  ## Load ratchet ceiling. Returns 0 if missing.
  let ceilingPath = repoRoot / CeilingRelPath
  if not fileExists(ceilingPath):
    return 0
  try:
    let data = parseJson(readFile(ceilingPath))
    result = data["impure_proc_ceiling"].getInt()
  except CatchableError:
    logError("monotonic_whitelist_gate", "Corrupt ratchet ceiling = FAIL")
    result = 0


proc saveBaselineCount(repoRoot: string, count: int) {.axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect].} =
  let baselinePath = repoRoot / BaselineRelPath
  let parentDir = baselinePath.parentDir()
  if not dirExists(parentDir):
    createDir(parentDir)
  let payload = %*{
    "count": count,
    "source": LockRelPath,
    "note": "Auto-generated by tools/ci/monotonic_whitelist_gate.py --update-baseline"
  }
  writeFile(baselinePath, $payload & "\n")


proc main() {.axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect].} =
  let repoRoot = findRepoRoot()
  setCurrentDir(repoRoot)

  var updateBaseline = false
  for i in 1 .. paramCount():
    if paramStr(i) == "--update-baseline":
      updateBaseline = true
      break

  let currentContent = readLockContent(repoRoot)
  let currentCount = parseWhitelistCount(currentContent)

  if updateBaseline:
    saveBaselineCount(repoRoot, currentCount)
    logger.info $GateTag & " Baseline updated to " & $currentCount & "."
    logger.info $GateTag & " Stage and commit " & $BaselineRelPath & "."
    quit(0)

  let baselineCount = loadBaselineCount(repoRoot)

  logger.info $GateTag & " Current whitelist count: " & $currentCount

  if baselineCount < 0:
    logError("monotonic_whitelist_gate", $(GateTag) & " FAIL: baseline file missing (" & $(BaselineRelPath) & ").")
    logInfo("monotonic_whitelist_gate", $(GateTag) & " Generate it with: --update-baseline")
    quit(1)

  logger.info $GateTag & " Baseline count: " & $baselineCount

  if currentCount > baselineCount:
    logError("monotonic_whitelist_gate", $(GateTag) & " FAIL: whitelist grew by " & $(currentCount - baselineCount) & " entries.")
    logInfo("monotonic_whitelist_gate", $(GateTag) & " New impure procedures must be justified and approved by the architect.")
    logInfo("monotonic_whitelist_gate", $(GateTag) & " To reduce the whitelist, run: tools/ci/auto_convert_proc_to_func.sh")
    quit(1)

  if currentCount < baselineCount:
    let ceiling = loadCeiling(repoRoot)

    if currentCount < ceiling:
      logError("monotonic_whitelist_gate", $(GateTag) & " FAIL: whitelist count " & $(currentCount) & " dropped below ratchet ceiling " & $(ceiling) & ".")
      logInfo("monotonic_whitelist_gate", $(GateTag) & " Update the ceiling in " & $(CeilingRelPath) & " or run with --update-baseline.")
      quit(1)

    logger.info $GateTag & " OK: whitelist decreased (" & $baselineCount & " -> " & $currentCount & ") & above ceiling " & $ceiling & "."
    logger.info $GateTag & " Run with --update-baseline to sync " & $BaselineRelPath & " & then commit it."
    quit(0)

  logger.info $GateTag & " PASS: whitelist count is stable."
  quit(0)

{.pop.}

when isMainModule:
  main()
