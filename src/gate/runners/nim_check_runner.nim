proc cleanupAggregator() {.noconv, raises: [], axiomEffect: IOEffect.} =
  for path in gAggregatorPaths:
    try:
      if fileExists(path):
        removeFile(path)
    except CatchableError:
      discard  # axiom:best-effort(ioboundary catch)

proc cleanupNimcheckRoots() {.noconv, raises: [], axiomEffect: IOEffect.} =
  ## Remove transient per-file nimcache roots created by runPerFileCheck.
  ## Invoked on SIGTERM/interrupt (and from cleanupAggregator) so a
  ## mid-batch termination never leaks temp dirs.
  for path in gNimcheckRoots:
    try:
      if dirExists(path):
        removeDir(path)
    except CatchableError:
      discard  # axiom:best-effort(ioboundary catch)
  gNimcheckRoots = @[]

when defined(posix):
  import std/posix
  proc sigtermAggregatorHandler(sig: cint) {.noconv, axiomEffect: IOEffect.} =
    cleanupAggregator()
    cleanupNimcheckRoots()

proc collectNimFiles(root, subdir: string): seq[string] {.raises: [], axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect].} =
  try:
    for f in walkDirRec(root / subdir):
      if f.endsWith(".nim"):
        result.add(f)
  except CatchableError:
    discard  # axiom:best-effort(ioboundary catch)

proc importPathFor(repoRoot, file: string): string {.raises: [], axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect].} =
  try:
    let rel = relativePath(file, repoRoot)
    let parts = rel.split(DirSep)
    var body: seq[string]
    if parts.len >= 2 and parts[0] == "src":
      body = parts[1 .. ^1]
    elif parts.len >= 3 and parts[0] == "tests" and parts[1] == "gateway":
      body = parts[2 .. ^1]
    else:
      body = parts
    result = body.join("/")
    if result.endsWith(".nim"):
      result = result[0 .. ^5]
  except CatchableError:
    result = ""

proc containsIsMainModule(path: string): bool {.raises: [].} =
  try:
    readFile(path).contains("when " & "isMainModule")
  except CatchableError:
    false

proc isForwardingStub(path: string): bool {.raises: [], axiomEffect: IOEffect.} =
  ## Detect deprecated forwarding stubs that cannot be imported in an
  ## aggregator without tripping -d:Deprecated-as-error. They are checked
  ## per-file instead.
  try:
    let content = readFile(path)
    var count = 0
    for line in content.splitLines:
      if count >= 10:
        break
      if line.contains("Forwarding stub"):
        return true
      if line.len > 0 and not line.startsWith("#"):
        break
      inc count
  except CatchableError:
    discard  # axiom:best-effort(ioboundary catch)
  false

proc cleanupOldAggregators(cacheDir: string) {.raises: [], axiomEffect: IOEffect.} =
  try:
    for kind, path in walkDir(cacheDir):
      if kind == pcFile and path.endsWith(".nim") and
         path.contains("axiom_gate_aggregator"):
        removeFile(path)
  except CatchableError:
    discard  # axiom:best-effort(ioboundary catch)

proc writeAggregator(path: string; imports: seq[string]; blockScoped: bool)
                    {.raises: [CatchableError], axiomEffect: IOEffect, axiomEffect: IOEffect.} =
  var lines: seq[string] = @["# AUTO-GENERATED by nim_check_gate -- do not edit"]
  if blockScoped:
    for i, imp in imports:
      if imp.len == 0:
        continue
      lines.add("block test_block_" & $i & ":")
      lines.add("  import " & imp)
  else:
    for imp in imports:
      if imp.len > 0:
        lines.add("import " & imp)
  writeFile(path, lines.join("\n") & "\n")

proc extractFailedModules(output, repoRoot: string): seq[string] {.raises: [].} =
  ## Return import paths of project modules that caused the aggregator to fail.
  ## Also parses the special "Forwarding stub: '<import>' deprecated" message
  ## reported on the aggregator line itself.
  var seen = initHashSet[string]()
  try:
    for line in output.splitLines:
      let stubPrefix = "Forwarding stub: '"
      let stubIdx = line.find(stubPrefix)
      if stubIdx >= 0:
        let start = stubIdx + stubPrefix.len
        let endq = line.find("'", start)
        if endq > start:
          let imp = line[start ..< endq]
          if imp.len > 0 and not seen.contains(imp):
            seen.incl(imp)
            result.add(imp)
          continue

      let idx = line.find(".nim(")
      if idx < 0:
        continue
      var start = idx
      while start > 0 and line[start - 1] notin {' ', '\t', '\n', ':'}:
        dec start
      let candidate = line[start ..< idx + 4]
      if candidate.contains("axiom_gate_aggregator"):
        continue
      if not candidate.startsWith(repoRoot):
        continue
      let rel = relativePath(candidate, repoRoot)
      let imp = importPathFor(repoRoot, repoRoot / rel)
      if imp.len > 0 and not seen.contains(imp):
        seen.incl(imp)
        result.add(imp)
  except CatchableError:
    discard  # axiom:best-effort(ioboundary catch)

