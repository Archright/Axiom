    if srcFiles.len > 0:
      let ts = $getTime().toUnix & "_" & $getCurrentProcessId()
      let agg = cacheDir / "axiom_gate_aggregator_src_" & ts & ".nim"
      gAggregatorPaths.add(agg)
      var normalFiles: seq[string]
      var perFileFiles: seq[string]
      var importToFile = initTable[string, string]()
      var excludedImports = initHashSet[string]()
