proc computeFingerprintHeader(repoRoot: string; files: seq[string];
                              maxJobs: int; start: times.Time;
                              finish: times.Time): string {.raises: [].} =
  ## Deterministic repro metadata emitted as a diagnostics header. All hashes
  ## use core/crypto/hash_kernel.sha256Hex (std/hashes is non-cryptographic and
  ## unsuitable). Enables reconstructing child/execution/cache state that led to
  ## a transient nim check failure.
  var corpus = ""
  for f in files:
    var content = ""
    try:
      content = readFile(f)
    except CatchableError:
      discard  # axiom:best-effort(diagnostic fingerprint read; missing file uses empty hash)
    corpus.add(f & "|" & sha256Hex(content) & "\n")
  var sortedList = files
  try:
    sortedList.sort()
  except CatchableError:
    discard  # axiom:best-effort(diagnostic fingerprint sort; fallback preserves input order)
  let envKeys = @["AXIOM_HERMETIC_BUILDING", "NPROC",
                  "AXIOM_CI_PRESERVE_CACHE", "AXIOM_ENV"]
  var envLines: seq[string] = @[]
  for k in envKeys:
    try:
      envLines.add(k & "=" & getEnv(k, ""))
    except CatchableError:
      envLines.add(k & "=<unreadable>")
  try:
    envLines.sort()
  except CatchableError:
    discard  # axiom:best-effort(diagnostic fingerprint env sort; fallback preserves input order)
  var hermeticVal = ""
  try:
    hermeticVal = getEnv("AXIOM_HERMETIC_BUILDING", "")
  except CatchableError:
    discard  # axiom:best-effort(diagnostic fingerprint hermetic val; fallback uses empty string)
  var binHash = "unreadable"
  try:
    binHash = sha256Hex(readFile(getAppFilename()))
  except CatchableError:
    discard  # axiom:best-effort(diagnostic fingerprint binary hash; fallback uses unreadable marker)
  result = "Axiom nim check fingerprint\n" &
    "corpusHash=" & sha256Hex(corpus) & "\n" &
    "fileCount=" & $files.len & "\n" &
    "orderMode=fixed\norderSeed=0\n" &
    "orderHash=" & sha256Hex(sortedList.join("\n")) & "\n" &
    "envAllowlistHash=" & sha256Hex(envLines.join("\n")) & "\n" &
    "hermetic=" & (if hermeticVal.len > 0: "1" else: "0") & "\n" &
    "binaryHash=" & binHash & "\n" &
    "nimVersion=" & $NimMajor & "." & $NimMinor & "." & $NimPatch & "\n" &
    "os=" & (when defined(posix): "posix" else: (when defined(windows): "windows" else: "unknown")) & "\n" &
    "jobs=" & $countProcessors() & "\n" &
    "requestedJobs=" & $maxJobs & "\n" &
    "concurrencyModel=process-polling(heavy)\n" &
    "timestamp=" & $start.toUnix & "\n" &
    "durationMs=" & $(finish - start).inMilliseconds & "\n"

