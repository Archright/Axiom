  of grmIncremental:
    if files.len == 0:
      return GateResult(ok: true, name: "Axiom nim check gate",
                        stdout: "", stderr: "", duration: getTime() - start)
    var targets: seq[string]
    for f in files:
      if f.endsWith(".nim") and fileExists(f):
        targets.add(f)
    if targets.len == 0:
      return GateResult(ok: true, name: "Axiom nim check gate",
                        stdout: "", stderr: "", duration: getTime() - start)
    if targets.len == 1:
      let r = runPerFileCheck(repoRoot, targets, maxJobs)
      return GateResult(ok: r.ok, name: "Axiom nim check gate",
                        stdout: r.log, stderr: "", duration: getTime() - start)

    let cacheDir = repoRoot / "build" / "nimcache"
    try:
      createDir(cacheDir)
    except CatchableError:
      discard  # axiom:best-effort(ioboundary catch)
    cleanupOldAggregators(cacheDir)

    defer: cleanupAggregator()
    when declared(setControlCHook):
      setControlCHook(cleanupAggregator)
    when defined(posix):
      discard signal(SIGTERM, sigtermAggregatorHandler)

