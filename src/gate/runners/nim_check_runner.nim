proc runPerFileCheck(repoRoot: string; files: seq[string];
                     maxJobs: int): tuple[ok: bool, log: string]
                    {.raises: [CatchableError].} =
  ## Run ``nim check`` on each file with a unique per-file ``--nimcache`` so
  ## concurrent checks cannot collide on shared compiler cache state.
  ## runBatch is the scheduler; this proc owns compiler invocation semantics.
  ## Captures child output (deadlock-safe byte drain) and returns a repro
  ## fingerprint header plus per-file failure diagnostics.
  if files.len == 0:
    return (ok: true, log: "")
  let start = getTime()
  # OS temp dir + pid yields a unique per-batch root; createTempDir is not
  # available across all supported Nim toolchains, so create explicitly.
  let tmpRoot = getTempDir() / ("axiom-nimcheck_" & $getCurrentProcessId())
  try:
    createDir(tmpRoot)
  except CatchableError:
    discard  # axiom:best-effort(ioboundary catch)
  gNimcheckRoots.add(tmpRoot)
  defer:
    gNimcheckRoots.keepItIf(it != tmpRoot)
    try:
      if dirExists(tmpRoot):
        removeDir(tmpRoot)
    except CatchableError:
      discard  # axiom:best-effort(ioboundary catch)
  var cmds: seq[CmdSpec] = @[]
  for i, f in files:
    let nc = tmpRoot / $i / "nimcache"
    cmds.add(cmdSpec("nim", @["check", "--hints:off", "--nimcache:" & nc, f],
                     captureOutput = true, file = f))
  let results = runBatch(cmds, repoRoot, maxJobs)
  var allOk = true
  var log = computeFingerprintHeader(repoRoot, files, maxJobs, start, getTime())
  for r in results:
    if r.exitCode != 0:
      allOk = false
      log.add("\n[FAILED] " & r.file & " (exit=" & $r.exitCode & ")\n")
      if r.stdout.len > 0:
        log.add(r.stdout)
        if not r.stdout.endsWith("\n"):
          log.add("\n")
  result = (ok: allOk, log: log)

proc runAggregatedSrcCheck(repoRoot: string; srcFiles: seq[string]; maxJobs: int;
                           cacheDir, prefix: string): tuple[ok: bool, log: string]
                          {.raises: [CatchableError].} =
  ## Single-invocation `nim check` over a generated aggregator that imports the
  ## given src/ modules. Modules that cannot be imported safely (isMainModule,
  ## forwarding stubs, or aggregator failures) fall back to per-file checks.
  let ts = $getTime().toUnix & "_" & $getCurrentProcessId()
  let agg = cacheDir / prefix & ts & ".nim"
  gAggregatorPaths.add(agg)

  var logOutput = ""
  var allOk = true

  var normalFiles: seq[string] = @[]
  var perFileFiles: seq[string] = @[]
  var importToFile = initTable[string, string]()
  var excludedImports = initHashSet[string]()
  for f in srcFiles:
    let imp = importPathFor(repoRoot, f)
    if imp.len > 0:
      importToFile[imp] = f
    if containsIsMainModule(f) or isForwardingStub(f):
      perFileFiles.add(f)
      if imp.len > 0:
        excludedImports.incl(imp)
    else:
      normalFiles.add(f)

  var aggExitCode = 1
  var attempt = 0
  const MaxAggregatorRetries = 3
  while attempt < MaxAggregatorRetries:
    let activeImports = normalFiles.mapIt(importPathFor(repoRoot, it)).filterIt(
      it.len > 0 and not excludedImports.contains(it)
    )
    writeAggregator(agg, activeImports, false)
    let (outp, code) = execCmdEx(
      "nim check --hints:off " & quoteShell(agg),
      workingDir = repoRoot,
      options = {poStdErrToStdOut}
    )
    logOutput.add(outp)
    aggExitCode = code
    if code == 0:
      break
    let failed = extractFailedModules(outp, repoRoot)
    var changed = false
    for imp in failed:
      if not excludedImports.contains(imp):
        excludedImports.incl(imp)
        changed = true
        if importToFile.hasKey(imp):
          perFileFiles.add(importToFile[imp])
    if not changed:
      break
    inc attempt

  var seenPerFile = initHashSet[string]()
  var uniquePerFile: seq[string] = @[]
  for f in perFileFiles:
    if not seenPerFile.contains(f):
      seenPerFile.incl(f)
      uniquePerFile.add(f)
  if uniquePerFile.len > 0:
    logOutput.add("\n[Per-file check] " & $uniquePerFile.len &
                  " module(s) excluded from aggregator\n")
    let r = runPerFileCheck(repoRoot, uniquePerFile, maxJobs)
    allOk = allOk and r.ok
    logOutput.add(r.log)

  result = (ok: allOk, log: logOutput)

proc runNimCheck*(repoRoot: string; mode: GateRunMode; maxJobs: int;
                  files: seq[string] = @[]): GateResult {.axiomEffect: IOEffect.} =
  let start = getTime()

  case mode
  of grmIncremental:
    # Fast-Feedback: only the files the caller provided. Zero external discovery.
    if files.len == 0:
      return GateResult(
        ok: true,
        name: "Axiom nim check gate",
        stdout: "",
        stderr: "",
        duration: getTime() - start
      )
    var targets: seq[string]
    for f in files:
      if f.endsWith(".nim") and fileExists(f):
        targets.add(f)
    if targets.len == 0:
      return GateResult(
        ok: true,
        name: "Axiom nim check gate",
        stdout: "",
        stderr: "",
        duration: getTime() - start
      )

    # Verification unit is per-file; only execution is parallelized
    # (runPerFileCheck owns unique per-file --nimcache isolation, runBatch is
    # the bounded-parallel scheduler). Incremental == exactly the caller's
    # files. Aggregate mode remains exclusive to grmExhaustive.
    when declared(setControlCHook):
      setControlCHook(cleanupAggregator)
    when defined(posix):
      discard signal(SIGTERM, sigtermAggregatorHandler)

    let r = runPerFileCheck(repoRoot, targets, maxJobs)
    return GateResult(
      ok: r.ok,
      name: "Axiom nim check gate",
      stdout: r.log,
      stderr: "",
      duration: getTime() - start
    )

  of grmExhaustive:
    let cacheDir = repoRoot / "build" / "nimcache"
    try:
      createDir(cacheDir)
    except CatchableError:
      discard  # axiom:best-effort(ioboundary catch)
    cleanupOldAggregators(cacheDir)

    defer: cleanupAggregator()
    when declared(setControlCHook):
      setControlCHook(cleanupAggregator)
    when defined(posix):
      discard signal(SIGTERM, sigtermAggregatorHandler)

    var logOutput = ""
    var allOk = true

    # --- src/ aggregator ----------------------------------------------------
    let srcFiles = collectNimFiles(repoRoot, "src")
    if srcFiles.len > 0:
      let (ok, aggLog) = runAggregatedSrcCheck(
        repoRoot, srcFiles, maxJobs, cacheDir, "axiom_gate_aggregator_src_"
      )
      allOk = allOk and ok
      logOutput.add(aggLog)

    # --- tests/gateway per-file ---------------------------------------------
    let testFiles = collectNimFiles(repoRoot, "tests" / "gateway").filterIt(
      it.endsWith("_test.nim")
    )
    if testFiles.len > 0:
      let r = runPerFileCheck(repoRoot, testFiles, maxJobs)
      allOk = allOk and r.ok
      logOutput.add(r.log)

    return GateResult(
      ok: allOk,
      name: "Axiom nim check gate",
      stdout: logOutput,
      stderr: "",
      duration: getTime() - start
    )

proc runNimCheckDetailed*(repoRoot: string; mode: GateRunMode; maxJobs: int;
                          files: seq[string] = @[]): tuple[ok: bool; failingFiles: seq[string]; duration: Duration] {.axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect].} =
  ## Thin wrapper around runNimCheck for consumers that need the detailed tuple API.
  let gr = runNimCheck(repoRoot, mode, maxJobs, files)
  result = (ok: gr.ok, failingFiles: @[], duration: gr.duration)

