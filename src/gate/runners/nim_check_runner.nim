        if not seenPerFile.contains(f):
          seenPerFile.incl(f)
          uniquePerFile.add(f)
      if uniquePerFile.len > 0:
        logOutput.add("\n[Per-file check] " & $uniquePerFile.len &
                      " module(s) excluded from aggregator\n")
        let r = runPerFileCheck(repoRoot, uniquePerFile, maxJobs)
        allOk = allOk and r.ok
        logOutput.add(r.log)

    if otherTargets.len > 0:
      let r = runPerFileCheck(repoRoot, otherTargets, maxJobs)
      allOk = allOk and r.ok
      logOutput.add(r.log)

    return GateResult(ok: allOk, name: "Axiom nim check gate",
                      stdout: logOutput, stderr: "", duration: getTime() - start)

  of grmExhaustive:
