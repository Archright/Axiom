# ── Debt CT: Pure helpers ─────────────────────────────────────────────────────
func isDigitStr(s: string): bool =
  if s.len == 0: return false
  for c in s:
    if c notin {'0'..'9'}: return false
  true

func matchesDebtId(s: string): bool =
  ## Accept both DEBT#NNN (theater registry) and DEBT-CI#NNN (CI pipeline) IDs.
  if s.startsWith("DEBT-CI#") and s.len > 8:
    return isDigitStr(s[8..^1])
  s.startsWith("DEBT#") and isDigitStr(s[5..^1])

func matchesSeverity(s: string): bool =
  s in ["critical", "high", "medium", "low", "low-medium"]

func statusVocabulary*(schema: JsonNode): seq[string] =
  ## DEBT#512: data/debt_schema.json definitions.statusEnum.enum is the single
  ## authority for the debt status vocabulary. An empty result means the
  ## authority could not be established — callers fail closed, never guess.
  let enumNode = schema{"definitions"}{"statusEnum"}{"enum"}
  if enumNode.isNil or enumNode.kind != JArray: return @[]
  for value in enumNode:
    if value.kind != JString or value.getStr().len == 0: return @[]
    result.add(value.getStr())

func matchesStatus*(s: string; canonical: openArray[string]): bool =
  ## Accept exactly the schema-canonical vocabulary (DEBT#512).
  s in canonical

func jsonStr(node: JsonNode): string =
  if node == nil or node.kind != JString: "" else: node.getStr("")

func fileMatchesRef(filePath, refPath: string): bool =
  if filePath.len == 0 or refPath.len == 0: return false
  filePath == refPath or filePath.endsWith(refPath) or refPath.endsWith(filePath) or
    filePath.contains(refPath) or refPath.contains(filePath)

proc validateArchitectureDebtImpl(content: string): seq[string] =
  result = @[]
  var json: JsonNode
  try: json = parseJson(content)
  except CatchableError: result.add("Invalid JSON"); return
  if not json.hasKey("version"): result.add("Missing 'version'")
  elif json["version"].kind != JInt: result.add("'version' must be int")
  if not json.hasKey("entries"): result.add("Missing 'entries'")
  elif json["entries"].kind != JArray: result.add("'entries' must be array")
  else:
    let entries = json["entries"]
    for idx in 0 ..< entries.len:
      let entry = entries[idx]
      if entry{"file"}.kind != JString or entry{"file"}.getStr().len == 0:
        result.add("entry[" & $idx & "].file: must be non-empty string")
      if entry{"count"}.kind != JInt or entry{"count"}.getInt() <= 0:
        result.add("entry[" & $idx & "].count: must be int > 0")
      if entry{"firstSeen"}.kind != JString:
        result.add("entry[" & $idx & "].firstSeen: must be string")
      if entry{"lastSeen"}.kind != JString:
        result.add("entry[" & $idx & "].lastSeen: must be string")
      let hasNewHashFields = (entry{"rawContentHash"} != nil and entry{"rawContentHash"}.kind == JString) or (entry{"canonicalSyntaxHash"} != nil and entry{"canonicalSyntaxHash"}.kind == JString)
      let hasLegacyHash = entry{"contentHash"} != nil and entry{"contentHash"}.kind == JString
      if not hasNewHashFields and not hasLegacyHash:
        result.add("entry[" & $idx & "]: missing rawContentHash/canonicalSyntaxHash")
      elif hasNewHashFields:
        let filePath = entry{"file"}.getStr()
        if fileExists(filePath):
          let (rawHash, canonicalHash) = getExpectedHashes(filePath)
          if hasNewHashFields and entry{"rawContentHash"} != nil and entry{"rawContentHash"}.kind == JString:
            if entry{"rawContentHash"}.getStr() != rawHash:
              result.add("entry[" & $idx & "].rawContentHash mismatch")
          if hasNewHashFields and entry{"canonicalSyntaxHash"} != nil and entry{"canonicalSyntaxHash"}.kind == JString:
            if entry{"canonicalSyntaxHash"}.getStr() != canonicalHash:
              result.add("entry[" & $idx & "].canonicalSyntaxHash mismatch")

proc validateDebtRegistryImpl*(content: string;
                               canonicalStatuses: openArray[string]): seq[string] =
  result = @[]
  var json: JsonNode
  try: json = parseJson(content)
  except CatchableError: result.add("Invalid JSON"); return
  if not json.hasKey("entries"): result.add("Missing 'entries'"); return
  if json["entries"].kind != JArray: result.add("'entries' must be array"); return
  for idx in 0 ..< json["entries"].len:
    let entry = json["entries"][idx]
    let id = entry{"id"}
    if id.kind != JString or not matchesDebtId(id.getStr()):
      result.add("entry[" & $idx & "].id: invalid format")
    if not matchesSeverity(jsonStr(entry{"severity"})):
      result.add("entry[" & $idx & "].severity: invalid")
    if not matchesStatus(jsonStr(entry{"status"}), canonicalStatuses):
      result.add("entry[" & $idx & "].status: invalid")

proc validateDebtLedgerImpl(content: string): seq[string] =
  result = @[]
  var json: JsonNode
  try: json = parseJson(content)
  except CatchableError: result.add("Invalid JSON"); return
  if not json.hasKey("version"): result.add("Missing 'version'")
  elif json["version"].kind != JString: result.add("'version' must be string")
  if not json.hasKey("records"): result.add("Missing 'records'")
  elif json["records"].kind != JArray: result.add("'records' must be array")

# ── Debt Reduction metrics ────────────────────────────────────────────────────
type
  DebtMetrics = object
    forwardingStubs: int
    isMainModuleInCore: int
    staleGeneratedPbtFiles: int
    nimtryViolationCount: int
    nimtryActiveViolations: int

proc countForwardingStubs(repoRoot: string): int =
  let coreRoot = repoRoot / CoreRootRel
  if not dirExists(coreRoot): return 0
  var nimFiles: seq[string] = @[]
  for path in walkDirRec(coreRoot, yieldFilter = {pcFile}):
    if path.endsWith(".nim"): nimFiles.add(path)
  for fullPath in nimFiles:
    try:
      let text = readFile(fullPath)
      let lines = text.splitLines()
      var head = ""
      for i in 0 ..< min(10, lines.len):
        if i > 0: head.add("\n")
        head.add(lines[i])
      for marker in ForwardingMarkers:
        if marker in head: inc result; break
    except CatchableError: discard  # axiom:best-effort(ioboundary catch)

proc countIsMainModuleInCore(repoRoot: string): int =
  let coreRoot = repoRoot / CoreRootRel
  if not dirExists(coreRoot): return 0
  let pattern = re(IsMainModuleReStr)
  for path in walkDirRec(coreRoot, yieldFilter = {pcFile}):
    if path.endsWith(".nim"):
      try:
        if readFile(path).contains(pattern): inc result
      except CatchableError: discard  # axiom:best-effort(ioboundary catch)

proc countStaleGeneratedPbt(repoRoot: string): int =
  let pbtDir = repoRoot / GeneratedPbtRel
  if not dirExists(pbtDir): return 0
  for path in walkDirRec(pbtDir, yieldFilter = {pcFile}):
    if path.endsWith(".nim"): inc result

proc countNimtryViolations(repoRoot: string): int =
  ## The total recorded in nimtry's v2 fingerprint anchor. Under the v2
  ## protocol nimtry gates on fingerprint membership, so this is the anchor's
  ## recorded total, not a threshold — the ratchet cap lives in
  ## data/debt_reduction_baseline.json.
  let path = repoRoot / NimtryBaselineRelPath
  if not fileExists(path): return 0
  try: parseJson(readFile(path))["total_violations"].getInt()
  except CatchableError: 0

proc countNimtryActiveViolations(repoRoot: string): int =
  ## Live measured violations from the nimtry run sidecar.
  ## -1 when the sidecar is absent (nimtry not run yet in this workspace), which
  ## callers treat as UNMEASURED rather than as zero.
  let path = repoRoot / "data" / "nimtry_live_count.json"
  if not fileExists(path):
    # DEBT#563: without the sidecar the reduction ratchet compares the declared
    # baseline instead of a measurement, so CI cannot observe violation growth.
    const debtMarker563 {.axiomDebt: "DEBT#563".} = true
    return -1
  try: parseJson(readFile(path))["total_violations"].getInt()
  except CatchableError: -1

proc scanDebtMetrics(repoRoot: string): DebtMetrics =
  DebtMetrics(
    forwardingStubs: countForwardingStubs(repoRoot),
    isMainModuleInCore: countIsMainModuleInCore(repoRoot),
    staleGeneratedPbtFiles: countStaleGeneratedPbt(repoRoot),
    nimtryViolationCount: countNimtryViolations(repoRoot),
    nimtryActiveViolations: countNimtryActiveViolations(repoRoot),
  )

func metricsToPairs(m: DebtMetrics): seq[(string, int)] =
  result.add(("forwarding_stubs", m.forwardingStubs))
  result.add(("isMainModule_in_core", m.isMainModuleInCore))
  result.add(("nimtry_violation_count", m.nimtryViolationCount))
  result.add(("nimtry_active_violations", m.nimtryActiveViolations))
  result.add(("stale_generated_pbt_files", m.staleGeneratedPbtFiles))

proc loadBaselineMetrics(repoRoot: string): seq[(string, int)] =
  let baselinePath = repoRoot / BaselineRelPath
  if not fileExists(baselinePath): return @[]
  try:
    let data = parseJson(readFile(baselinePath))
    let metrics = data["metrics"]
    var keys: seq[string] = @[]
    for k in metrics.keys: keys.add(k)
    keys.sort()
    for k in keys: result.add((k, metrics[k].getInt()))
  except CatchableError: result = @[]

func baselineCap(baseline: seq[(string, int)]; key: string): int =
  ## The single threshold for one metric: the `metrics` entry in
  ## data/debt_reduction_baseline.json. The ratchet comparison and every
  ## report of the cap read it through this function, so the number a log line
  ## displays is the number the gate adjudicates. A missing key caps at 0,
  ## which no measured count can satisfy.
  for (k, v) in baseline:
    if k == key: return v
  0

proc saveBaselineMetrics(repoRoot: string, metrics: seq[(string, int)]) =
  let baselinePath = repoRoot / BaselineRelPath
  let parentDir = baselinePath.parentDir()
  if not dirExists(parentDir): createDir(parentDir)
  var metricsObj = newJObject()
  for (k, v) in metrics: metricsObj[k] = newJInt(v)
  writeFile(baselinePath, $(%*{"metrics": metricsObj}) & "\n")

# ── Original: Bidirectional binding ──────────────────────────────────────────
const RegistryDispositionBinding = "registry_disposition"

type
  RegistryEntry = object
    id: string
    status: string
    binding: string
    bindingRationale: string

func isAcceptedStatus(status: string): bool =
  result = status == "accepted" or status == "exempted"

func isOpenStatus(status: string): bool =
  result = status == "open"

func isRegistryDisposition(e: RegistryEntry): bool {.raises: [].} =
  ## docs/spec/debt_registry_schema.md §10.1 — the registry entry itself is the
  ## binding medium; the {.axiomDebt.} marker requirement does not apply.
  e.binding == RegistryDispositionBinding

func hasBindingRationale(e: RegistryEntry): bool {.raises: [].} =
  ## §10.2 — registry_disposition requires a non-blank bindingRationale;
  ## blank means a BINDING-CONTRACT failure, not a silent pass.
  e.bindingRationale.strip().len > 0

proc parseRegistry(jsonPath: string): seq[RegistryEntry] =
  let content = readFile(jsonPath)
  let root = parseJson(content)
  let entriesNode = root{"entries"}
  if entriesNode.isNil or entriesNode.kind != JArray: return
  for node in entriesNode:
    let id = node{"id"}.getStr("")
    let status = node{"status"}.getStr("")
    if id.len > 0:
      result.add(RegistryEntry(
        id: id,
        status: status,
        binding: node{"binding"}.getStr(""),
        bindingRationale: node{"bindingRationale"}.getStr("")))

proc loadCanonicalStatuses*(repoRoot: string): seq[string] =
  ## DEBT#512: read the status vocabulary from its single authority
  ## (data/debt_schema.json). An empty result means the authority is
  ## unavailable; the caller fails closed instead of validating against a
  ## guessed vocabulary.
  let schemaPath = repoRoot / DebtSchemaPath
  if not fileExists(schemaPath):
    logError(GateTag, "debt_schema.json not found: " & schemaPath)
    return @[]
  try:
    result = statusVocabulary(parseJson(readFile(schemaPath)))
  except CatchableError as e:
    logError(GateTag, "debt_schema.json unreadable: " & e.msg)
    return @[]
  if result.len == 0:
    logError(GateTag, "debt_schema.json definitions.statusEnum.enum is missing, empty, or malformed")

# -- Whole-file contentHash verification (docs/spec/debt_registry_schema.md section 6) --
type
  ContentHashReport* = object
    entriesTotal*: int
    entriesWithHash*: int
    checked*: int
    skippedNoLineRange*: int
    skippedNonPlain*: int
    skippedMissingFile*: int

func isPlainRelativePath(p: string): bool =
  ## True only for a bare relative file path. Line spans (`:12-34`), multi-path
  ## prose (`;`, `|`), annotations (`(...)`), and every other non-mechanical
  ## form are rejected here and counted as a skip by the caller - a form this
  ## check cannot resolve is never treated as verified.
  if p.len == 0 or p.isAbsolute: return false
  for c in p:
    if c notin {'A'..'Z', 'a'..'z', '0'..'9', '.', '_', '-', '/'}:
      return false
  for segment in p.split('/'):
    if segment.len == 0 or segment == "." or segment == "..": return false
  true

proc validateRegistryContentHashes*(content: string; repoRoot: string):
    tuple[errors: seq[string]; report: ContentHashReport]
    {.raises: [], axiomEffect: IOEffect,
      tags: [AxiomIOEffect, IOEffect, RootEffect].} =
  ## Recompute `sha256:` over the exact file bytes for entries whose lineRange
  ## is a plain relative path naming an existing file. Function-body hashes
  ## and prose/line-span lineRanges are not mechanically resolvable here; they
  ## are counted in `report`, never assumed correct. Paths resolve against
  ## `repoRoot`, so the verdict does not depend on the caller's CWD.
  result.errors = @[]
  var json: JsonNode
  try: json = parseJson(content)
  except CatchableError:
    result.errors.add("registry: invalid JSON")
    return
  let entries = json{"entries"}
  if entries.isNil or entries.kind != JArray:
    result.errors.add("registry: missing 'entries' array")
    return
  result.report.entriesTotal = entries.len
  for idx in 0 ..< entries.len:
    let entry = entries[idx]
    let id = entry{"id"}.getStr("")
    let hashNode = entry{"contentHash"}
    if hashNode.isNil or hashNode.kind != JString or hashNode.getStr().len == 0:
      continue
    inc result.report.entriesWithHash
    let recorded = hashNode.getStr()
    let lineNode = entry{"lineRange"}
    if lineNode.isNil or lineNode.kind != JString or lineNode.getStr().len == 0:
      inc result.report.skippedNoLineRange
      continue
    let rel = lineNode.getStr()
    if not isPlainRelativePath(rel):
      inc result.report.skippedNonPlain
      continue
    let fullPath = repoRoot / rel
    if not fileExists(fullPath):
      inc result.report.skippedMissingFile
      continue
    var actual: string
    try:
      actual = computeRawContentHash(readFile(fullPath))
    except CatchableError as e:
      result.errors.add("entry[" & $idx & "] (" & id & ").contentHash unreadable: " &
        rel & ": " & e.msg)
      continue
    inc result.report.checked
    if actual != recorded:
      result.errors.add("entry[" & $idx & "] (" & id & ").contentHash mismatch: " &
        "lineRange=" & rel & " recorded=" & recorded & " actual=" & actual)

proc run(repoRoot: string): int =
  let jsonPath = repoRoot / "data" / "debt_registry.json"
  if not fileExists(jsonPath):
    logError(GateTag, "debt_registry.json not found: " & jsonPath)
    return 1

  # Step 1: Debt CT validation (merged from debt-ct-gate)
  let archPath = repoRoot / ArchitectureDebtPath
  let ledgerPath = repoRoot / DebtLedgerPath
  if fileExists(archPath) and fileExists(ledgerPath):
    let canonicalStatuses = loadCanonicalStatuses(repoRoot)
    if canonicalStatuses.len == 0:
      logError(GateTag, "status vocabulary unavailable — FAIL (fail-closed, DEBT#512)")
      return 1
    let archErrors = validateArchitectureDebtImpl(readFile(archPath))
    let registryErrors = validateDebtRegistryImpl(readFile(jsonPath), canonicalStatuses)
    let ledgerErrors = validateDebtLedgerImpl(readFile(ledgerPath))
    for e in archErrors: logWarn(GateTag, "[architecture_debt] " & e)
    for e in registryErrors: logWarn(GateTag, "[debt_registry] " & e)
    for e in ledgerErrors: logWarn(GateTag, "[debt_ledger] " & e)

  # Step 1b: Whole-file contentHash enforcement (unconditional, fail-closed).
  # docs/spec/debt_registry_schema.md section 6 binds contentHash to exact artifact
  # content; presence alone was never the contract. Only bare relative
  # lineRanges naming an existing file are mechanically recomputable - every
  # other form is counted below so the skip set is visible, never silent.
  let (hashErrors, hashReport) =
    validateRegistryContentHashes(readFile(jsonPath), repoRoot)
  logInfo(GateTag, "contentHash: " & $hashReport.checked &
    " whole-file artifact(s) verified; skipped " &
    $hashReport.skippedNoLineRange & " (no lineRange), " &
    $hashReport.skippedNonPlain & " (non-plain lineRange), " &
    $hashReport.skippedMissingFile & " (lineRange path is not a file); " &
    $hashReport.entriesWithHash & "/" & $hashReport.entriesTotal &
    " entries carry contentHash")
  if hashErrors.len > 0:
    for e in hashErrors: logError(GateTag, "[debt_registry] " & e)
    logError(GateTag, $hashErrors.len & " contentHash failure(s) - FAIL")
    return 1

  # Step 2: Debt reduction metrics (merged from debt-reduction-gate)
  var updateBaseline = false
  for arg in commandLineParams():
    if arg == "--update-baseline": updateBaseline = true; break
  let currentMetrics = scanDebtMetrics(repoRoot)
  let currentPairs = metricsToPairs(currentMetrics)
  if updateBaseline:
    saveBaselineMetrics(repoRoot, currentPairs)
    logInfo(GateTag, "Baseline updated"); return 0
  let baseline = loadBaselineMetrics(repoRoot)
  for (key, value) in currentPairs:
    let base = baselineCap(baseline, key)
    if value > base:
      let isDevMode = (not defined(release)) or getAxiomEnv(evDevMode) == "1"
      if isDevMode:
        logWarn(GateTag, "WARN (dev-mode): " & key & " increased (" & $value & " > " & $base & ")")
      else:
        logError(GateTag, "FAIL: " & key & " increased (" & $value & " > " & $base & ")")
        return 1

  # Step 2b: an absent nimtry measurement is UNKNOWN, not green (DEBT#563).
  # The sidecar exists only after a live `bin/nimtry src/` run (gitignored,
  # .gitignore:422). The cap printed here is baselineCap's, the same value
  # Step 2 compared `nimtry_active_violations` against.
  let active = currentMetrics.nimtryActiveViolations
  let cap = baselineCap(baseline, "nimtry_active_violations")
  if active < 0:
    logError(GateTag, "nimtry — Active Violations: UNMEASURED / Cap: " & $cap)
  else:
    logInfo(GateTag, "nimtry — Active Violations: " & $active & " / Cap: " & $cap)

  # Step 3: Parse registry (original)
  let entries = parseRegistry(jsonPath)
  var openIds: seq[string]
  var acceptedIds: seq[string]
  var registryDispositionIds: HashSet[string]
  var markerBoundOpenCount = 0
  var registryBoundCount = 0
  for e in entries:
    if isOpenStatus(e.status):
      openIds.add(e.id)
      if isRegistryDisposition(e):
        registryDispositionIds.incl(e.id)
        if hasBindingRationale(e): inc registryBoundCount
      else: inc markerBoundOpenCount
    elif isAcceptedStatus(e.status): acceptedIds.add(e.id)

  logInfo(GateTag, "Registry: " & $entries.len & " entries (" &
    $openIds.len & " open, " & $acceptedIds.len & " accepted)")
  logInfo(GateTag, "Open: " & $markerBoundOpenCount & " marker-bound, " &
    $registryBoundCount & " registry_disposition-bound (rationale verified)")

  # Step 4: Scan code for pragmas
  let scanned = scanDebtPragmas(repoRoot / "src")
  var codeIds: HashSet[string]
  for s in scanned: codeIds.incl(s.id)
  logInfo(GateTag, "Code: " & $codeIds.len & " {.axiomDebt.} markers found")

  # Step 5: Bidirectional binding check
  var failures: seq[string]
  var warnings: seq[string]
  for id in openIds:
    if id in registryDispositionIds: continue
    if id notin codeIds:
      failures.add("STALE: " & id & " is open in registry but has no {.axiomDebt.} marker")
  for e in entries:
    if isOpenStatus(e.status) and isRegistryDisposition(e) and
        not hasBindingRationale(e):
      failures.add("BINDING-CONTRACT: " & e.id &
        " uses registry_disposition without bindingRationale")
  for id in acceptedIds:
    if id notin codeIds:
      warnings.add("ORPHAN-ACCEPTED: " & id & " is accepted but has no marker")
  var allRegistryIds: HashSet[string]
  for e in entries: allRegistryIds.incl(e.id)
  for s in scanned:
    if s.id notin allRegistryIds:
      warnings.add("ORPHAN-CODE: " & s.id & " (" & s.file & ":" & $s.line & ")")

  if active < 0:
    failures.add("UNMEASURED: nimtry_active_violations — " &
      "missing evidence is not a valid empty set (DEBT#563 fail-closed)")
  for w in warnings: logWarn(GateTag, w)
  for f in failures: logError(GateTag, f)
  if failures.len > 0:
    logError(GateTag, $failures.len & " blocking debt finding(s) — FAIL")
    return 1
  logInfo(GateTag, "All " & $openIds.len & " open debts have code markers. PASS.")
  return 0

when isMainModule:
  # Root resolution is CWD-independent: AXIOM_ROOT wins, else the `.axiom_root`
  # anchor is walked up from the binary's own location (not the caller's CWD).
  # The whole-file contentHash check resolves registry lineRange paths against
  # this same root.
  quit(run(findRepoRoot()))
