# ── Debt CT: Pure helpers ─────────────────────────────────────────────────────
func isDigitStr(s: string): bool =
  if s.len == 0: return false
  for c in s:
    if c notin {'0'..'9'}: return false
  true

func matchesDebtId(s: string): bool =
  ## Accept both DEBT#NNN (theater registry) and DEBT-CI#NNN (CI pipeline) IDs.
  if s.startsWith("DEBT-CI#") and s.len > 8:
    return isDigitStr(s[8..^1])
  s.startsWith("DEBT#") and isDigitStr(s[5..^1])

func matchesSeverity(s: string): bool =
  s in ["critical", "high", "medium", "low", "low-medium"]

func matchesStatus(s: string): bool =
  s in ["open", "closed", "deferred", "resolved"]

func jsonStr(node: JsonNode): string =
  if node == nil or node.kind != JString: "" else: node.getStr("")

func fileMatchesRef(filePath, refPath: string): bool =
  if filePath.len == 0 or refPath.len == 0: return false
  filePath == refPath or filePath.endsWith(refPath) or refPath.endsWith(filePath) or
    filePath.contains(refPath) or refPath.contains(filePath)

proc validateArchitectureDebtImpl(content: string): seq[string] =
  result = @[]
  var json: JsonNode
  try: json = parseJson(content)
  except CatchableError: result.add("Invalid JSON"); return
  if not json.hasKey("version"): result.add("Missing 'version'")
  elif json["version"].kind != JInt: result.add("'version' must be int")
  if not json.hasKey("entries"): result.add("Missing 'entries'")
  elif json["entries"].kind != JArray: result.add("'entries' must be array")
  else:
    let entries = json["entries"]
    for idx in 0 ..< entries.len:
      let entry = entries[idx]
      if entry{"file"}.kind != JString or entry{"file"}.getStr().len == 0:
        result.add("entry[" & $idx & "].file: must be non-empty string")
      if entry{"count"}.kind != JInt or entry{"count"}.getInt() <= 0:
        result.add("entry[" & $idx & "].count: must be int > 0")
      if entry{"firstSeen"}.kind != JString:
        result.add("entry[" & $idx & "].firstSeen: must be string")
      if entry{"lastSeen"}.kind != JString:
        result.add("entry[" & $idx & "].lastSeen: must be string")
      let hasNewHashFields = (entry{"rawContentHash"} != nil and entry{"rawContentHash"}.kind == JString) or (entry{"canonicalSyntaxHash"} != nil and entry{"canonicalSyntaxHash"}.kind == JString)
      let hasLegacyHash = entry{"contentHash"} != nil and entry{"contentHash"}.kind == JString
      if not hasNewHashFields and not hasLegacyHash:
        result.add("entry[" & $idx & "]: missing rawContentHash/canonicalSyntaxHash")
      elif hasNewHashFields:
        let filePath = entry{"file"}.getStr()
        if fileExists(filePath):
          let (rawHash, canonicalHash) = getExpectedHashes(filePath)
          if hasNewHashFields and entry{"rawContentHash"} != nil and entry{"rawContentHash"}.kind == JString:
            if entry{"rawContentHash"}.getStr() != rawHash:
              result.add("entry[" & $idx & "].rawContentHash mismatch")
          if hasNewHashFields and entry{"canonicalSyntaxHash"} != nil and entry{"canonicalSyntaxHash"}.kind == JString:
            if entry{"canonicalSyntaxHash"}.getStr() != canonicalHash:
              result.add("entry[" & $idx & "].canonicalSyntaxHash mismatch")

proc validateDebtRegistryImpl(content: string): seq[string] =
  result = @[]
  var json: JsonNode
  try: json = parseJson(content)
  except CatchableError: result.add("Invalid JSON"); return
  if not json.hasKey("entries"): result.add("Missing 'entries'"); return
  if json["entries"].kind != JArray: result.add("'entries' must be array"); return
  for idx in 0 ..< json["entries"].len:
    let entry = json["entries"][idx]
    let id = entry{"id"}
    if id.kind != JString or not matchesDebtId(id.getStr()):
      result.add("entry[" & $idx & "].id: invalid format")
    if not matchesSeverity(jsonStr(entry{"severity"})):
      result.add("entry[" & $idx & "].severity: invalid")
    if not matchesStatus(jsonStr(entry{"status"})):
      result.add("entry[" & $idx & "].status: invalid")

proc validateDebtLedgerImpl(content: string): seq[string] =
  result = @[]
  var json: JsonNode
  try: json = parseJson(content)
  except CatchableError: result.add("Invalid JSON"); return
  if not json.hasKey("version"): result.add("Missing 'version'")
  elif json["version"].kind != JString: result.add("'version' must be string")
  if not json.hasKey("records"): result.add("Missing 'records'")
  elif json["records"].kind != JArray: result.add("'records' must be array")

# ── Debt Reduction metrics ────────────────────────────────────────────────────
type
  DebtMetrics = object
    forwardingStubs: int
    isMainModuleInCore: int
    staleGeneratedPbtFiles: int
    nimtryViolationCount: int
    nimtryActiveViolations: int

proc countForwardingStubs(repoRoot: string): int =
  let coreRoot = repoRoot / CoreRootRel
  if not dirExists(coreRoot): return 0
  var nimFiles: seq[string] = @[]
  for path in walkDirRec(coreRoot, yieldFilter = {pcFile}):
    if path.endsWith(".nim"): nimFiles.add(path)
  for fullPath in nimFiles:
    try:
      let text = readFile(fullPath)
      let lines = text.splitLines()
      var head = ""
      for i in 0 ..< min(10, lines.len):
        if i > 0: head.add("\n")
        head.add(lines[i])
      for marker in ForwardingMarkers:
        if marker in head: inc result; break
    except CatchableError: discard  # axiom:best-effort(ioboundary catch)

proc countIsMainModuleInCore(repoRoot: string): int =
  let coreRoot = repoRoot / CoreRootRel
  if not dirExists(coreRoot): return 0
  let pattern = re(IsMainModuleReStr)
  for path in walkDirRec(coreRoot, yieldFilter = {pcFile}):
    if path.endsWith(".nim"):
      try:
        if readFile(path).contains(pattern): inc result
      except CatchableError: discard  # axiom:best-effort(ioboundary catch)

proc countStaleGeneratedPbt(repoRoot: string): int =
  let pbtDir = repoRoot / GeneratedPbtRel
  if not dirExists(pbtDir): return 0
  for path in walkDirRec(pbtDir, yieldFilter = {pcFile}):
    if path.endsWith(".nim"): inc result

proc countNimtryViolations(repoRoot: string): int =
  let path = repoRoot / NimtryBaselineRelPath
  if not fileExists(path): return 0
  try: parseJson(readFile(path))["total_violations"].getInt()
  except CatchableError: 0

proc countNimtryActiveViolations(repoRoot: string): int =
  ## Live measured violations from the nimtry run sidecar.
  ## Falls back to the baseline cap when the sidecar is absent (nimtry not
  ## run yet in this workspace) — the fallback is labeled by callers.
  let path = repoRoot / "data" / "nimtry_live_count.json"
  if not fileExists(path): return -1
  try: parseJson(readFile(path))["total_violations"].getInt()
  except CatchableError: -1

proc scanDebtMetrics(repoRoot: string): DebtMetrics =
  DebtMetrics(
    forwardingStubs: countForwardingStubs(repoRoot),
    isMainModuleInCore: countIsMainModuleInCore(repoRoot),
    staleGeneratedPbtFiles: countStaleGeneratedPbt(repoRoot),
    nimtryViolationCount: countNimtryViolations(repoRoot),
    nimtryActiveViolations: countNimtryActiveViolations(repoRoot),
  )

func metricsToPairs(m: DebtMetrics): seq[(string, int)] =
  result.add(("forwarding_stubs", m.forwardingStubs))
  result.add(("isMainModule_in_core", m.isMainModuleInCore))
  result.add(("nimtry_violation_count", m.nimtryViolationCount))
  result.add(("nimtry_active_violations", m.nimtryActiveViolations))
  result.add(("stale_generated_pbt_files", m.staleGeneratedPbtFiles))

proc loadBaselineMetrics(repoRoot: string): seq[(string, int)] =
  let baselinePath = repoRoot / BaselineRelPath
  if not fileExists(baselinePath): return @[]
  try:
    let data = parseJson(readFile(baselinePath))
    let metrics = data["metrics"]
    var keys: seq[string] = @[]
    for k in metrics.keys: keys.add(k)
    keys.sort()
    for k in keys: result.add((k, metrics[k].getInt()))
  except CatchableError: result = @[]

proc saveBaselineMetrics(repoRoot: string, metrics: seq[(string, int)]) =
  let baselinePath = repoRoot / BaselineRelPath
  let parentDir = baselinePath.parentDir()
  if not dirExists(parentDir): createDir(parentDir)
  var metricsObj = newJObject()
  for (k, v) in metrics: metricsObj[k] = newJInt(v)
  writeFile(baselinePath, $(%*{"metrics": metricsObj}) & "\n")

# ── Original: Bidirectional binding ──────────────────────────────────────────
type
  RegistryEntry = object
    id: string
    status: string

func isAcceptedStatus(status: string): bool =
  result = status == "accepted" or status == "exempted"

func isOpenStatus(status: string): bool =
  result = status == "open"

proc parseRegistry(jsonPath: string): seq[RegistryEntry] =
  let content = readFile(jsonPath)
  let root = parseJson(content)
  let entriesNode = root{"entries"}
  if entriesNode.isNil or entriesNode.kind != JArray: return
  for node in entriesNode:
    let id = node{"id"}.getStr("")
    let status = node{"status"}.getStr("")
    if id.len > 0: result.add(RegistryEntry(id: id, status: status))

proc run(repoRoot: string): int =
  let jsonPath = repoRoot / "data" / "debt_registry.json"
  if not fileExists(jsonPath):
    logError(GateTag, "debt_registry.json not found: " & jsonPath)
    return 1

  # Step 1: Debt CT validation (merged from debt-ct-gate)
  let archPath = repoRoot / ArchitectureDebtPath
  let ledgerPath = repoRoot / DebtLedgerPath
  if fileExists(archPath) and fileExists(ledgerPath):
    let archErrors = validateArchitectureDebtImpl(readFile(archPath))
    let registryErrors = validateDebtRegistryImpl(readFile(jsonPath))
    let ledgerErrors = validateDebtLedgerImpl(readFile(ledgerPath))
    for e in archErrors: logWarn(GateTag, "[architecture_debt] " & e)
    for e in registryErrors: logWarn(GateTag, "[debt_registry] " & e)
    for e in ledgerErrors: logWarn(GateTag, "[debt_ledger] " & e)

  # Step 2: Debt reduction metrics (merged from debt-reduction-gate)
  var updateBaseline = false
  for arg in commandLineParams():
    if arg == "--update-baseline": updateBaseline = true; break
  let currentMetrics = scanDebtMetrics(repoRoot)
  let currentPairs = metricsToPairs(currentMetrics)
  if updateBaseline:
    saveBaselineMetrics(repoRoot, currentPairs)
    logInfo(GateTag, "Baseline updated"); return 0
  let baseline = loadBaselineMetrics(repoRoot)
  for (key, value) in currentPairs:
    var base = 0
    for (k, v) in baseline:
      if k == key: base = v; break
    if value > base:
      let isDevMode = (not defined(release)) or getAxiomEnv(evDevMode) == "1"
      if isDevMode:
        logWarn(GateTag, "WARN (dev-mode): " & key & " increased (" & $value & " > " & $base & ")")
      else:
        logError(GateTag, "FAIL: " & key & " increased (" & $value & " > " & $base & ")")
        return 1

  # Step 2b: Active vs Historical Cap disambiguation (nimtry)
  let active = currentMetrics.nimtryActiveViolations
  let cap = currentMetrics.nimtryViolationCount
  if active >= 0:
    logInfo(GateTag, "nimtry — Active Violations: " & $active &
      " / Historical Baseline Cap: " & $cap)
  else:
    logInfo(GateTag, "nimtry — Active Violations: (unmeasured; nimtry not run yet) " &
      "/ Historical Baseline Cap: " & $cap)

  # Step 3: Parse registry (original)
  let entries = parseRegistry(jsonPath)
  var openIds: seq[string]
  var acceptedIds: seq[string]
  for e in entries:
    if isOpenStatus(e.status): openIds.add(e.id)
    elif isAcceptedStatus(e.status): acceptedIds.add(e.id)

  logInfo(GateTag, "Registry: " & $entries.len & " entries (" &
    $openIds.len & " open, " & $acceptedIds.len & " accepted)")

  # Step 4: Scan code for pragmas
  let scanned = scanDebtPragmas(repoRoot / "src")
  var codeIds: HashSet[string]
  for s in scanned: codeIds.incl(s.id)
  logInfo(GateTag, "Code: " & $codeIds.len & " {.axiomDebt.} markers found")

  # Step 5: Bidirectional binding check
  var failures: seq[string]
  var warnings: seq[string]
  for id in openIds:
    if id notin codeIds:
      failures.add("STALE: " & id & " is open in registry but has no {.axiomDebt.} marker")
  for id in acceptedIds:
    if id notin codeIds:
      warnings.add("ORPHAN-ACCEPTED: " & id & " is accepted but has no marker")
  var allRegistryIds: HashSet[string]
  for e in entries: allRegistryIds.incl(e.id)
  for s in scanned:
    if s.id notin allRegistryIds:
      warnings.add("ORPHAN-CODE: " & s.id & " (" & s.file & ":" & $s.line & ")")

  for w in warnings: logWarn(GateTag, w)
  for f in failures: logError(GateTag, f)
  if failures.len > 0:
    logError(GateTag, $failures.len & " stale debt(s) — FAIL"); return 1
  logInfo(GateTag, "All " & $openIds.len & " open debts have code markers. PASS.")
  return 0

when isMainModule:
  let repoRoot = getCurrentDir()
  quit(run(repoRoot))
