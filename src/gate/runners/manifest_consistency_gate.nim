## Manifest Consistency Gate
##
## Validates that the per-gate JSON files in ``src/gate/manifest.d/`` stay in
## sync with actual runner files and binaries.  The monolithic
## ``gate_manifest.json`` has been replaced by one JSON object per gate in
## ``manifest.d/``; this gate scans the directory, parses each file, and runs
## the same consistency checks the old single-file path performed:
##   1. ``manifest.d/`` is readable and contains at least one gate file
##   2. The ``_index.json`` (a plain-text, newline-separated list of gate IDs,
##      one per line, generated by ``tools/sync_topology.nim`` via
##      ``sorted.join("\n")``) matches the names of the JSON files on disk
##   3. Each gate file is valid JSON with the required schema fields
##   4. Each gate satisfies schema (required fields, enums, types)
##   5. Each manifest gate with ``src/gate/runners/`` entry has a .nim file
##   6. Each manifest gate with ``bin/`` or ``tools/ci/`` entry warns if missing
##   7. Each standalone gate runner .nim in src/gate/runners/ has an SSOT
##      (manifest.d/*.json) registration. A runner is only treated as a
##      standalone gate by its genuine gate contract — ``registerGate`` or a
##      runnable ``when isMainModule`` binary — NOT by filename/`proc main`
##      heuristics. Helpers declared in the SSOT helper registry
##      (helper_spec.nim → generated helper_registry.nim, NOT a hardcoded
##      code list) and files imported by another registered gate are exempt.
##      SSOT registration is the single source of gate truth.
##   8. All manifest ids are unique across every file
##   9. Gates sorted by id ascending (cross-file global order)
##  10. Declaration↔call-site stage consistency (Orphan Gate Authority
##      Closure, 2026-10-08). Every declared stage must have call-site
##      evidence, and every hook call-site must be declared:
##        pre-commit / pre-push claim ⇒ the gate's binary basename appears on
##          a non-comment invocation line of the corresponding .githooks hook.
##        ci claim ⇒ a production `bin/gate_hook <stage>` invocation exists in
##          Makefile / ci/checker.mk / .github/workflows (none since the
##          ci.yml retirement fa069d610 — any ci claim therefore fails).
##        manual claim ⇒ the runner source exists and carries a run contract
##          (`when isMainModule`, `proc main(`, `proc run(`, or an in-process
##          dispatch case — the documented direct-run interfaces).
##        (reverse) hook invocation line for a gate basename ⇒ that stage
##          must be declared (under-declaration of live authority fails too).
##
## Structured verdict (--json — observer-verdict slice PR-β1, ADR-0033):
##   Passing ``--json`` emits exactly one fixed-key JSON line on stdout
##   (deterministic bytes; key order verdict → violations → judgmentKey →
##   fault_cause; the hand-built fixed-key-order rendering is ported from
##   layer_enforcement_gate.nim — a deliberate local copy, not a shared
##   module):
##     verdict: "PASS" | "WOULD-BLOCK" | "OBSERVER-FAULT"
##       PASS           no errors
##       WOULD-BLOCK    determined violations (the errors[] content) — the
##                      observed repository state would block admission
##       OBSERVER-FAULT internal gate fault (manifest enumeration failure,
##                      manifest.d empty, schema missing, schema unparseable,
##                      runners enumeration failure) — the observer itself is
##                      defective; the wrapper may attribute additional
##                      toolchain/timeout causes on top of fault_cause "gate"
##     violations: string array — the errors[] content
##     judgmentKey: gate id + enumerated inputs; the caller composes the
##                  gate|B|H judgment key on top of it
##     fault_cause: "gate" on OBSERVER-FAULT, "" otherwise
##   The exit contract is common to both modes (0/1) — OBSERVER-FAULT is
##   distinguished only by the JSON verdict field; no new exit code exists.
##   Without arguments the legacy contract is byte-identical: blank stdout,
##   stderr logs, exit 0/1 (Makefile check-manifest-consistency consumes the
##   exit code only).

