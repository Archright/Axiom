const
  GateTag = "[manifest-consistency]"
  ManifestDir = "src/gate/manifest.d"
  IndexPath = ManifestDir & "/_index.json"
  SchemaPath = "src/gate/gate_manifest.schema.json"
  RunnersDir = "src/gate/runners"

  ## --json judgmentKey: gate id + the inputs this gate reads. The caller
  ## (observation wrapper) composes the full gate|B|H key on top of it.
  JudgmentKey = "manifest-consistency-gate" &
                "|manifest=" & ManifestDir &
                "|schema=" & SchemaPath &
                "|runners=" & RunnersDir

  RequiredFields = ["id", "name", "layer", "entry", "stages", "weight"]
  ValidLayers = ["meta", "functional"]
  ValidStages = ["pre-commit", "pre-push", "manual", "ci"]
  ValidWeights = ["light", "medium", "heavy"]

var
  errors: seq[string]
  warnings: seq[string]
  jsonMode: bool

proc fail(msg: string) {.raises: [].} =
  errors.add(GateTag & " FAIL — " & msg)

proc warn(msg: string) {.raises: [].} =
  warnings.add(GateTag & " WARN — " & msg)

func jsonEscape(s: string): string {.raises: [].} =
  ## JSON string escaping — deliberate local copy of layer_enforcement_gate's
  ## jsonEscape (the fixed-key deterministic-bytes rendering pattern is ported
  ## per the observer-verdict slice contract; not a shared module).
  result = "\""
  for c in s:
    case c
    of '"': result.add("\\\"")
    of '\\': result.add("\\\\")
    of '\n': result.add("\\n")
    of '\r': result.add("\\r")
    of '\t': result.add("\\t")
    else: result.add(c)
  result.add("\"")

proc renderVerdictJson(verdict, faultCause: string): string =
  ## Hand-built JSON with fixed key order — deterministic bytes for identical
  ## input (std/json object fields are hash-ordered, which is not). Same
  ## pattern as layer_enforcement_gate.renderJson; the key set is the
  ## observer-verdict contract (verdict, violations, judgmentKey, fault_cause).
  result = "{"
  result.add("\"verdict\": " & jsonEscape(verdict))
  result.add(", \"violations\": [")
  for i, v in errors:
    if i > 0: result.add(", ")
    result.add(jsonEscape(v))
  result.add("]")
  result.add(", \"judgmentKey\": " & jsonEscape(JudgmentKey))
  result.add(", \"fault_cause\": " & jsonEscape(faultCause))
  result.add("}")

proc emitVerdictJson(verdict, faultCause: string) =
  ## --json contract: exactly one fixed-key JSON line on stdout.
  stdout.writeLine(renderVerdictJson(verdict, faultCause))

func isHelperModule(filename: string): bool =
  ## SSOT-driven helper check: a runner is exempt from Check 6 only if it is
  ## declared in the generated helper registry (the deterministic analog of
  ## `sync_topology.nim` → `helper_registry.nim` from `helper_spec.nim`).
  for m in HelperRegistry:
    if filename == m:
      return true
  false

func fileContainsPattern(content, pattern: string): bool =
  ## Simple substring check — good enough for structural markers.
  content.contains(pattern)

func fileHasGateSignals(content, filename: string): bool =
  ## Genuine standalone-gate contract: a runnable binary carrying
  ## ``when isMainModule``.  This is the ONLY signal used — the SSOT
  ## (manifest.d/*.json) decides what is a gate, and a runner is flagged
  ## only if it is a real executable gate that is missing its registration.
  ## Filename patterns (e.g. ``*_gate.nim``) and bare ``proc main`` markers
  ## are deliberately NOT used: they false-positive on helper modules.
  fileContainsPattern(content, "when isMainModule")

func normalizeSeparator(s: string): string =
  ## Replace ``-`` with ``_`` so that ``architecture-guard`` matches
  ## ``architecture_guard``.
  result = s
  for i in 0 ..< result.len:
    if result[i] == '-':
      result[i] = '_'

proc manifestEntryMatchesFile(entry, filename: string): bool =
  ## Check whether a manifest entry path refers to (or was compiled from) the
  ## given runner file.  Matching is exact-only (no containment heuristics):
  ## both sides are normalized (- → _, drop ".nim", take basename) and must
  ## be equal.  Suffix-stripped match (bin/nimtry ↔ nimtry_gate.nim) handles
  ## compiled-binary cross-references.
  let baseName = filename[0 .. ^5]  # strip ".nim"
  var entryBasename = entry.extractFilename()
  if entryBasename.endsWith(".nim"):
    entryBasename = entryBasename[0 .. ^5]
  let normBase = baseName.normalizeSeparator()
  let normEntry = entryBasename.normalizeSeparator()

  # Exact match: entry path equals the runner source path
  if entry == RunnersDir & "/" & baseName:
    return true

  # Normalized basename match (handles - vs _ differences and .nim extension)
  if normBase == normEntry:
    return true

  # Suffix-stripped match: bin/nimtry ↔ nimtry_gate.nim
  if normBase.endsWith("_gate") and normEntry == normBase[0 .. ^6]:
    return true

  false

proc validateGateEntry(entry: JsonNode, index: int, sourceFile: string) =
  ## Validate a single gate entry against schema requirements.
  let id = if entry.hasKey("id"): entry["id"].getStr() else: "<missing@" & $index & ">"
  let src = " (" & sourceFile & ")"

  # Check required fields
  for field in RequiredFields:
    if not entry.hasKey(field):
      fail("gate[" & $index & "] (id=" & id & ") missing required field: " & field & src)

  # Validate layer enum
  if entry.hasKey("layer"):
    let layer = entry["layer"].getStr()
    if layer notin ValidLayers:
      fail("gate " & id & " has invalid layer: " & layer &
           " (expected " & ValidLayers.join("|") & ")" & src)

  # Validate weight enum
  if entry.hasKey("weight"):
    let weight = entry["weight"].getStr()
    if weight notin ValidWeights:
      fail("gate " & id & " has invalid weight: " & weight &
           " (expected " & ValidWeights.join("|") & ")" & src)

  # Validate stages array
  if entry.hasKey("stages"):
    let stages = entry["stages"]
    if stages.kind != JArray:
      fail("gate " & id & " 'stages' must be an array" & src)
    else:
      # Schema minItems: 1 — actually enforced (was latent-only before the
      # Orphan Gate Authority Closure): an entry scheduled nowhere must be
      # removed from the manifest, not declared with an empty array.
      if stages.len < 1:
        fail("gate " & id & " 'stages' must contain at least 1 stage " &
             "(minItems; remove the gate instead — DEBT#425 precedent)" & src)
      var seenStages: seq[string]
      for s in stages:
        if s.kind != JString or s.getStr() notin ValidStages:
          fail("gate " & id & " has invalid stage: " &
               (if s.kind == JString: s.getStr() else: "<non-string>") &
               " (expected one of " & ValidStages.join("|") & ")" & src)
        elif s.getStr() in seenStages:
          fail("gate " & id & " has duplicate stage: " & s.getStr() & src)
        else:
          seenStages.add(s.getStr())

  # Validate passFilenames type
  if entry.hasKey("passFilenames") and entry["passFilenames"].kind != JBool:
    fail("gate " & id & " 'passFilenames' must be a boolean" & src)

  # Validate envVars structure
  if entry.hasKey("envVars"):
    let envVars = entry["envVars"]
    if envVars.kind != JArray:
      fail("gate " & id & " 'envVars' must be an array" & src)
    else:
      for ev in envVars:
        if ev.kind != JObject or not ev.hasKey("name") or not ev.hasKey("value"):
          fail("gate " & id & " envVar entry must have 'name' and 'value' strings" & src)

  # Validate argsTemplate
  if entry.hasKey("argsTemplate"):
    let args = entry["argsTemplate"]
    if args.kind != JArray:
      fail("gate " & id & " 'argsTemplate' must be an array" & src)
    else:
      for a in args:
        if a.kind != JString:
          fail("gate " & id & " argsTemplate items must be strings" & src)

  # Validate depsDirs
  if entry.hasKey("depsDirs"):
    let deps = entry["depsDirs"]
    if deps.kind != JArray:
      fail("gate " & id & " 'depsDirs' must be an array" & src)

type
  GateRef = object
    id: string
    entry: string
    stages: seq[string]
    sourceFile: string

# ── Check 10: declaration↔call-site stage consistency ──────────────────────

const
  HookPreCommitPath = ".githooks/pre-commit"
  HookPrePushPath = ".githooks/pre-push"
  GateLaneScans = @["Makefile", "ci/checker.mk"]

func gateBinaryBasename(entry: string): string {.raises: [].} =
  ## The basename the executable is invoked as: "src/gate/runners/nim_check_gate.nim"
  ## → "nim_check_gate"; "tools/stale_cert_gate" → "stale_cert_gate". Hook and
  ## Makefile invocation lines use the underscored binary name.
  let base = entry.extractFilename()
  if base.endsWith(".nim"):
    return base[0 .. ^5]
  return base

func invocationTokens(entry: string): seq[string] {.raises: [].} =
  ## Tokens whose presence on a non-comment line signals a real invocation of
  ## this gate (the underscored binary name, with and without bin/ prefix).
  let base = gateBinaryBasename(entry)
  result = @["bin/" & base, "bin/" & base.replace("-", "_")]
  result.add(base.replace("-", "_"))

func isInvocationLine(line: string): bool {.raises: [].} =
  ## Comment lines describe history (e.g. the pre-push anti-theater removal
  ## note) — they are not call-sites.
  let s = line.strip()
  s.len > 0 and not s.startsWith("#")

proc scanInvocationLines(path: string; entry: string): int =
  ## Count non-comment lines in `path` that invoke this gate's binary.
  if not fileExists(path):
    return 0
  let content = readFile(path)
  var n = 0
  for line in content.splitLines():
    if not isInvocationLine(line):
      continue
    for tok in invocationTokens(entry):
      if line.contains(tok):
        inc n
        break
  return n

proc gateHookLaneLive(): bool {.raises: [].} =
  ## A production `bin/gate_hook <stage>` invocation exists in the lane
  ## surfaces (Makefile recipes / checker.mk / workflow run steps). Compile
  ## lines (`-o:bin/gate_hook`), artifact uploads, chmod loops and sha256
  ## provenance lines are not executions.
  var surfaces: seq[string] = @[]
  surfaces.add(GateLaneScans)
  try:
    for kind, path in walkDir(".github/workflows"):
      if kind in {pcFile, pcLinkToFile} and
         (path.endsWith(".yml") or path.endsWith(".yaml")):
        surfaces.add(path)
  except OSError as e:
    # Fail-closed: if the lane surface cannot be enumerated, ci claims are
    # unverifiable — record the error (gate fails) instead of swallowing it.
    fail("cannot enumerate .github/workflows lane surface: " & e.msg)
    return false
  for path in surfaces:
    if not fileExists(path):
      continue
    let content = block:
      try:
        readFile(path)
      except IOError as e:
        # Fail-closed: an unreadable lane surface leaves ci claims unverifiable.
        fail("cannot read lane surface " & path & ": " & e.msg)
        continue
    for line in content.splitLines():
      if line.contains("-o:bin/gate_hook") or line.contains("-o: bin/gate_hook"):
        continue
      if line.contains("sha256sum") or line.contains("chmod ") or
         line.contains("upload-artifact") or line.contains("path:"):
        continue
      if line.contains("bin/gate_hook") and isInvocationLine(line):
        # Execution = the token followed by a stage argument token.
        for suffix in [" ci", " pre-commit", " pre-push", " any-ci", " run"]:
          if line.contains("bin/gate_hook" & suffix):
            return true
  return false

proc manualRunContractHolds(entry: string): bool =
  ## Manual stage evidence: the runner source exists and carries a run
  ## contract — a standalone main (`when isMainModule` / `proc main(`), the
  ## legacy gate-runner interface (`proc run(`), or an in-process dispatch
  ## case. These are the documented direct-run interfaces of this repository.
  var candidates: seq[string] = @[]
  if entry.startsWith(RunnersDir & "/"):
    let base = if entry.endsWith(".nim"): entry[0 .. ^5] else: entry
    candidates.add(base & ".nim")
  elif entry.startsWith("bin/"):
    candidates.add(RunnersDir & "/" & gateBinaryBasename(entry) & ".nim")
    candidates.add("src/cli/" & gateBinaryBasename(entry) & ".nim")
  else:
    let base = if entry.endsWith(".nim"): entry[0 .. ^5] else: entry
    candidates.add(base & ".nim")
  for c in candidates:
    if fileExists(c):
      let content = block:
        try:
          readFile(c)
        except IOError:
          continue
      if content.contains("when isMainModule") or
         content.contains("proc main(") or content.contains("proc main*(") or
         content.contains("proc run(") or content.contains("proc run*("):
        return true
  return false

proc checkStageConsistency(allGates: seq[GateRef]) =
  ## Fail on any stage claim without call-site evidence and on any hook
  ## call-site that no manifest entry declares (recurrence guard for the
  ## orphan-gate drift class; see topology_spec.nim header note).
  let hookLaneLive = gateHookLaneLive()
  for g in allGates:
    let pcCalls = scanInvocationLines(HookPreCommitPath, g.entry)
    let ppCalls = scanInvocationLines(HookPrePushPath, g.entry)
    for stage in g.stages:
      case stage
      of "pre-commit":
        if pcCalls == 0:
          fail("gate " & g.id & " declares stage 'pre-commit' but no invocation exists in " &
               HookPreCommitPath & " (declaration without call-site = false protection claim)")
      of "pre-push":
        if ppCalls == 0:
          fail("gate " & g.id & " declares stage 'pre-push' but no invocation exists in " &
               HookPrePushPath & " (declaration without call-site = false protection claim)")
      of "ci":
        if not hookLaneLive:
          fail("gate " & g.id & " declares stage 'ci' but no production `bin/gate_hook <stage>` " &
               "invocation lane exists (retired fa069d610) — re-declare manual or restore the lane first")
      of "manual":
        if not manualRunContractHolds(g.entry):
          fail("gate " & g.id & " declares stage 'manual' but its runner has no documented " &
               "direct-run contract (standalone main / legacy run proc / in-process case)")
    # Reverse direction: live hook authority must be declared.
    if pcCalls > 0 and "pre-commit" notin g.stages:
      fail("gate " & g.id & " is invoked by " & HookPreCommitPath &
           " but does not declare stage 'pre-commit' (undeclared authority)")
    if ppCalls > 0 and "pre-push" notin g.stages:
      fail("gate " & g.id & " is invoked by " & HookPrePushPath &
           " but does not declare stage 'pre-push' (undeclared authority)")


proc main() {.axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect].} =
  # The only argv read in this gate: the --json structured-verdict flag.
  # Without arguments the legacy contract below is byte-identical.
  jsonMode = commandLineParams().contains("--json")

  # --- Discover manifest files in manifest.d/ (deterministic sorted order) ---
  var manifestFiles: seq[string] = @[]
  try:
    for kind, path in walkDir(ManifestDir):
      if kind in {pcFile, pcLinkToFile} and path.endsWith(".json"):
        manifestFiles.add(path)
  except OSError as e:
    fail("could not list manifest directory: " & ManifestDir & " (" & e.msg & ")")
    if jsonMode:
      emitVerdictJson("OBSERVER-FAULT", "gate")
    for err in errors:
      logInfo("manifest_consistency_gate", err)
    quit(1)

  manifestFiles.sort()

  if manifestFiles.len == 0:
    fail("no manifest JSON files found in " & ManifestDir)
    if jsonMode:
      emitVerdictJson("OBSERVER-FAULT", "gate")
    for err in errors:
      logInfo("manifest_consistency_gate", err)
    quit(1)

  # --- Check 1: Schema exists and is valid JSON ---
  if not fileExists(SchemaPath):
    fail("schema file not found: " & SchemaPath)
    if jsonMode:
      emitVerdictJson("OBSERVER-FAULT", "gate")
    for e in errors:
      logInfo("manifest_consistency_gate", e)
    quit(1)

  try:
    discard parseJson(readFile(SchemaPath))
  except JsonParsingError as e:
    fail("schema JSON parse error: " & e.msg)
    if jsonMode:
      emitVerdictJson("OBSERVER-FAULT", "gate")
    for err in errors:
      logInfo("manifest_consistency_gate", err)
    quit(1)

  # --- Check 2: _index.json is consistent with disk ---
  if fileExists(IndexPath):
    # _index.json is NOT JSON — it is a plain-text, newline-separated list of
    # gate IDs (one per line), generated by tools/sync_topology.nim via
    # sorted.join("\n").  Mirror all_gate_runners.nim (staticRead + splitLines +
    # strip, skipping blank lines) rather than parseJson.
    let indexRaw = try: readFile(IndexPath) except IOError: ""
    var indexEntries: seq[string] = @[]
    for line in indexRaw.splitLines():
      let stripped = line.strip()
      if stripped.len > 0:
        indexEntries.add(stripped)
    indexEntries.sort()

    # Filenames actually present on disk (excluding _index.json itself).  Each
    # gate file is named "<gate-id>.json", and _index.json lists the bare gate
    # IDs — so strip the ".json" extension to compare like-for-like.
    var diskNames: seq[string] = @[]
    for f in manifestFiles:
      let n = f.extractFilename()
      if n != "_index.json":
        diskNames.add(splitFile(n).name)  # strip ".json" -> gate id
    diskNames.sort()

    if indexEntries != diskNames:
      fail("manifest.d/_index.json is a plain-text gate-ID list (one per line), not JSON — " &
           "listing does not match manifest.d/ on disk: " &
           $indexEntries.len & " indexed vs " & $diskNames.len & " on disk")

  # --- Parse every manifest file and collect gate refs ---
  var allGates: seq[GateRef] = @[]
  var totalGateCount = 0

  for mfile in manifestFiles:
    let fname = mfile.extractFilename()

    # Skip the index file — it is a flat list, not a gate object
    if fname == "_index.json":
      continue

    var gateObj: JsonNode
    try:
      gateObj = parseJson(readFile(mfile))
    except JsonParsingError as e:
      fail("JSON parse error in " & fname & ": " & e.msg)
      continue

    if gateObj.kind != JObject:
      fail("manifest file " & fname & " must be a JSON object")
      continue

    # Each file holds a single gate object.  Validate it as entry index 0.
    validateGateEntry(gateObj, 0, fname)

    if gateObj.hasKey("id") and gateObj.hasKey("entry"):
      var declaredStages: seq[string] = @[]
      if gateObj.hasKey("stages") and gateObj["stages"].kind == JArray:
        for s in gateObj["stages"]:
          if s.kind == JString:
            declaredStages.add(s.getStr())
      allGates.add(GateRef(
        id: gateObj["id"].getStr(),
        entry: gateObj["entry"].getStr(),
        stages: declaredStages,
        sourceFile: fname
      ))
    totalGateCount.inc()

  # --- Check 8: All ids are unique across every manifest file ---
  var seenIds: seq[string]
  for g in allGates:
    if g.id in seenIds:
      fail("duplicate manifest id: " & g.id & " (in " & g.sourceFile & ")")
    seenIds.add(g.id)

  # --- Check 9: Gates sorted by id ascending (global cross-file order) ---
  for i in 1 ..< allGates.len:
    if allGates[i].id < allGates[i - 1].id:
      fail("gates not sorted by id: '" & allGates[i - 1].id & "' (" &
           allGates[i - 1].sourceFile & ") > '" & allGates[i].id & "' (" &
           allGates[i].sourceFile & ")")

  # --- Check 4: Each src/gate/runners/ entry has a .nim source file ---
  for g in allGates:
    if g.entry.startsWith(RunnersDir & "/"):
      # Some manifest entries already carry the ".nim" extension, others do
      # not — normalize so we check the actual "<name>.nim" file either way.
      let base =
        if g.entry.endsWith(".nim"): g.entry[0 .. ^5]
        else: g.entry
      let nimFile = base & ".nim"
      if not fileExists(nimFile):
        fail("missing runner file for entry: " & g.entry & " (gate: " & g.id & ")")

  # --- Check 5: Each bin/ or tools/ci/ entry should exist (warn only) ---
  for g in allGates:
    if g.entry.startsWith("bin/") or g.entry.startsWith("tools/ci/"):
      # For tools/ci/ entries the manifest holds a bare basename (no extension)
      # while the actual source is "<name>.nim" — normalize before checking.
      let checkPath =
        if g.entry.startsWith("tools/ci/") and not g.entry.endsWith(".nim"):
          g.entry & ".nim"
        else:
          g.entry
      if not fileExists(checkPath):
        warn("missing file for entry: " & g.entry & " (gate: " & g.id & ")")
      # Also verify source file exists for bin/ entries
      if g.entry.startsWith("bin/"):
        let srcName = g.id.replace("-", "_") & ".nim"
        let srcPath = "src/gate/runners/" & srcName
        if not fileExists(srcPath):
          let cliPath = "src/cli/" & srcName
          if not fileExists(cliPath):
            warn("missing source for entry: " & g.entry & " (gate: " & g.id & ") — expected " & srcPath & " or " & cliPath)

  # --- Merged from manifest-integrity: validate tests/specs/bootstrap_manifest.json ---
  block:
    let bootstrapPath = "tests/specs/bootstrap_manifest.json"
    if fileExists(bootstrapPath):
      let raw = try: readFile(bootstrapPath) except IOError: ""
      if raw.len > 0:
        let jsonData = try: parseJson(raw) except JsonParsingError: nil
        if jsonData != nil:
          let res = validateManifest(jsonData)
          if not res.ok:
            for err in res.errors:
              fail("bootstrap_manifest.json: " & err)

  # --- Check 6: Gate runner files must have manifest entries ---
  var runnerNimFiles: seq[string] = @[]
  var runnersEnumerated = true
  try:
    for kind, path in walkDir(RunnersDir):
      if kind == pcFile and path.endsWith(".nim"):
        runnerNimFiles.add(path)
  except OSError:
    runnersEnumerated = false
    fail("could not list runner directory: " & RunnersDir)

  for nimFile in runnerNimFiles:
    let filename = nimFile.extractFilename()

    # Skip helper modules per the SSOT helper registry
    if isHelperModule(filename):
      continue

    # Genuine gate contract check: only runnable binaries (`when isMainModule`)
    # are candidates. Helpers with `proc main`/`*_gate.nim` names are skipped —
    # SSOT registration is the single source of gate truth.
    let content = try: readFile(nimFile) except IOError: ""
    if not fileHasGateSignals(content, filename):
      continue

    # Check if any manifest entry covers this file
    var found = false
    for g in allGates:
      if manifestEntryMatchesFile(g.entry, filename):
        found = true
        break

    if not found:
      fail("missing manifest entry for runner: " & nimFile)

  # --- Check 10: declaration↔call-site stage consistency ---
  checkStageConsistency(allGates)

  # --- Report ---
  # Structured verdict (--json): runners-enumeration failure is an
  # OBSERVER-FAULT (the observer could not see), everything else in errors[]
  # is a determined WOULD-BLOCK violation. Exit codes are mode-independent.
  let verdict =
    if not runnersEnumerated: "OBSERVER-FAULT"
    elif errors.len > 0: "WOULD-BLOCK"
    else: "PASS"
  let faultCause = if not runnersEnumerated: "gate" else: ""
  if jsonMode:
    emitVerdictJson(verdict, faultCause)
  if errors.len > 0:
    for e in errors:
      logInfo("manifest_consistency_gate", e)
    for w in warnings:
      logInfo("manifest_consistency_gate", w)
    quit(1)
  else:
    if warnings.len > 0:
      for w in warnings:
        logInfo("manifest_consistency_gate", w)
    logger.info $GateTag & " PASS — manifest consistent (" & $totalGateCount & " gates validated)"
    quit(0)

