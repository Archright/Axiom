## Hermetic Test Ratchet Gate
##
## Ensures test files do not become more dependent on ambient system state.
## Scans tests/ for non-hermetic primitives (I/O, environment, subprocess, etc.)
## and enforces a per-file monotonic ratchet: once a file's violation count is
## recorded in the baseline, it must never increase. Decreases are allowed and
## encouraged; the baseline can be refreshed with --update-baseline.
##
## Usage:
##   hermetic_test_gate              # compare against baseline
##   hermetic_test_gate --update-baseline

