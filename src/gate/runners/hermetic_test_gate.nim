const
  GateTag = "[hermetic-test]"
  BaselineRelPath = "data/hermetic_test_baseline.json"
  TestRootRel = "tests"

  ## Runner/helper files are allowed to orchestrate non-hermetic setup.
  ExcludedFiles: array[6, string] = [
    "tests/gateway/all_gateway_runner.nim",
    "tests/gateway/test_aot_runner.nim",
    "tests/gateway/gateway_test_helpers.nim",
    "tests/gateway_test_helpers.nim",
    "tests/features/steps/gate_steps.nim",
    "tests/unit/nimtry_fixtures/run_all_fictures.nim",
  ]


proc isExcluded(relPath: string): bool =
  for excluded in ExcludedFiles:
    if relPath == excluded:
      return true
    if relPath.contains(excluded):
      return true
  false

proc scanTests(repoRoot: string): seq[(string, int)] {.axiomEffect: IOEffect.} =
  let testRoot = repoRoot / TestRootRel
  if not dirExists(testRoot):
    return @[]

  const NonHermeticReStr = "(readFile|writeFile|execCmd|execCmdEx|execProcess|startProcess|open|createDir|removeDir|deleteFile|moveFile|copyFile|renameFile|fileExists|dirExists|setCurrentDir|shellCmd|stdin|stdout|stderr|log|echo|write|writeLine|readFile|readAll|readLine|readBytes|writeBytes|getEnv|putEnv|removeEnv|expandEnv|includeEnv|testEnv|getAppFileName|getAppDir|getAppRelDir|getInstallPrefix|getConfigDir|getDataDir|getDocDir|getHomeDir|getHomeDir|getTempDir|getWordExp|getSpecialFolder|changeDir|extractFilePath|extractFileName|extractFileExt|extractBaseName|splitFile|addSlash|delInlineExt|addExt|changeFileExt|quotedResizable)"
  let pattern = re(NonHermeticReStr)

  # Collect all .nim files recursively
  var nimFiles: seq[string] = @[]
  for path in walkDirRec(testRoot, yieldFilter = {pcFile}):
    if path.endsWith(".nim"):
      nimFiles.add(path)
  nimFiles.sort()

  for fullPath in nimFiles:
    # Compute relative path from repo root
    var relPath = fullPath
    if fullPath.startsWith(repoRoot):
      relPath = fullPath[repoRoot.len .. ^1]
      if relPath.startsWith("/"):
        relPath = relPath[1 .. ^1]

    # Normalize to POSIX separators
    relPath = relPath.replace("\\", "/")

    if isExcluded(relPath):
      continue
    # Skip non-.nim files
    if not relPath.endsWith(".nim"):
      continue

    try:
      let text = readFile(fullPath)
      let matches = text.findAll(pattern)
      if matches.len > 0:
        result.add((relPath, matches.len))
    except CatchableError:
      discard  # axiom:best-effort(ioboundary catch)


proc loadBaseline(repoRoot: string): seq[(string, int)] {.axiomEffect: IOEffect.} =
  let baselinePath = repoRoot / BaselineRelPath
  if not fileExists(baselinePath):
    return @[]
  try:
    let data = parseJson(readFile(baselinePath))
    let counts = data["counts"]
    var keys: seq[string] = @[]
    for k in counts.keys:
      keys.add(k)
    keys.sort()
    for k in keys:
      result.add((k, counts[k].getInt()))
  except CatchableError:
    return @[]


func getBaselineValue(baseline: seq[(string, int)], key: string): int =
  for (k, v) in baseline:
    if k == key:
      return v
  0

func sumValues(items: seq[(string, int)]): int =
  var total = 0
  for (_, v) in items:
    total += v
  total
proc saveBaseline(repoRoot: string, counts: seq[(string, int)]) {.axiomEffect: IOEffect.} =
  let baselinePath = repoRoot / BaselineRelPath
  let parentDir = baselinePath.parentDir()
  if not dirExists(parentDir):
    createDir(parentDir)
  var countsObj = newJObject()
  for (k, v) in counts:
    countsObj[k] = newJInt(v)
  let payload = %*{
    "counts": countsObj,
    "source": "tests/",
    "note": "Auto-generated by tools/ci/hermetic_test_gate.py --update-baseline"
  }
  writeFile(baselinePath, $payload & "\n")


proc main()  =
  let repoRoot = findRepoRoot()
  setCurrentDir(repoRoot)

  var updateBaseline = false
  for i in 1 .. paramCount():
    if paramStr(i) == "--update-baseline":
      updateBaseline = true
      break

  let current = scanTests(repoRoot)

  if updateBaseline:
    saveBaseline(repoRoot, current)
    logger.info $GateTag & " Baseline updated: " & $current.len & " file(s) with violations."
    logger.info $GateTag & " Stage and commit " & $BaselineRelPath & "."
    quit(0)

  let baseline = loadBaseline(repoRoot)
  let totalCurrent = sumValues(current)
  let totalBaseline = sumValues(baseline)
  logger.info $GateTag & " Current violation files: " & $current.len & " & total occurrences: " & $totalCurrent
  logger.info $GateTag & " Baseline files: " & $baseline.len & " & total occurrences: " & $totalBaseline

  var failed = false
  for (rel, count) in current:
    let base = getBaselineValue(baseline, rel)
    if count > base:
      logError("hermetic_test_gate", $(GateTag) & " FAIL: " & $(rel) & " has " & $(count) & " non-hermetic call(s), baseline allows " & $(base) & ".")
      failed = true

  if totalCurrent > totalBaseline:
    logError("hermetic_test_gate", $(GateTag) & " FAIL: total non-hermetic occurrences increased (" & $(totalCurrent) & " > " & $(totalBaseline) & ").")
    failed = true

  if failed:
    logInfo("hermetic_test_gate", $(GateTag) & " New non-hermetic test patterns detected.")
    logInfo("hermetic_test_gate", $(GateTag) & " Isolate them via core/test_support/sandbox_guard.nim or reduce the baseline.")
    quit(1)

  logger.info $GateTag & " PASS: hermetic test ratchet holds."
  quit(0)

{.pop.}

when isMainModule:
  main()

