## bootstrap_verifier.nim — Two-Phase Hermetic Bootstrapping Protocol.
## When axiom-gate detects a self-referential change (its own source is being
## modified), it builds a next-state binary in an isolated sandbox, verifies
## it passes gates, then promotes it to bin/axiom-gate.
##
## This resolves the Bootstrap Paradox: the old binary can't verify changes
## to itself because cached failures from the old binary block the commit.
##
## Architecture:
##   Phase 1: Copy source tree (whitelist-based) to sandbox
##   Phase 2: Overlay staged changes
##   Phase 3: Build next-state binary in sandbox
##   Phase 4: Verify next-state binary against gates (--dry-run)
##   Phase 5: Promote if verified, or defer to CI if compilation fails
##
## Depends on: self_ref_detect.nim (Phase 1 — detection)

import std/[os, osproc, tempfiles, strutils]
import core/trusted/stdlib_shield
import core/axiom_pragmas

# ── Hermetic Copy Configuration ──────────────────────────────────────
# Whitelist: only directories needed for axiom-gate compilation.
# Blacklist: mutable state, large assets, caches.
const BootstrapWhitelist* = [
  "src/",
  "config.nims",
  "config/",
  "axiom.nimble",
  "AGENTS.md",            # read by config/integrity.nims at build time — sandbox build fails without it
  "docs/agents/",         # read by config/integrity.nims (staticRead policy artifacts)
  "docs/spec/",           # read by spec_binding_macro at compile time (spec_registry.json)
]

const BootstrapBlacklistPrefixes* = [
  "src/generated/",        # regenerated by hermetic_build
  ".git/",
  "logs/",
  "data/",
  "proofs/",
  "tests/",
  "vendor/",
  "tmp/",
  "build/",
  ".axiom/cache/",
  ".nimcache_gate_hook/",
  ".nimcache_test/",
  ".lake/",
  ".worktrees/",
]

# ── Bootstrap Result Type ────────────────────────────────────────────
type BootstrapResult* = object
  ok*: bool           ## true = next-state binary verified successfully
  reason*: string     ## human-readable explanation
  deferred*: bool     ## true = compilation failed, deferred to CI (≠ failure)
  nextBinaryPath*: string  ## path to promoted binary (if ok=true)

# ── Whitelist-Based Source Copy ──────────────────────────────────────
func isBlacklisted*(relPath: string): bool =
  ## Check if a relative path matches any blacklist prefix.
  ## debt_sync_guard.nim is include'd by config/integrity.nims at compile time but
  ## is a static stub (not actually regenerated during sandbox builds) — copy it.
  ## build_metadata.json is read by self_ref_detect.nim at compile time and is not
  ## regenerated inside the sandbox — copy it.
  if relPath == "src/generated/debt_sync_guard.nim" or
     relPath == "src/generated/build_metadata.json":
    return false
  for prefix in BootstrapBlacklistPrefixes:
    if relPath.startsWith(prefix) or relPath == prefix:
      return true
  false

proc copyBootstrapSource*(repoRoot, sandboxDir: string): int {.axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect], raises: [CatchableError].} =
  ## Copy source tree to sandbox using whitelist/blacklist rules.
  ## Returns number of files copied.
  result = 0
  for whitelistEntry in BootstrapWhitelist:
    let srcPath = repoRoot / whitelistEntry
    if dirExists(srcPath):
      for file in walkDirRec(srcPath):
        let relPath = relativePath(file, repoRoot)
        if isBlacklisted(relPath):
          continue
        let dstPath = sandboxDir / relPath
        createDir(dstPath.parentDir)
        copyFile(file, dstPath)
        inc result
    elif fileExists(srcPath):
      if not isBlacklisted(whitelistEntry):
        let dstPath = sandboxDir / whitelistEntry
        createDir(dstPath.parentDir)
        copyFile(srcPath, dstPath)
        inc result

# ── Staged Changes Overlay ───────────────────────────────────────────
proc overlayStagedChanges*(sandboxDir: string, stagedFiles: seq[string],
                            repoRoot: string): int {.axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect], raises: [CatchableError].} =
  ## Overlay staged file changes onto the sandbox.
  ## Returns number of files overlaid.
  result = 0
  for f in stagedFiles:
    let srcPath = repoRoot / f
    let dstPath = sandboxDir / f
    if fileExists(srcPath):
      createDir(dstPath.parentDir)
      copyFile(srcPath, dstPath)
      inc result

# ── Next-State Binary Build ──────────────────────────────────────────
proc buildNextStateBinary*(sandboxDir: string): tuple[ok: bool; output: string; binaryPath: string] {.axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect], raises: [CatchableError].} =
  ## Build axiom-gate binary in the isolated sandbox.
  ## Returns (ok, output, binaryPath).
  let binDir = sandboxDir / "bin"
  createDir(binDir)
  let nextBinary = binDir / "axiom-gate"

  # Build with hermetic flags — no gorge() calls, no external state
  let buildCmd = "cd " & quoteShell(sandboxDir) &
    " && AXIOM_HERMETIC_BUILDING=1" &
    " nim c -d:release --hints:off --warnings:off" &
    " -o:" & quoteShell(nextBinary) &
    " src/gate/gateway.nim 2>&1"

  let (output, exitCode) = execCmdEx(buildCmd)

  if exitCode == 0 and fileExists(nextBinary):
    (ok: true, output: output, binaryPath: nextBinary)
  else:
    (ok: false, output: output, binaryPath: "")

# ── Next-State Binary Verification ───────────────────────────────────
proc verifyNextStateBinary*(nextBinary, sandboxDir: string): tuple[ok: bool; output: string] {.axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect], raises: [CatchableError].} =
  ## Run the next-state binary in --dry-run mode to verify gates pass.
  ## The sandbox directory serves as the repo root for verification.
  let verifyCmd = "AXIOM_BOOTSTRAP_VERIFY=1 " &
    quoteShell(nextBinary) & " hook pre-commit --dry-run" &
    " --repo-root=" & quoteShell(sandboxDir) & " 2>&1"

  let (output, exitCode) = execCmdEx(verifyCmd)
  (ok: exitCode == 0, output: output)

# ── Binary Promotion ─────────────────────────────────────────────────
proc promoteBinary*(src, dst: string): bool {.axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect], raises: [CatchableError].} =
  ## Promote the next-state binary to the official path.
  ## Uses copy+remove instead of moveFile to avoid unlisted Exception raise.
  let tmpDst = dst & ".bootstrap.tmp"
  try:
    copyFile(src, tmpDst)
    if fileExists(dst):
      safeRemoveFile(dst)
    copyFile(tmpDst, dst)
    safeRemoveFile(tmpDst)
    true
  except CatchableError:
    if fileExists(tmpDst):
      safeRemoveFile(tmpDst)
    false

# ── Main Bootstrap Protocol ──────────────────────────────────────────
proc runBootstrapVerification*(repoRoot: string, stagedFiles: seq[string]): BootstrapResult {.axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect], raises: [CatchableError].} =
  ## Execute the full Two-Phase Hermetic Bootstrapping protocol.
  ##
  ## 1. Create isolated sandbox
  ## 2. Copy source tree (whitelist-based)
  ## 3. Overlay staged changes
  ## 4. Build next-state binary
  ## 5. Verify with --dry-run
  ## 6. Promote if verified
  let sandboxDir = createTempDir("axiom_bootstrap_", "")
  defer:
    try: removeDir(sandboxDir)
    except CatchableError: discard  # axiom:best-effort(ioboundary catch)

  # Phase 1: Copy source tree
  let copiedCount = copyBootstrapSource(repoRoot, sandboxDir)
  if copiedCount == 0:
    return BootstrapResult(ok: false, reason: "No source files copied to sandbox", deferred: false)

  # Phase 2: Overlay staged changes
  discard overlayStagedChanges(sandboxDir, stagedFiles, repoRoot)

  # Phase 3: Build next-state binary
  let buildResult = buildNextStateBinary(sandboxDir)
  if not buildResult.ok:
    let outputLen = buildResult.output.len
    let tail = if outputLen > 500: buildResult.output[^500..^1]
               else: buildResult.output
    return BootstrapResult(
      ok: false,
      reason: "Compilation failed in sandbox: " & tail,
      deferred: true  # Compilation failure = defer to CI, not a gate failure
    )

  # Phase 4: Verify next-state binary
  let verifyResult = verifyNextStateBinary(buildResult.binaryPath, sandboxDir)
  if not verifyResult.ok:
    let outputLen = verifyResult.output.len
    let tail = if outputLen > 500: verifyResult.output[^500..^1]
               else: verifyResult.output
    return BootstrapResult(
      ok: false,
      reason: "Gate verification failed: " & tail,
      deferred: false
    )

  # Phase 5: Promote next-state binary
  let promoted = promoteBinary(buildResult.binaryPath, repoRoot / "bin" / "axiom-gate")
  if not promoted:
    return BootstrapResult(ok: false, reason: "Binary promotion failed", deferred: false)

  BootstrapResult(
    ok: true,
    reason: "Next-state binary verified and promoted successfully",
    deferred: false,
    nextBinaryPath: repoRoot / "bin" / "axiom-gate"
  )
