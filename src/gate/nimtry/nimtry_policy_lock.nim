## Generate policy lock content from current codebase metrics (Ground Truth).
## Reads existing lockfile and updates derived sections while preserving mandatory sections.
proc generatePolicyLock*(allFacts: seq[ModuleFacts]; policy: ArchitecturePolicy): string {.raises: [], axiomEffect: IOEffect, tags: [AxiomIOEffect, IOEffect, RootEffect].} =
  let repoRoot = try: getCurrentDir() except OSError: "."
  let lockPath = repoRoot / "src/gate/architecture_policy.lock"
  
  # Read existing lockfile to preserve mandatory sections
  var existingSections = initTable[string, string]()
  if fileExists(lockPath):
    let existing = try: readFileSafe(lockPath) except CatchableError: ""
    if existing.len > 0:
      var currentSection = ""
      var currentContent = ""
      for line in existing.splitLines():
        let stripped = line.strip()
        if stripped.startsWith("[") and stripped.endsWith("]"):
          if currentSection.len > 0:
            existingSections[currentSection] = currentContent
          currentSection = stripped[1 .. ^2]
          currentContent = ""
        elif currentSection.len > 0:
          currentContent.add(line & "\n")
      if currentSection.len > 0:
        existingSections[currentSection] = currentContent
  
  result.add("# Auto-generated by nimtry --update-lock\n")
  result.add("# Ground Truth: derived from current clean codebase\n\n")
  
  # Preserve mandatory sections from existing lockfile
  let mandatorySections = ["meta", "layer", "layer_edges", "module_roles", "allowed_assignment_owners", "ssot_types", "forbidden_assignments", "forbidden_calls", "dry"]
  for section in mandatorySections:
    try:
      if existingSections.hasKey(section):
        result.add("[" & section & "]\n")
        result.add(existingSections[section])
        result.add("\n")
      else:
        # Fallback: architecture_policy.lock is SSOT. If a section is missing, emit
        # an empty section rather than a hardcoded default (which would diverge
        # from the real lockfile). This keeps the regeneration deterministic and
        # language-native (Nim's case expression has no implicit default value).
        result.add("[" & section & "]\n\n")
    except KeyError:
      discard
  
  # [canonical_computations] — derive from actual assignments
  result.add("[canonical_computations]\n")
  var foundPatterns = initTable[string, string]()
  for facts in allFacts:
    for assignment in facts.assignments:
      if '/' in assignment.rhsExpr:
        let pattern = assignment.rhsExpr.strip()
        if pattern.len > 0 and not foundPatterns.hasKey(pattern):
          foundPatterns[pattern] = facts.path
          result.add("\"" & pattern & "\" = { owner = \"" & facts.path & "\", varType = \"float\" }\n")
  
  # [interfaces] — derive from pragma declarations
  result.add("\n[interfaces]\n")
  var foundInterfaces = initTable[string, seq[string]]()
  for facts in allFacts:
    for pragma in facts.pragmas:
      if pragma.pragmaName == "axiomImplements":
        let iface = pragma.pragmaValue.strip(chars = {'"', ' ', '\t'})
        if iface.len > 0:
          try:
            if not foundInterfaces.hasKey(iface):
              foundInterfaces[iface] = @[]
            foundInterfaces[iface].add(pragma.pragmaName)
          except KeyError:
            discard
  for iface, pragmas in foundInterfaces.pairs:
    result.add("\"" & iface & "\" = { file = \"auto\", requiredPragmas = [\"gcsafe\", \"noSideEffect\"] }\n")
  
  # [opaque_types] — derive from distinct types
  result.add("\n[opaque_types]\n")
  for facts in allFacts:
    for dt in facts.distinctTypes:
      result.add("\"" & dt.name & "\" = { owner = \"" & facts.path & "\" }\n")
  
  # [cohesion] — preserve or default
  result.add("\n[cohesion]\n")
  try:
    if existingSections.hasKey("cohesion"):
      result.add(existingSections["cohesion"])
    else:
      result.add("max_lcom = 0.6\nmin_tcc = 0.3\n")
  except KeyError:
    result.add("max_lcom = 0.6\nmin_tcc = 0.3\n")
  
  # [surface_area] — preserve or default
  result.add("\n[surface_area]\n")
  try:
    if existingSections.hasKey("surface_area"):
      result.add(existingSections["surface_area"])
    else:
      result.add("max_imports = 30\nmax_exported_functions = 50\nexempt_layers = [\"gate\"]\n")
  except KeyError:
    result.add("max_imports = 30\nmax_exported_functions = 50\nexempt_layers = [\"gate\"]\n")
  
  # Preserve all remaining manual sections from existing lockfile
  let autoGeneratedSections = @["meta", "layer", "layer_edges", "module_roles",
    "allowed_assignment_owners", "ssot_types", "forbidden_assignments",
    "forbidden_calls", "dry", "canonical_computations", "interfaces",
    "opaque_types", "cohesion", "surface_area"]
  for section, content in existingSections.pairs:
    if section notin autoGeneratedSections:
      result.add("[" & section & "]\n")
      result.add(content)
      result.add("\n")

