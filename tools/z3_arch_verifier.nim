  SkipPrefixes = ["std", "pkg", "checksums", "malebolgia"]

# ── Types ──────────────────────────────────────────────────────────────────────

type
  ArchViolation = object
    sourceLayer: string
    targetLayer: string

  VerifyResult = object
    status: string           ## "pass" or "fail"
    violations: seq[ArchViolation]
    policyEdges: int         ## total allowed edges in policy
    importEdges: int         ## total import edges found
