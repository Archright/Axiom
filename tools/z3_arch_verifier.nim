    policyPath: string
    importsDir: string
    jsonOutput: bool
    verbose: bool

# ── Layer Index Builder ────────────────────────────────────────────────────────

func cmpStr(a, b: string): int =
  if a < b: -1
  elif a > b: 1
  else: 0

func buildLayerIndex(dag: LayerDag): Table[string, int] =
  ## Assign deterministic integer indices to all layer/sub-domain names.
  ## Sorted for reproducibility across runs.
  var names: seq[string] = @[]
  for name in dag.layerPaths.keys:
    names.add(name)
  for source, targets in dag.edges:
    if source notin dag.layerPaths:
      names.add(source)
    for target in targets:
      if target notin dag.layerPaths and target notin names:
        names.add(target)
  names.sort(cmpStr)
  names = names.deduplicate(isSorted = true)
  var idx = 0
  for name in names:
    result[name] = idx
    inc idx

func reverseIndex(layerIndex: Table[string, int]): Table[int, string] =
  for name, idx in layerIndex:
    result[idx] = name

# ── SMT2 Generator ────────────────────────────────────────────────────────────

func generateSmt2(dag: LayerDag, layerIndex: Table[string, int],
                   importEdges: seq[(string, string)]): string =
  ## Generate Z3 HORN logic SMT2 content.
  ##
  ## Encoding:
  ##   - allowed(a,b): direct edges from architecture_policy.lock
  ##   - reachable(a,b): transitive closure via Horn clauses
  ##   - imported(a,b): actual import edges from source scanning
  ##   - Safety query: ∀a,b. imported(a,b) → reachable(a,b)
  ##     (encoded as negated query: ¬(imported(a,b) ∧ ¬reachable(a,b)))
  ##
  ## Result semantics:
  ##   sat   = safety property holds (no violations)
  ##   unsat = violation found (import exists but not reachable)

  var s: string
  s.add ";; Generated by z3_arch_verifier — Z3 HORN Logic Architecture Verification\n"
  s.add ";; Encoding: CHC (Constrained Horn Clauses) with transitive closure\n\n"
  s.add "(set-logic HORN)\n\n"

  # Declare relations
  s.add "(declare-fun allowed (Int Int) Bool)\n"
  s.add "(declare-fun reachable (Int Int) Bool)\n"
  s.add "(declare-fun imported (Int Int) Bool)\n\n"

  # Allowed edges from policy as facts
  s.add ";; ── Allowed edges from architecture_policy.lock ──\n"
  var edgeCount = 0
  for source, targets in dag.edges:
    if source in layerIndex:
      let si = layerIndex[source]
      for target in targets:
        if target in layerIndex:
          let ti = layerIndex[target]
          s.add "(assert (allowed " & $si & " " & $ti & "))\n"
          inc edgeCount
  s.add "\n"

  # Transitive closure rules
  s.add ";; ── Transitive closure via Horn clauses ──\n"
  s.add ";; Rule 1: direct allowed edges are reachable\n"
  s.add "(assert (forall ((a Int) (b Int))\n"
  s.add "  (=> (allowed a b) (reachable a b))))\n\n"
  s.add ";; Rule 2: transitivity — allowed(a,b) ∧ reachable(b,c) → reachable(a,c)\n"
  s.add "(assert (forall ((a Int) (b Int) (c Int))\n"
  s.add "  (=> (and (allowed a b) (reachable b c)) (reachable a c))))\n\n"

  # Import facts from source scanning
  s.add ";; ── Import edges from source scanning ──\n"
  var importCount = 0
  for (src, tgt) in importEdges:
    if src in layerIndex and tgt in layerIndex:
      s.add "(assert (imported " & $layerIndex[src] & " " & $layerIndex[tgt] & "))\n"
      inc importCount
  s.add "\n"

  # Safety query: all imports must be reachable
  s.add ";; ── Safety query ──\n"
  s.add ";; ¬∃a,b. imported(a,b) ∧ ¬reachable(a,b)\n"
  s.add ";; Encoded as: ∀a,b. (imported(a,b) ∧ ¬reachable(a,b)) → ⊥\n"
  s.add "(assert (forall ((a Int) (b Int))\n"
  s.add "  (=> (and (imported a b) (not (reachable a b))) false)))\n\n"

  s.add "(check-sat)\n"

  result = s

# ── Import Scanner ─────────────────────────────────────────────────────────────

func resolveImportLayer(importPath: string, dag: LayerDag): string =
  ## Resolve a raw import path to its target layer name.
  ## Strategy: check longest-prefix match against layer paths,
  ## then fall back to first-component match.
  let normalized = importPath.replace("\\", "/").replace(".", "/")

  # Longest-prefix match against layer paths (most specific first)
  var bestLayer = ""
  var bestLen = 0
  for layer, layerPath in dag.layerPaths:
    let nlp = layerPath.replace("\\", "/")
    if normalized.startsWith(nlp & "/") or normalized == nlp:
      if nlp.len > bestLen:
        bestLayer = layer
        bestLen = nlp.len

  if bestLayer.len > 0:
    return bestLayer

  # First-component match (e.g., "core/bmc/foo" → "core")
  let firstComponent = normalized.split("/")[0]
  if firstComponent in dag.layerPaths:
    return firstComponent

  # Check sub-domains (e.g., "bmc/foo" → "bmc" if bmc is a known edge source)
  if firstComponent in dag.edges:
    return firstComponent

  ""

proc scanImports(srcDir: string, dag: LayerDag): seq[(string, string)] =
  ## Scan .nim source files for import relationships.
  ## Returns deduplicated (sourceLayer, targetLayer) pairs.
  var seen = initHashSet[(string, string)]()

  var allFiles: seq[string] = @[]
  for filePath in walkDirRec(srcDir):
    if filePath.endsWith(".nim") and
       "/generated/" notin filePath and
       "/nimcache" notin filePath:
      allFiles.add(filePath)

  allFiles.sort(cmpStr)

  for filePath in allFiles:
    let sourceLayer = getLayer(filePath, dag)
    if sourceLayer.len == 0:
      continue

    var content: string
    try:
      content = readFile(filePath)
    except IOError:
      continue

    let imports = tokenizeImports(content)
    for imp in imports:
      # Skip stdlib and external packages
      let firstComponent = imp.split("/")[0]
      if firstComponent in SkipPrefixes:
        continue

      let targetLayer = imp.resolveImportLayer(dag)
      if targetLayer.len == 0 or targetLayer == sourceLayer:
        continue

      let edge = (sourceLayer, targetLayer)
      if edge notin seen:
        seen.incl(edge)
        result.add(edge)

# ── Graph Reachability (fallback for violation extraction) ─────────────────────

func computeTransitiveClosure(dag: LayerDag): Table[string, Table[string, bool]] =
  ## Compute transitive closure of allowed edges via Floyd-Warshall.
  ## Returns: closure[a][b] = true if b is reachable from a through allowed paths.
  var layers: seq[string] = @[]
  for layer in dag.layerPaths.keys:
    layers.add(layer)
  for source in dag.edges.keys:
    if source notin dag.layerPaths:
      layers.add(source)
  layers.sort(cmpStr)
  layers = layers.deduplicate(isSorted = true)

  # Initialize: closure[a][b] = true iff (a,b) is a direct edge
  for layer in layers:
    result[layer] = initTable[string, bool]()

  for source, targets in dag.edges:
    for target in targets:
      if source in result and target in result:
        result[source][target] = true

  # Floyd-Warshall
  for k in layers:
    for i in layers:
      for j in layers:
        if result[i].getOrDefault(k, false) and
           result[k].getOrDefault(j, false):
          result[i][j] = true

func findViolations(dag: LayerDag,
                    importEdges: seq[(string, string)]): seq[ArchViolation] =
  ## Find import edges that violate the architecture policy.
  ## Uses transitive closure of allowed edges.
  let closure = computeTransitiveClosure(dag)

  for (src, tgt) in importEdges:
    let reachable = closure.getOrDefault(src, initTable[string, bool]())
        .getOrDefault(tgt, false)
    if not reachable:
      result.add(ArchViolation(sourceLayer: src, targetLayer: tgt))

# ── Cache ──────────────────────────────────────────────────────────────────────

func computeCacheHash(policyContent: string,
                      importEdges: seq[(string, string)]): string =
  ## Simple content hash for cache invalidation.
  var h = 0'u64
  for ch in policyContent:
    h = h xor (cast[uint64](ch) shl (h mod 56))
    h = h + 1
  for (src, tgt) in importEdges:
    for ch in src & "\x00" & tgt & "\x01":
      h = h xor (cast[uint64](ch) shl (h mod 56))
      h = h + 1
  result = $h

proc tryLoadCache(hash: string): VerifyResult =
  ## Try to load cached result. Returns empty result on failure.
  result = VerifyResult(status: "", cached: false)
  try:
    if not fileExists(CacheKeyFile) or not fileExists(CacheResultFile):
      return
    let storedHash = readFile(CacheKeyFile).strip()
    if storedHash != hash:
      return
    let jsonContent = parseJson(readFile(CacheResultFile))
    result.status = jsonContent{"status"}.getStr("")
    result.policyEdges = jsonContent{"policyEdges"}.getInt(0)
    result.importEdges = jsonContent{"importEdges"}.getInt(0)
    result.layersChecked = jsonContent{"layersChecked"}.getInt(0)
    result.z3TimeMs = 0
    result.cached = true
    for v in jsonContent{"violations"}:
      result.violations.add(ArchViolation(
        sourceLayer: v{"sourceLayer"}.getStr(""),
        targetLayer: v{"targetLayer"}.getStr("")
      ))
  except CatchableError:
    result = VerifyResult(status: "", cached: false)

proc saveCache(hash: string, res: VerifyResult) =
  ## Persist result to cache.
  try:
    createDir(CacheDir)
    writeFile(CacheKeyFile, hash)
    let jsonRes = %*{
      "status": res.status,
      "violations": res.violations.mapIt(%*{
        "sourceLayer": it.sourceLayer,
        "targetLayer": it.targetLayer
      }),
      "policyEdges": res.policyEdges,
      "importEdges": res.importEdges,
      "layersChecked": res.layersChecked
    }
    writeFile(CacheResultFile, jsonRes.pretty(indent = 2))
  except CatchableError: # axiom:best-effort(cache write failure is non-fatal; result still returned)
    discard  # Cache write failure is non-fatal

# ── Z3 Execution ──────────────────────────────────────────────────────────────

proc runZ3(smt2Content: string, verbose: bool): (string, int) =
  ## Write SMT2 to temp file, run Z3, return (output, timeMs).
  ## Uses std/tempfiles for safe temp file management.
  let startTime = getTime()

  # Write SMT2 to cache location for debugging
  try:
    createDir(CacheDir)
    writeFile(CacheSmt2File, smt2Content)
  except IOError:
    discard

  # Write to a temp file for Z3 execution
  let tempDir = getTempDir()
  let tempFile = tempDir / "z3_arch_query.smt2"
  try:
    writeFile(tempFile, smt2Content)
  except IOError:
    return ("ERROR: Failed to write temp file", 0)

  # Run Z3
  if verbose:
    stderr.writeLine("[z3_arch_verifier] Running Z3 on: ", tempFile)

  var output: string
  try:
    output = execProcess(Z3Binary, args = ["-smt2", tempFile],
                         options = {poUsePath, poStdErrToStdOut})
  except OSError:
    return ("ERROR: Z3 binary not found or execution failed", 0)
  except CatchableError:
    return ("ERROR: " & getCurrentExceptionMsg(), 0)

  # Clean up temp file
  try:
    removeFile(tempFile)
  except CatchableError: # axiom:best-effort(temp file cleanup failure is non-fatal)
    discard

  let elapsed = (getTime() - startTime).inMilliseconds.int
  result = (output, elapsed)

# ── Result Formatting ─────────────────────────────────────────────────────────

func formatJsonResult(res: VerifyResult): string =
  ## Format result as JSON.
  let violationsJson = res.violations.mapIt(%*{
    "sourceLayer": it.sourceLayer,
    "targetLayer": it.targetLayer
  })
  var violationsArr = newJArray()
  for v in violationsJson:
    violationsArr.add(v)

  let jsonRes = %*{
    "tool": "z3_arch_verifier",
    "layer": "L4",
    "status": res.status,
    "violations": violationsArr,
    "policyEdges": res.policyEdges,
    "importEdges": res.importEdges,
    "layersChecked": res.layersChecked,
    "z3TimeMs": res.z3TimeMs,
    "cached": res.cached
  }
  jsonRes.pretty(indent = 2)

func formatTextResult(res: VerifyResult): string =
  ## Format result as human-readable text.
  var s: string
  s.add "=== Z3 Architecture Verifier (L4) ===\n"
  if res.cached:
    s.add "  (served from cache)\n"
  s.add "  Policy edges:   " & $res.policyEdges & "\n"
  s.add "  Import edges:   " & $res.importEdges & "\n"
  s.add "  Layers checked: " & $res.layersChecked & "\n"
  s.add "  Z3 time:        " & $res.z3TimeMs & "ms\n"
  s.add "\n"

  if res.status == "pass":
    s.add "  ✅ PASS — All imports reach their targets through allowed paths.\n"
    s.add "  Z3 HORN logic verified: no forbidden import path exists.\n"
  else:
    s.add "  ❌ FAIL — " & $res.violations.len & " architecture violation(s) detected.\n"
    for v in res.violations:
      s.add "    " & v.sourceLayer & " → " & v.targetLayer & " (not reachable)\n"
  s

# ── CLI Parsing ────────────────────────────────────────────────────────────────

proc parseCliOptions(): CliOptions =
  result = CliOptions(
    policyPath: DefaultPolicyPath,
    importsDir: DefaultImportsDir,
    jsonOutput: false,
    verbose: false
  )

  var i = 1
  while i <= paramCount():
    let param = paramStr(i)
    case param
    of "--policy":
      if i + 1 <= paramCount():
        inc i
        result.policyPath = paramStr(i)
    of "--imports":
      if i + 1 <= paramCount():
        inc i
        result.importsDir = paramStr(i)
    of "--json":
      result.jsonOutput = true
    of "--verbose", "-v":
      result.verbose = true
    of "--help", "-h":
      echo "Usage: z3_arch_verifier [OPTIONS]"
      echo ""
      echo "Z3 HORN Logic Architecture Verifier (L4 of 5-Layer Defense Stack)"
      echo "Verifies architecture policy with transitive closure via Z3 SMT solver."
      echo ""
      echo "Options:"
      echo "  --policy <path>   Architecture policy lock file"
      echo "                    (default: " & DefaultPolicyPath & ")"
      echo "  --imports <dir>   Directory to scan for actual imports"
      echo "                    (default: " & DefaultImportsDir & ")"
      echo "  --json            Output results as JSON"
      echo "  --verbose, -v     Show Z3 query details"
      echo "  --help, -h        Show this help message"
      quit(0)
    else:
      stderr.writeLine("Unknown option: ", param)
      stderr.writeLine("Use --help for usage information.")
      quit(1)
    inc i

# ── Main ───────────────────────────────────────────────────────────────────────

proc main() =
  let opts = parseCliOptions()

  # 1. Read and parse policy
  if not fileExists(opts.policyPath):
    stderr.writeLine("ERROR: Policy file not found: ", opts.policyPath)
    quit(1)

  let policyContent = readFile(opts.policyPath)
  let dag = parseLayerEdges(policyContent)
  let layerIndex = buildLayerIndex(dag)

  # 2. Scan imports from source
  if not dirExists(opts.importsDir):
    stderr.writeLine("ERROR: Imports directory not found: ", opts.importsDir)
    quit(1)

  let importEdges = scanImports(opts.importsDir, dag)

  # 3. Check cache
  let cacheHash = computeCacheHash(policyContent, importEdges)
  var result = tryLoadCache(cacheHash)

  if result.cached:
    if opts.jsonOutput:
      echo formatJsonResult(result)
    else:
      echo formatTextResult(result)
    quit(if result.status == "pass": 0 else: 1)

  # 4. Generate SMT2
  let smt2Content = generateSmt2(dag, layerIndex, importEdges)

  if opts.verbose:
    stderr.writeLine("[z3_arch_verifier] Generated SMT2 (", smt2Content.len, " bytes)")
    stderr.writeLine("[z3_arch_verifier] Policy edges in SMT2: ",
                     $dag.edges.len)
    stderr.writeLine("[z3_arch_verifier] Import edges in SMT2: ",
                     $importEdges.len)
    stderr.writeLine("[z3_arch_verifier] Layer index: ", $layerIndex.len, " layers")

  # 5. Run Z3
  let (z3Output, z3TimeMs) = runZ3(smt2Content, opts.verbose)

  if opts.verbose:
    stderr.writeLine("[z3_arch_verifier] Z3 output:\n", z3Output)

  # 6. Interpret Z3 result
  let trimmed = z3Output.strip()

  if trimmed.startsWith("ERROR"):
    stderr.writeLine("Z3 execution error: ", trimmed)
    quit(2)

  # Z3 HORN logic semantics:
  #   sat   = safety property holds (all imports are reachable)
  #   unsat = safety property violated (an import is not reachable)
  var violations: seq[ArchViolation]
  var status: string

  if trimmed.startsWith("sat"):
    # Safety property holds — no violations
    status = "pass"
    violations = @[]
  elif trimmed.startsWith("unsat"):
    # Violation found — extract specific violating edges via graph analysis
    status = "fail"
    violations = findViolations(dag, importEdges)
  else:
    # Unexpected Z3 output
    stderr.writeLine("WARNING: Unexpected Z3 output: ", trimmed)
    stderr.writeLine("Falling back to graph-based verification.")
    status = "fail"
    violations = findViolations(dag, importEdges)

  # 7. Build result
  result = VerifyResult(
    status: status,
    violations: violations,
    policyEdges: dag.edges.len,
    importEdges: importEdges.len,
    layersChecked: layerIndex.len,
    z3TimeMs: z3TimeMs,
    z3Output: z3Output,
    smt2Path: CacheSmt2File,
    cached: false
  )

  # 8. Cache result
  saveCache(cacheHash, result)

  # 9. Output
  if opts.jsonOutput:
    echo formatJsonResult(result)
  else:
    echo formatTextResult(result)

  quit(if status == "pass": 0 else: 1)

main()
