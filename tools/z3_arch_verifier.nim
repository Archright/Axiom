## tools/z3_arch_verifier.nim — Z3 HORN Logic Architecture Verifier
##
## Layer 4 (L4) of the 5-Layer Defense Stack.
## Uses Z3's HORN logic (CHC / Datalog fixedpoint) to verify architecture
## policy with transitive closure. Formal verification that no forbidden
## import path exists — even through transitive chains.
##
## Unlike the DAG-based check in layer_dag.nim (L0), this provides formal
## proof via Z3 SMT solver that the architecture policy is globally consistent.
##
## Architecture:
##   1. Parse architecture_policy.lock via layer_dag.parseLayerEdges()
##   2. Scan source imports via import_tokenizer
##   3. Generate Z3 HORN SMT2 with transitive closure rules
##   4. Call Z3, parse result for violations
##   5. Report results in JSON format
##
## CLI:
##   z3_arch_verifier [--policy path] [--imports dir] [--json] [--verbose]
##
## Run: nim c --hints:off -d:release -d:useMalloc -o:bin/z3_arch_verifier tools/z3_arch_verifier.nim
##      bin/z3_arch_verifier

