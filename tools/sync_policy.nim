## tools/sync_policy.nim
## Mutation command: reads policy_revisions.json → validates → materializes → writes
## config/policy/policy_dispositions.json (idempotent).
## P0-3: reconstructs full current policy from genesis+patches alone.
## SSOT for policy materialization pipeline.

import std/[json, os, strutils, tables, options]
import policy/revision_chain

# ══════════════════════════════════════════════════════════════════════
# Constants
# ══════════════════════════════════════════════════════════════════════

const PolicyRevisionsPath = "config/policy/policy_revisions.json"
const DispositionsOut     = "config/policy/policy_dispositions.json"

# Decision table and reason map live in tools/policy/revision_chain.nim
# (shared SSOT) — imported above; do not redefine here.

# ══════════════════════════════════════════════════════════════════════
# Helpers
# ══════════════════════════════════════════════════════════════════════

proc loadJsonc(path: string): JsonNode {.raises: [CatchableError].} =
  if not fileExists(path):
    echo "ERROR: " & path & " not found"; quit(1)
  let content = readFile(path)
  let stripped = stripJsonComments(content)
  try:
    result = parseJson(stripped)
  except JsonParsingError:
    echo "ERROR: Invalid JSON in " & path & ": " & getCurrentExceptionMsg(); quit(1)

proc idempotentWrite(path, content: string) {.raises: [CatchableError].} =
  ## Write only if content differs (idempotency).
  if fileExists(path):
    let existing = readFile(path)
    let existingStripped = stripJsonComments(existing)
    if existingStripped.strip() == content.strip():
      echo "  [skip] " & path & " unchanged"
      return
  let dir = path.parentDir()
  if not dirExists(dir): createDir(dir)
  writeFile(path, content)
  echo "  [write] " & path & " (" & $content.len & " bytes)"

# ══════════════════════════════════════════════════════════════════════
# Main
# ══════════════════════════════════════════════════════════════════════

proc main() {.raises: [CatchableError].} =
  echo "sync_policy: read policy_revisions.json → validate → materialize → write policy_dispositions.json"
  echo ""

  # Step 1: Load and validate the revision chain
  echo "[1/4] Loading " & PolicyRevisionsPath & "..."
  let chainJson = loadJsonc(PolicyRevisionsPath)

  echo "[2/4] Validating revision chain invariants (P0-2)..."
  let validation = validateLinear(chainJson)
  if validation.len == 0:
    echo "  ✅ Revision chain is valid (linear, single genesis, single head, all reachable)"
  else:
    echo "  ❌ Revision chain validation FAILED:"
    for err in validation:
      echo "    - " & err
    quit(1)

  # Step 2: Find head and extract genesis payload
  echo "[3/4] Finding head and materializing policy (P0-3)..."
  let headId = findHead(chainJson)
  if headId.isNone():
    echo "  ❌ No head found in revision chain"; quit(1)
  echo "  Head revision: " & headId.get()

  # Extract genesis payload as the initial state
  var genesisState: JsonNode
  let revisions = chainJson{"revisions"}
  for rev in revisions:
    let parentId = rev{"parentRevisionId"}
    if parentId.kind == JNull:
      genesisState = rev{"payload"}
      break

  if genesisState.kind != JObject:
    echo "  ❌ Genesis payload not found or invalid"; quit(1)

  # Materialize: apply all patches from genesis to head
  let materialized = materialize(chainJson, genesisState)

  echo "  Materialized policy:"
  echo "    policyId:          " & materialized.policyId
  echo "    defaultDisposition: " & materialized.defaultDisposition
  echo "    rules:"
  for rule in materialized.rules:
    echo "      " & rule.state & " → " & rule.disposition

  # Step 3: Build per-metric dispositions from decision table + materialized rules
  echo ""
  echo "[4/4] Building policy_dispositions.json..."

  var metricsObj = newJObject()
  for metricName, expectedState in DecisionTable.pairs:
    # Look up disposition from materialized rules
    var disposition = materialized.defaultDisposition  # fail-closed default
    for rule in materialized.rules:
      if rule.state == expectedState:
        disposition = rule.disposition
        break

    var metricEntry = newJObject()
    metricEntry["disposition"] = %disposition
    metricEntry["reason"] = %ReasonMap.getOrDefault(metricName, "Policy-driven disposition")
    let direction = DirectionMap.getOrDefault(metricName, "MAINTAINED")
    metricEntry["direction"] = %direction
    metricsObj[metricName] = metricEntry

  var output = newJObject()
  output["version"] = %"1.0.0"
  output["schema"] = %"policy_dispositions"
  output["metrics"] = metricsObj

  let jsonOutput = output.pretty()
  let jsoncOutput = "// Auto-generated by tools/sync_policy - DO NOT EDIT\n// Policy dispositions for budget metric DRIFT results.\n// SSOT: docs/spec/canonical_contract_policy_layer.md §5\n// Version: v1.1.0 (P3 Policy Ratchet — added direction key per metric rule)\n//\n// Evaluator decides PASS|DRIFT; policy decides disposition severity.\n// direction: optional drift direction (IMPROVEMENT|REGRESSION|MAINTAINED) per metric.\n// Exit 0 when every disposition is INFO or WARN; exit 1 when any ERROR.\n// Escalation requires editing ONLY this artifact — no CI/Makefile changes needed.\n\n" & jsonOutput

  idempotentWrite(DispositionsOut, jsoncOutput)

  # Verify freshness
  echo ""
  echo "Freshness check:"
  let freshStatus = verifyContentFreshness(jsonOutput, DispositionsOut)
  echo "  " & freshStatus

  echo ""
  echo "Done."

when isMainModule:
  main()
