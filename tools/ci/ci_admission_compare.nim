func charonFromSpans*(spans: seq[int]; source: string): CharonResult {.raises: [].} =
  result = CharonResult(status: StatusObserved, source: source, minSeconds: -1,
                        maxSeconds: -1)
  if spans.len == 0:
    result.status = StatusUnknown
    result.reason = "span file carries no integer seconds for this cohort"
    return
  var v = spans
  v.sort()
  result.n = v.len
  result.p50 = r7Percentile(v, 0.5)
  result.minSeconds = v[0]
  result.maxSeconds = v[^1]

func buildComparison*(pre, post: Snapshot; opts: Options;
                      preCharon, postCharon: CharonResult): Comparison {.raises: [].} =
  result = Comparison(opts: opts, pre: pre, post: post,
                      preCharon: normalizeCharon(preCharon),
                      postCharon: normalizeCharon(postCharon))
  result.validity = cohortValidity(pre, post)
  result.preRows = headroomRows(pre)
  result.postRows = headroomRows(post)
  for k in PhaseKey:
    result.preSpread[k] = spreadOf(phaseValues(pre, k))
    result.postSpread[k] = spreadOf(phaseValues(post, k))

  result.x = metricValues(pre, opts.metric)
  result.y = metricValues(post, opts.metric)
  result.mw = mannWhitney(result.x, result.y)
  result.hlDoubled = hodgesLehmannDoubled(result.x, result.y)
  result.mde = minDetectableEffect(result.x.len, result.y.len, opts.alpha)
  if result.x.len > 0 and result.y.len > 0:
    result.mde.applyObservedEffect(
      abs(result.mw.uDoubled - int64(result.x.len) * int64(result.y.len)))

  let decision = preRegisteredVerdict(result.validity.verdict, result.mw,
                                      result.mde, result.x.len, result.y.len,
                                      opts.alpha)
  result.verdict = decision.verdict
  result.reason = decision.reason
  result.withheld = decision.verdict == tvRefused

  if result.withheld:
    # Descriptive quantities (spread, headroom, Hodges-Lehmann, U, MDE) stay
    # visible so a reviewer can read the numbers; the inferential ones are
    # withheld, because over overlapping cohorts they have no interpretation.
    result.boot = BootResult(reps: opts.reps, seed: opts.seed, alpha: opts.alpha,
                             status: WithheldRefused,
                             methodName: "withheld-cohort-invalid")
  else:
    result.boot = bootstrapMedianCi(result.x, result.y, opts.reps, opts.seed,
                                    opts.alpha)

