type
  HeadroomRow* = object
    prNumber*: int
    headSha*: string
    status*: string
    reason*: string
    lastFinisher*: string
    secondLastFinisher*: string
    headroomSecond*: int
    slowestIndependent*: string
    headroomIndependent*: int
    tieAtMax*: bool
    tiedCount*: int

  HeadroomSummary* = object
    n*: int
    p50*: float
    minSeconds*: int
    maxSeconds*: int
    tieAtMaxN*: int
    unknownN*: int

type
  CheckKey* = tuple[completedAt, context: string, idx: int]

func orderedBoundChecks*(checks: seq[CheckRow]): seq[CheckRow] {.raises: [].} =
  ## Bound checks with a completion instant, ascending by (completed_at, context).
  ## The tuple sort is used instead of a comparator callback so this stays inside
  ## an empty raises list without relying on closure effect inference.
  var keys: seq[CheckKey] = @[]
  for i, ch in checks:
    if ch.bound and ch.completedAt.len > 0:
      keys.add (completedAt: ch.completedAt, context: ch.context, idx: i)
  keys.sort()
  for k in keys:
    result.add checks[k.idx]

func deriveHeadroom*(prNumber: int; headSha: string;
                     checks: seq[CheckRow]): HeadroomRow {.raises: [].} =
  ## second_last_finisher / headroom_second / headroom_independent for one
  ## observed candidate. Every unobservable answer stays UNKNOWN with a reason; a
  ## missing measurement is never rendered as zero headroom.
  result = HeadroomRow(prNumber: prNumber, headSha: headSha,
                       status: StatusUnknown, headroomSecond: -1,
                       headroomIndependent: -1)
  let bound = orderedBoundChecks(checks)
  if bound.len < 2:
    result.reason = "fewer than two bound checks carry a completion instant"
    return

  # The last finisher is the lexicographically smallest context among the tied
  # maximum, exactly the observer's `lastFinisher` convention, so this row stays
  # consistent with the snapshot's own last_finisher field.
  let maxAt = bound[^1].completedAt
  for ch in bound:
    if ch.completedAt == maxAt:
      inc result.tiedCount
  result.tieAtMax = result.tiedCount > 1
  var last = bound[^1]
  for ch in bound:
    if ch.completedAt == maxAt and ch.context < last.context:
      last = ch
  result.lastFinisher = last.context
  # The runner-up is the second element of the ascending order, the same
  # definition the reference derivation uses (checks[-2]).
  result.secondLastFinisher = bound[^2].context

  if result.tieAtMax:
    # Freeing one of several contexts that finish at the same instant saves
    # nothing: another member of the tied set still defines the wall.
    result.status = StatusObserved
    result.headroomSecond = 0
    result.headroomIndependent = 0
    for ch in bound:
      if ch.workflowPath.len > 0 and ch.workflowPath != last.workflowPath:
        result.slowestIndependent = ch.context
    return

  let dSecond = secsBetween(last.completedAt, bound[^2].completedAt)
  if dSecond < 0:
    result.status = StatusUnknown
    result.reason = "completion instants are unparsable or out of order"
    return
  result.headroomSecond = dSecond

  if last.workflowPath.len == 0:
    # Without a workflow path for the last finisher, independence cannot be
    # established for ANY other context. Fail closed rather than report a number
    # the snapshot does not support.
    result.status = StatusUnknown
    result.reason = "last finisher has no workflow_path, so independence is unprovable"
    return

  var bestIndep = ""
  var haveIndep = false
  for ch in bound:
    if ch.context == last.context and ch.completedAt == last.completedAt:
      continue
    if ch.workflowPath.len == 0:
      continue
    if ch.workflowPath != last.workflowPath:
      # Ascending order is preserved, so the last accepted row is the slowest.
      bestIndep = ch.context
      haveIndep = true
      result.headroomIndependent =
        block:
          let d = secsBetween(last.completedAt, ch.completedAt)
          if d < 0: -1 else: d

  result.status = StatusObserved
  if haveIndep:
    result.slowestIndependent = bestIndep
  else:
    result.reason = "no context from a different workflow_path completes before the" &
                    " last finisher"

func summarizeHeadroom*(rows: seq[HeadroomRow]; independent: bool): HeadroomSummary
    {.raises: [].} =
  var values: seq[int] = @[]
  for r in rows:
    if r.tieAtMax:
      inc result.tieAtMaxN
    let v = if independent: r.headroomIndependent else: r.headroomSecond
    if v >= 0:
      values.add v
    else:
      inc result.unknownN
  result.n = values.len
  if values.len == 0:
    result.minSeconds = -1
    result.maxSeconds = -1
    return
  var v = values
  v.sort()
  result.minSeconds = v[0]
  result.maxSeconds = v[^1]
  result.p50 = r7Percentile(v, 0.5)

