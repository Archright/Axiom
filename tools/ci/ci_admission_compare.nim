    rangeSeconds*: int
    p95*: float
    p95Status*: string

func spreadOf*(values: seq[int]): Spread {.raises: [].} =
  ## Sample variance (n-1) and its square root; IQR in the same estimator family as
  ## p50/p90 (Hyndman-Fan 7) so the report never mixes families. p95 is INCOMPLETE
  ## below n = 20 per docs/spec/ci_critical_path_metric.md, section 5.
  result = Spread(p95Status: P95Incomplete, minSeconds: -1, maxSeconds: -1)
  if values.len == 0:
    return
  var v = values
  v.sort()
  result.n = v.len
  result.p50 = r7Percentile(v, 0.5)
  result.minSeconds = v[0]
  result.maxSeconds = v[^1]
  result.rangeSeconds = v[^1] - v[0]
  result.iqr = r7Percentile(v, 0.75) - r7Percentile(v, 0.25)
  if v.len >= 2:
    var total = 0.0
    for x in v:
      total += float(x)
    let mean = total / float(v.len)
    var ss = 0.0
    for x in v:
      let d = float(x) - mean
      ss += d * d
    result.variance = ss / float(v.len - 1)
    result.sd = sqrt(result.variance)
  if v.len >= P95MinN:
    result.p95 = r7Percentile(v, 0.95)
    result.p95Status = "REPORTED"

