## tools/ci/ci_admission_compare.nim - snapshot-to-snapshot admission comparison.
##
## REPORTER ONLY, and a PURE one: the comparison is a function of two frozen
## `axiom.ci_admission_observe.v1` snapshots. There is no `gh api`, no network,
## no subprocess and no live repository state anywhere in this module. The
## observer (tools/ci/ci_admission_observe.nim) collects; this module compares.
## Running it twice on the same pair of files reproduces every number.
##
## WHY THIS EXISTS (the gap it closes)
##   The observer measures ONE cohort and reports p50/p90/mean/min/max. It has no
##   second cohort, no variance, no headroom ("how much would be saved if the
##   last finisher were free"), and no test. A pre/post claim about the admission
##   wall therefore had no machinery behind it. This module is that machinery,
##   and its FIRST duty is to refuse the comparison when the two snapshots are
##   not two cohorts.
##
## COHORT VALIDITY (the gate, and the most important behavior here)
##   A pre/post test assumes two independent samples. Two snapshots taken over the
##   SAME population violate that assumption by construction (pseudo-replication):
##   a candidate appearing in both arms contributes its measurement twice, so any
##   p-value computed from the pooled ranks is meaningless. The gate fails closed:
##     SAME_BOUNDARY_REFUSED  both snapshots declare the same boundary ref, so the
##                            population is identical by definition;
##     OVERLAP_REFUSED        the cohort head_sha sets intersect;
##     VALID                  disjoint head_sha sets.
##   The boundary ref is read from the snapshot itself (`boundary`,
##   `cohort.boundary`, or `binding.boundary`). `cohort.source` (the collector
##   report path) is deliberately NOT read: that file is regenerated by the
##   collector, so its content after the snapshot was frozen would silently move
##   a verdict about a frozen snapshot. When no ref is declared the check is
##   recorded as UNKNOWN_*_ABSENT and the overlap gate still governs.
##
## PHASE MODEL
##   Inherited verbatim from the snapshot; this module never recomputes a phase.
##   `--metric admission|ready|verify` selects which recorded quantity is tested.
##   `admission` is the pre-registered metric: `ready` and `verify` exist so a
##   reviewer can inspect them, and testing all three then reporting the smallest
##   p-value would be a multiplicity error.
##
## HEADROOM (derived, per cohort, from the snapshot alone)
##   `second_last_finisher` is the runner-up completion instant and
##   `headroom_second` = last - second last. `headroom_independent` excludes
##   contexts that share a `workflow_path` with the last finisher: Actions
##   `needs:` edges are intra-workflow only, so two contexts bound to different
##   workflows cannot be DAG-coupled while contexts sharing one MAY be. The
##   exclusion is a conservative over-approximation - it can only UNDERSTATE
##   headroom, never overstate it. When the top instant is shared, "the last
##   finisher" is not unique and freeing one of them saves nothing: both
##   headrooms are then 0 and the row records TIE_AT_MAX.
##
## T_charon
##   There is no charon stage in CI, so T_charon cannot be derived from job logs.
##   The field is emitted with `status: "NO_LOG_SOURCE"` rather than a fabricated
##   duration; an optional `--charon-spans <json>` supplies externally collected
##   spans and the same field then becomes OBSERVED. The schema is identical
##   either way.
##
## STATISTICS (exact, or explicitly labeled as an approximation)
##   * Mann-Whitney U, exact null: counts[u] = number of label splits of the ranks
##     1..n1+n2 with U == u, by DP over the partition polynomial. The counts sum
##     to C(n1+n2, n1) (uint64; the binomial is overflow-checked before the DP
##     runs). Two-sided p = sum(counts[u] : |2u - n1n2| >= |2U_obs - n1n2|) over
##     C(n1+n2, n1), in integers only - no float enters the tail.
##   * Ties: midranks in doubled integer form, so a half rank stays exact. With
##     ties present the no-tie DP null is NOT valid, so the p-value comes from an
##     exact permutation enumeration of the label splits when the split space is
##     <= ExactEnumerationCap, and from a tie-corrected normal approximation
##     otherwise. `exact` records which ran, and the pre-registered rule never
##     promotes a non-exact p to SIGNIFICANT.
##   * Hodges-Lehmann: median of all n1*n2 pairwise differences y_j - x_i, carried
##     in doubled integer form so a .5 median is exact.
##   * Bootstrap: percentile CI on the median difference drawn from a fixed LCG
##     (`s = (1103515245*s + 12345) mod 2^31`, seed 20261124) - a pure function of
##     (x, y, reps, seed), re-implementable in five lines by any reviewer. It
##     reports UNINFORMATIVE when the resample median support is degenerate
##     (< 3 distinct medians) or the interval has zero width: at n=8 with
##     separated ranges the support collapses to a point, and printing that point
##     as a narrow confidence interval would be a theater artifact.
##   * MDE: the smallest |U - n1n2/2| whose exact upper tail is <= alpha/2 at the
##     observed n, expressed as a common-language AUC. When the observed
##     separation is below it, a non-significant result is INCONCLUSIVE, never
##     "no change".
##
## PRE-REGISTERED SIGNIFICANCE RULE (fixed before any optimization lands)
##   1. cohort gate: verdict must be VALID, else REFUSED and no inferential
##      statistic is published (descriptive quantities are still reported);
##   2. metric: admission_seconds;
##   3. primary test: exact two-sided Mann-Whitney at alpha (default 0.05);
##   4. both arms need >= 8 observed candidates, else INCONCLUSIVE;
##   5. SIGNIFICANT iff an exact p <= alpha;
##   6. otherwise UNDERPOWERED at the observed effect size => INCONCLUSIVE;
##   7. p95 is withheld below n = 20 (docs/spec/ci_critical_path_metric.md).
##
## ESTIMATORS
##   p50/p90 are the observer's own estimators (`r7Percentile`, Hyndman-Fan type
##   7, which is the canonical collector p50 at p=0.5) imported rather than
##   re-derived, so the two reports cannot disagree about the same array. IQR uses
##   the same family (r7(0.75) - r7(0.25)). Variance is the SAMPLE variance (n-1
##   denominator), sd its square root, 0 for n < 2.
##
## Exit: 0 comparison produced; 1 cohort invalid (same boundary or overlap)
##       unless --allow-overlap; 2 input unreadable or schema mismatch.

