func sortedUnique*(values: seq[string]): seq[string] {.raises: [].} =
  var v = values
  v.sort()
  for x in v:
    if result.len == 0 or result[^1] != x:
      result.add x

func sharedOf*(a, b: seq[string]): seq[string] {.raises: [].} =
  ## a and b must be sorted and duplicate-free (see sortedUnique).
  var i = 0
  var j = 0
  while i < a.len and j < b.len:
    if a[i] == b[j]:
      result.add a[i]
      inc i
      inc j
    elif a[i] < b[j]:
      inc i
    else:
      inc j

func isSubsetOf*(a, b: seq[string]): bool {.raises: [].} =
  ## a and b must be sorted and duplicate-free.
  var j = 0
  for x in a:
    while j < b.len and b[j] < x:
      inc j
    if j >= b.len or b[j] != x:
      return false
    inc j
  true

type
  CohortValidity* = object
    verdict*: CohortVerdict
    disjoint*: bool
    sameBoundary*: bool
    boundaryCheck*: string
    preBoundary*: string
    postBoundary*: string
    shared*: seq[string]
    sharedObserved*: seq[string]
    preSubsetOfPost*: bool
    postSubsetOfPre*: bool
    reason*: string

func cohortValidity*(pre, post: Snapshot): CohortValidity {.raises: [].} =
  ## The gate that makes a pre/post number meaningful. Order matters: an
  ## identical boundary is refused before overlap is considered, because it proves
  ## the two snapshots sample one population regardless of what the head lists
  ## happen to contain.
  let a = sortedUnique(pre.headShas)
  let b = sortedUnique(post.headShas)
  result.preBoundary = pre.boundary
  result.postBoundary = post.boundary
  result.shared = sharedOf(a, b)
  result.preSubsetOfPost = a.len > 0 and isSubsetOf(a, b)
  result.postSubsetOfPre = b.len > 0 and isSubsetOf(b, a)
  var obsA: seq[string] = @[]
  var obsB: seq[string] = @[]
  for c in pre.observed:
    obsA.add c.headSha
  for c in post.observed:
    obsB.add c.headSha
  result.sharedObserved = sharedOf(sortedUnique(obsA), sortedUnique(obsB))

  result.sameBoundary = pre.boundary.len > 0 and post.boundary.len > 0 and
                        pre.boundary == post.boundary
  if pre.boundary.len == 0 and post.boundary.len == 0:
    result.boundaryCheck = "UNKNOWN_BOTH_ABSENT"
  elif pre.boundary.len == 0:
    result.boundaryCheck = "UNKNOWN_PRE_ABSENT"
  elif post.boundary.len == 0:
    result.boundaryCheck = "UNKNOWN_POST_ABSENT"
  else:
    result.boundaryCheck = "COMPARED"

  if result.sameBoundary:
    result.verdict = cvSameBoundaryRefused
    result.disjoint = false
    result.reason = "both snapshots declare boundary " & pre.boundary &
      "; they sample one population, so a pre/post test would be pseudo-replication"
  elif result.shared.len > 0:
    result.verdict = cvOverlapRefused
    result.disjoint = false
    result.reason = $result.shared.len & " of " & $a.len & " pre and " & $b.len &
      " post cohort head_sha values are shared" &
      (if result.preSubsetOfPost: " (the pre cohort is a subset of the post cohort)"
       else: "") & "; shared candidates would be counted in both arms"
  else:
    result.verdict = cvValid
    result.disjoint = true
    result.reason = "disjoint head_sha sets"

