func boundaryOf*(node: JsonNode): tuple[value, source: string] {.raises: [].} =
  ## The observe schema does not carry a boundary field, so the ref is read
  ## wherever a producer may declare it and the location is recorded. An absent
  ## ref is reported as absent rather than inferred from the file path.
  let top = jsonAt(node, "boundary")
  if not top.isNil and top.kind == JString and top.getStr().len > 0:
    return (top.getStr(), "top-level:boundary")
  let cohort = jsonStrAt(jsonAt(node, "cohort"), "boundary")
  if cohort.len > 0:
    return (cohort, "cohort.boundary")
  let binding = jsonStrAt(jsonAt(node, "binding"), "boundary")
  if binding.len > 0:
    return (binding, "binding.boundary")
  ("", "ABSENT")

func parseCheckRow*(node: JsonNode): CheckRow {.raises: [].} =
  CheckRow(context: jsonStrAt(node, "context"),
           workflowPath: jsonStrAt(node, "workflow_path"),
           completedAt: jsonStrAt(node, "completed_at"),
           bound: jsonBoolAt(node, "bound"))

func parseSnapshot*(node: JsonNode; path: string):
    tuple[ok: bool, snap: Snapshot, err: string] {.raises: [].} =
  ## Reads one `axiom.ci_admission_observe.v1` snapshot. A wrong schema version is
  ## a schema mismatch, never a best-effort parse: a v2 report could rename a
  ## field and a silent default would be indistinguishable from a measurement.
  if node.isNil or node.kind != JObject:
    return (false, Snapshot(), "snapshot is not a JSON object")
  let sv = jsonStrAt(node, "schema_version")
  if sv != ObserveSchemaVersion:
    return (false, Snapshot(), "schema_version is '" & sv & "', expected '" &
            ObserveSchemaVersion & "'")
  let cands = jsonAt(node, "candidates")
  if cands.isNil or cands.kind != JArray:
    return (false, Snapshot(), "candidates is not an array")

  var s = Snapshot(path: path)
  s.repo = jsonStrAt(node, "repo")
  let (bv, bs) = boundaryOf(node)
  s.boundary = bv
  s.boundarySource = bs
  let cohort = jsonAt(node, "cohort")
  s.cohortSource = jsonStrAt(cohort, "source")
  let shas = jsonAt(cohort, "head_shas")
  if not shas.isNil and shas.kind == JArray:
    for e in items(shas):
      if e.kind == JString and e.getStr().len > 0:
        s.headShas.add e.getStr()
  s.cohortN = jsonIntAt(cohort, "n")
  s.observedN = jsonIntAt(node, "observed_n")
  s.unknownN = jsonIntAt(node, "unknown_n")

  for c in items(cands):
    if c.kind != JObject:
      continue
    if jsonStrAt(c, "outcome") != StatusObserved:
      continue
    var row = CandidateRow(prNumber: jsonIntAt(c, "pr_number"),
                           headSha: jsonStrAt(c, "head_sha"),
                           lastFinisher: jsonStrAt(c, "last_finisher"))
    for k in PhaseKey:
      row.phaseSeconds[k] = -1
    # `ready_seconds` and `admission_seconds` are TOP-LEVEL candidate fields in
    # axiom.ci_admission_observe.v1 (only queue/verify/publication/merge are
    # phases). Read them from their own keys so the derived totals are the
    # snapshot's, not a re-derivation.
    row.phaseSeconds[pkReady] = jsonIntAt(c, "ready_seconds")
    row.phaseSeconds[pkAdmission] = jsonIntAt(c, "admission_seconds")
    let phases = jsonAt(c, "phases")
    if not phases.isNil and phases.kind == JArray:
      for p in items(phases):
        let name = jsonStrAt(p, "name")
        for k in PhaseKey:
          if name == $k:
            row.phaseSeconds[k] = jsonIntAt(p, "seconds")
    let checks = jsonAt(c, "checks")
    if not checks.isNil and checks.kind == JArray:
      for ch in items(checks):
        if ch.kind == JObject:
          row.checks.add parseCheckRow(ch)
    s.observed.add row

  if s.headShas.len == 0:
    for c in s.observed:
      if c.headSha.len > 0:
        s.headShas.add c.headSha
  if s.cohortN == 0:
    s.cohortN = s.headShas.len
  if s.observedN == 0:
    s.observedN = s.observed.len
  (true, s, "")

proc loadSnapshot*(path: string):
    tuple[ok: bool, snap: Snapshot, err: string] {.axiomEffect: IoEffect.} =
  if path.len == 0:
    return (false, Snapshot(), "empty snapshot path")
  if not fileExists(path):
    return (false, Snapshot(), "missing file: " & path)
  try:
    let node = parseJson(readFile(path))
    return parseSnapshot(node, path)
  except CatchableError as e:
    (false, Snapshot(), "unparsable JSON in " & path & ": " & e.msg)

