func binomialBounded*(n, k: int; cap: uint64):
    tuple[value: uint64, overflow: bool] {.raises: [].} =
  ## C(n, k) with an explicit overflow report. Each intermediate product is
  ## divisible by its denominator at that step, so the division order keeps every
  ## intermediate exact.
  if n < 0 or k < 0 or k > n:
    return (0'u64, false)
  let kk = min(k, n - k)
  var v = 1'u64
  for i in 1 .. kk:
    let num = uint64(n - kk + i)
    if num > 0'u64 and v > cap div num:
      return (0'u64, true)
    v = v * num
    v = v div uint64(i)
  (v, false)

func exactUDistribution*(n1, n2: int):
    tuple[ok: bool, counts: seq[uint64], total: uint64] {.raises: [].} =
  ## counts[u] = number of label splits of the ranks 1..n1+n2 with U == u, over
  ## C(n1+n2, n1) splits, by DP over the partition polynomial. `total` is summed
  ## from the counts so a caller can verify the binomial identity instead of
  ## trusting it.
  if n1 <= 0 or n2 <= 0:
    return (false, @[], 0'u64)
  let totalRanks = n1 + n2
  # C(N, floor(N/2)) bounds every DP cell, so this single check also guarantees
  # that no intermediate accumulation can overflow.
  let (_, ovfPeak) = binomialBounded(totalRanks, totalRanks div 2, high(uint64))
  if ovfPeak:
    return (false, @[], 0'u64)
  let (_, ovfTarget) = binomialBounded(totalRanks, n1, high(uint64))
  if ovfTarget:
    return (false, @[], 0'u64)

  let maxSum = n1 * totalRanks
  let stride = maxSum + 1
  var dp = newSeq[uint64]((n1 + 1) * stride)
  dp[0] = 1'u64
  for r in 1 .. totalRanks:
    for j in countdown(min(r, n1), 1):
      let base = j * stride
      let prev = (j - 1) * stride
      for s in countdown(maxSum - r, 0):
        let c = dp[prev + s]
        if c > 0'u64:
          dp[base + s + r] = dp[base + s + r] + c

  let shift = n1 * (n1 + 1) div 2
  var counts = newSeq[uint64](n1 * n2 + 1)
  var total = 0'u64
  for s in 0 .. maxSum:
    let c = dp[n1 * stride + s]
    if c > 0'u64:
      total += c
      let u = s - shift
      if u >= 0 and u <= n1 * n2:
        counts[u] += c
  (true, counts, total)

func doubledMidranks*(values: seq[int]): seq[int64] {.raises: [].} =
  ## Midranks in doubled integer form: a tie group covering ranks i+1..j+1 has
  ## midrank (i+j+2)/2, so its doubled value is the integer i+j+2 and no half rank
  ## is ever rounded.
  let n = values.len
  result = newSeq[int64](n)
  var keys: seq[tuple[value, idx: int]] = @[]
  for i in 0 ..< n:
    keys.add (value: values[i], idx: i)
  keys.sort()
  var i = 0
  while i < n:
    var j = i
    while j + 1 < n and keys[j + 1].value == keys[i].value:
      inc j
    let dr = int64(i + j + 2)
    for k in i .. j:
      result[keys[k].idx] = dr
    i = j + 1

func pooledOf*(x, y: seq[int]): seq[int] {.raises: [].} =
  result = newSeq[int](x.len + y.len)
  for i in 0 ..< x.len:
    result[i] = x[i]
  for j in 0 ..< y.len:
    result[x.len + j] = y[j]

func uDoubled*(x, y: seq[int]): int64 {.raises: [].} =
  ## 2U = sum(doubled midranks of x) - n1(n1+1).
  if x.len == 0 or y.len == 0:
    return 0'i64
  let ranks = doubledMidranks(pooledOf(x, y))
  var total = 0'i64
  for i in 0 ..< x.len:
    total += ranks[i]
  total - int64(x.len) * int64(x.len + 1)

type
  TieInfo* = object
    tieGroups*: int
    tiedValues*: int

func tieInfo*(x, y: seq[int]): TieInfo {.raises: [].} =
  var pooled = pooledOf(x, y)
  pooled.sort()
  var i = 0
  while i < pooled.len:
    var j = i
    while j + 1 < pooled.len and pooled[j + 1] == pooled[i]:
      inc j
    if j > i:
      inc result.tieGroups
      result.tiedValues += j - i + 1
    i = j + 1

func gcdU64*(a, b: uint64): uint64 {.raises: [].} =
  var x = a
  var y = b
  while y != 0'u64:
    let t = x mod y
    x = y
    y = t
  x

func fractionString*(num, den: uint64): string {.raises: [].} =
  if den == 0'u64:
    return "0/0"
  let g = gcdU64(num, den)
  if g <= 1'u64:
    return $num & "/" & $den
  $(num div g) & "/" & $(den div g)

func extremeCount*(counts: seq[uint64]; centerDoubled, devDoubled: int64): uint64
    {.raises: [].} =
  ## Sum of counts at |2u - n1n2| >= devDoubled. Integer comparison only: both
  ## sides are exact, so no epsilon tolerance is involved.
  for u in 0 ..< counts.len:
    if abs(2'i64 * int64(u) - centerDoubled) >= devDoubled:
      result += counts[u]

func exactTiePermutation*(ranks: seq[int64]; n1: int; devDoubled: int64):
    tuple[num, den: uint64] {.raises: [].} =
  ## Exact conditional permutation p-value over the C(n1+n2, n1) label splits, with
  ## the observed doubled midranks fixed. Valid with ties, but exponential in
  ## character, so callers gate it on the split-space size.
  let n = ranks.len
  let n2 = n - n1
  if n1 <= 0 or n2 <= 0:
    return (0'u64, 0'u64)
  let centerDoubled = int64(n1) * int64(n2)
  let offset = int64(n1) * int64(n1 + 1)
  var combo = newSeq[int](n1)
  for i in 0 ..< n1:
    combo[i] = i
  while true:
    var total = 0'i64
    for i in combo:
      total += ranks[i]
    if abs((total - offset) - centerDoubled) >= devDoubled:
      inc result.num
    inc result.den
    var i = n1 - 1
    while i >= 0 and combo[i] == n - n1 + i:
      dec i
    if i < 0:
      break
    combo[i] = combo[i] + 1
    for k in i + 1 ..< n1:
      combo[k] = combo[k - 1] + 1

func normalTwoSidedP*(z: float): float {.raises: [].} =
  ## Two-sided normal tail via the Abramowitz-Stegun 26.2.17 erf approximation
  ## (|error| <= 1.5e-7). Only the tie-corrected FALLBACK uses this; the primary
  ## evidence is always an exact null.
  let az = abs(z)
  let t = 1.0 / (1.0 + 0.3275911 * az)
  let poly = t * (0.254829592 + t * (-0.284496736 + t * (1.421413741 +
               t * (-1.453152027 + t * 1.061405429))))
  let erfv = 1.0 - poly * exp(-az * az)
  let cdf = 0.5 * (1.0 + erfv)
  min(1.0, max(0.0, 2.0 * (1.0 - cdf)))

func tieCorrectedNormalP*(x, y: seq[int]): float {.raises: [].} =
  let n1 = x.len
  let n2 = y.len
  let n = n1 + n2
  if n < 2:
    return 1.0
  var pooled = pooledOf(x, y)
  pooled.sort()
  var tieSum = 0.0
  var i = 0
  while i < pooled.len:
    var j = i
    while j + 1 < pooled.len and pooled[j + 1] == pooled[i]:
      inc j
    let t = float(j - i + 1)
    tieSum += t * t * t - t
    i = j + 1
  let nf = float(n)
  let variance = float(n1) * float(n2) / 12.0 *
                 ((nf + 1.0) - tieSum / (nf * (nf - 1.0)))
  if variance <= 0.0:
    return 1.0
  let u = float(uDoubled(x, y)) / 2.0
  let mu = float(n1) * float(n2) / 2.0
  let z = max(0.0, abs(u - mu) - 0.5) / sqrt(variance)
  normalTwoSidedP(z)

type
  MwResult* = object
    n1*: int
    n2*: int
    uDoubled*: int64
    u*: float
    center*: float
    dev*: float
    p*: float
    pExact*: string
    exact*: bool
    methodName*: string
    tieGroups*: int
    tiedValues*: int

func mannWhitney*(x, y: seq[int]): MwResult {.raises: [].} =
  ## Two-sided Mann-Whitney U with an exact null whenever one is valid:
  ##   no ties, binomial fits uint64 -> exact DP over label splits;
  ##   ties, split space <= cap      -> exact permutation with fixed midranks;
  ##   otherwise                     -> tie-corrected normal (exact = false).
  result = MwResult(n1: x.len, n2: y.len, pExact: NotExact, methodName: "none")
  if x.len == 0 or y.len == 0:
    result.p = 1.0
    result.methodName = "degenerate-empty-arm"
    return
  let ties = tieInfo(x, y)
  result.tieGroups = ties.tieGroups
  result.tiedValues = ties.tiedValues
  let centerDoubled = int64(x.len) * int64(y.len)
  result.uDoubled = uDoubled(x, y)
  result.center = float(centerDoubled) / 2.0
  result.u = float(result.uDoubled) / 2.0
  result.dev = abs(result.u - result.center)
  let devDoubled = abs(result.uDoubled - centerDoubled)

  if ties.tieGroups == 0:
    let (ok, counts, total) = exactUDistribution(x.len, y.len)
    if ok and total > 0'u64:
      let ext = extremeCount(counts, centerDoubled, devDoubled)
      result.exact = true
      result.methodName = "exact-u-dp"
      result.pExact = fractionString(ext, total)
      result.p = float(ext) / float(total)
      return

  let (comb, ovf) = binomialBounded(x.len + y.len, x.len, uint64(ExactEnumerationCap))
  if not ovf and comb <= uint64(ExactEnumerationCap):
    let ranks = doubledMidranks(pooledOf(x, y))
    let (num, den) = exactTiePermutation(ranks, x.len, devDoubled)
    if den > 0'u64:
      result.exact = true
      result.methodName = "exact-permutation-midrank"
      result.pExact = fractionString(num, den)
      result.p = float(num) / float(den)
      return

  result.exact = false
  result.methodName = "tie-corrected-normal"
  result.pExact = NotExact
  result.p = tieCorrectedNormalP(x, y)

