type
  CliOutcome* = object
    code*: int
    outText*: string
    errText*: string
    reportPath*: string
    markdownPath*: string

func usage*(): string {.raises: [].} =
  "usage:\n" &
  "  " & ToolName & " --pre <observe.json> --post <observe.json>\n" &
  "      [--metric admission|ready|verify] [--reps " & $DefaultReps &
  "] [--seed " & $DefaultSeed & "]\n" &
  "      [--alpha " & fmt2(DefaultAlpha) & "] [--allow-overlap]" &
  " [--charon-spans <json>]\n" &
  "      [--out DIR] [--json]\n" &
  "  " & ToolName & " --help\n\n" &
  "--pre/--post are two frozen '" & ObserveSchemaVersion & "' snapshots.\n" &
  "The cohort gate refuses (exit 1) unless the head_sha sets are disjoint and the\n" &
  "boundary refs differ; --allow-overlap keeps the verdict REFUSED and exits 0 so a\n" &
  "reviewer can still read the descriptive numbers. Inferential statistics (the\n" &
  "p-value and the bootstrap interval) are not published for a refused cohort.\n\n" &
  "Exit: 0 comparison produced, 1 cohort invalid, 2 input unreadable/schema mismatch.\n"

proc readCharonSpans(path, cohortKey: string):
    tuple[ok: bool, spans: seq[int], err: string] {.axiomEffect: IoEffect.} =
  ## Optional externally collected spans. The shape is intentionally small and
  ## strict: `{"pre": [seconds...], "post": [seconds...]}` (or the same under a
  ## per-cohort object with a `spans_seconds` array). Anything else is a schema
  ## mismatch rather than a partial read.
  if not fileExists(path):
    return (false, @[], "missing charon span file: " & path)
  var node: JsonNode
  try:
    node = parseJson(readFile(path))
  except CatchableError as e:
    return (false, @[], "unparsable JSON in " & path & ": " & e.msg)
  if node.isNil or node.kind != JObject:
    return (false, @[], "charon span file is not a JSON object")
  var arr = jsonAt(node, cohortKey)
  if arr.isNil or arr.kind != JArray:
    let inner = jsonAt(arr, "spans_seconds")
    if not inner.isNil and inner.kind == JArray:
      arr = inner
  if arr.isNil or arr.kind != JArray:
    return (false, @[], "charon span file has no '" & cohortKey &
                        "' array of integer seconds")
  for e in items(arr):
    if e.kind != JInt or e.getInt < 0:
      return (false, @[], "charon span entry in '" & cohortKey &
                          "' is not a non-negative integer")
    result.spans.add e.getInt
  (true, result.spans, "")

proc runCli*(args: seq[string]): CliOutcome {.axiomEffect: IoEffect.} =
  ## Argument parsing plus report production. Never calls quit, so fixtures can
  ## drive the real CLI path in-process without a subprocess or a built binary.
  var opts = Options(metric: mmAdmission, reps: DefaultReps, seed: DefaultSeed,
                     alpha: DefaultAlpha)
  var wantHelp = false
  var i = 0
  while i < args.len:
    template needValue(): string =
      if i + 1 >= args.len:
        return CliOutcome(code: ExitInputError,
                          errText: ToolName & ": missing value for " & args[i] & "\n")
      i = i + 1
      args[i]
    let arg = args[i]
    case arg
    of "--pre": opts.prePath = needValue()
    of "--post": opts.postPath = needValue()
    of "--out": opts.outDir = needValue()
    of "--charon-spans": opts.charonSpansPath = needValue()
    of "--json": opts.emitJson = true
    of "--allow-overlap": opts.allowOverlap = true
    of "--help", "-h": wantHelp = true
    of "--metric":
      let raw = needValue()
      let parsed = parseMetric(raw)
      if not parsed.ok:
        return CliOutcome(code: ExitInputError,
                          errText: ToolName & ": --metric expects admission|ready|" &
                            "verify, got '" & raw & "'\n")
      opts.metric = parsed.metric
    of "--reps":
      let raw = needValue()
      var v = 0
      try:
        v = parseInt(raw)
      except ValueError:
        return CliOutcome(code: ExitInputError,
                          errText: ToolName & ": --reps expects an integer, got '" &
                            raw & "'\n")
      if v < 1:
        return CliOutcome(code: ExitInputError,
                          errText: ToolName & ": --reps must be >= 1\n")
      opts.reps = v
    of "--seed":
      let raw = needValue()
      var v = 0
      try:
        v = parseInt(raw)
      except ValueError:
        return CliOutcome(code: ExitInputError,
                          errText: ToolName & ": --seed expects an integer, got '" &
                            raw & "'\n")
      opts.seed = int64(v)
    of "--alpha":
      let raw = needValue()
      var v = 0.0
      try:
        v = parseFloat(raw)
      except ValueError:
        return CliOutcome(code: ExitInputError,
                          errText: ToolName & ": --alpha expects a number in (0,1)," &
                            " got '" & raw & "'\n")
      if not (v > 0.0 and v < 1.0):
        return CliOutcome(code: ExitInputError,
                          errText: ToolName & ": --alpha must be in (0,1)\n")
      opts.alpha = v
    else:
      return CliOutcome(code: ExitInputError,
                        errText: ToolName & ": unknown argument '" & arg & "'\n" &
                          usage())
    i = i + 1

  if wantHelp:
    return CliOutcome(code: ExitProduced, outText: usage())
  if opts.prePath.len == 0 or opts.postPath.len == 0:
    return CliOutcome(code: ExitInputError,
                      errText: ToolName & ": --pre and --post are required\n" & usage())

  let preLoad = loadSnapshot(opts.prePath)
  if not preLoad.ok:
    return CliOutcome(code: ExitInputError,
                      errText: ToolName & ": pre snapshot unusable: " & preLoad.err & "\n")
  let postLoad = loadSnapshot(opts.postPath)
  if not postLoad.ok:
    return CliOutcome(code: ExitInputError,
                      errText: ToolName & ": post snapshot unusable: " &
                        postLoad.err & "\n")

  var preCharon = charonNoSource()
  var postCharon = charonNoSource()
  if opts.charonSpansPath.len > 0:
    let preSpans = readCharonSpans(opts.charonSpansPath, "pre")
    if not preSpans.ok:
      return CliOutcome(code: ExitInputError,
                        errText: ToolName & ": charon spans unusable: " &
                          preSpans.err & "\n")
    preCharon = charonFromSpans(preSpans.spans, opts.charonSpansPath)
    let postSpans = readCharonSpans(opts.charonSpansPath, "post")
    if not postSpans.ok:
      return CliOutcome(code: ExitInputError,
                        errText: ToolName & ": charon spans unusable: " &
                          postSpans.err & "\n")
    postCharon = charonFromSpans(postSpans.spans, opts.charonSpansPath)

  let comparison = buildComparison(preLoad.snap, postLoad.snap, opts,
                                   preCharon, postCharon)
  let report = comparisonJson(comparison)

  var outText = comparison.renderSummary()
  if opts.emitJson:
    outText = pretty(report, indent = 2) & "\n"
  var errText = ""
  if comparison.validity.verdict != cvValid:
    errText = ToolName & ": cohort invalid (" & $comparison.validity.verdict & "): " &
              comparison.validity.reason & "\n"
    if opts.allowOverlap:
      errText.add "  --allow-overlap: exiting 0, verdict stays REFUSED and no" &
                  " inferential statistic is published\n"
    else:
      errText.add "  refusing to publish a pre/post comparison over overlapping" &
                  " cohorts; pass --allow-overlap to inspect the descriptive numbers\n"

  var reportPath = ""
  var markdownPath = ""
  if opts.outDir.len > 0:
    createDir(opts.outDir)
    reportPath = opts.outDir / (ToolName & "_report.json")
    markdownPath = opts.outDir / (ToolName & "_report.md")
    writeFile(reportPath, pretty(report, indent = 2) & "\n")
    writeFile(markdownPath, comparison.renderMarkdown())

  var code = ExitProduced
  if comparison.validity.verdict != cvValid and not opts.allowOverlap:
    code = ExitCohortInvalid
  CliOutcome(code: code, outText: outText, errText: errText,
             reportPath: reportPath, markdownPath: markdownPath)

proc main() {.axiomEffect: IoEffect.} =
  let outcome = runCli(commandLineParams())
  if outcome.outText.len > 0:
    stdout.write(outcome.outText)
  if outcome.errText.len > 0:
    stderr.write(outcome.errText)
  if outcome.reportPath.len > 0:
    echo ToolName & ": wrote " & outcome.reportPath & " and " & outcome.markdownPath
  quit(outcome.code)

when isMainModule:
  main()
