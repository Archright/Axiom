func jsonAt*(n: JsonNode; key: string): JsonNode {.raises: [].} =
  ## Indexing a JsonNode raises KeyError; this returns nil instead, which keeps
  ## every reader in this module inside an empty raises list.
  if n.isNil or n.kind != JObject:
    return nil
  n.getOrDefault(key)

func jsonStrAt*(n: JsonNode; key: string): string {.raises: [].} =
  let v = jsonAt(n, key)
  if v.isNil or v.kind != JString: "" else: v.getStr()

func jsonIntAt*(n: JsonNode; key: string): int {.raises: [].} =
  let v = jsonAt(n, key)
  if v.isNil or v.kind != JInt: 0 else: v.getInt()

func jsonBoolAt*(n: JsonNode; key: string): bool {.raises: [].} =
  let v = jsonAt(n, key)
  not v.isNil and v.kind == JBool and v.getBool()

