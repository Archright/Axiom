proc renderMarkdown*(c: Comparison): string {.axiomEffect: IoEffect.} =
  var md = "# CI admission comparison (" & SchemaVersion & ")\n\n"
  md.add "- tool: `" & ToolName & "`\n"
  md.add "- metric: `" & metricField(c.opts.metric) & "`"
  if metricField(c.opts.metric) != MetricPreRegistered:
    md.add " (secondary; the pre-registered metric is " & MetricPreRegistered & ")"
  else:
    md.add " (pre-registered)"
  md.add "\n"
  md.add "- pre: `" & c.pre.path & "` (" & $c.x.len & " observed of " &
         $c.pre.cohortN & ")\n"
  md.add "- post: `" & c.post.path & "` (" & $c.y.len & " observed of " &
         $c.post.cohortN & ")\n\n"

  md.add "## Cohort validity\n\n"
  md.add "- verdict: **" & $c.validity.verdict & "**\n"
  md.add "- reason: " & c.validity.reason & "\n"
  md.add "- boundary check: " & c.validity.boundaryCheck & "\n"
  md.add "- shared head_shas: " & $c.validity.shared.len & " (observed: " &
         $c.validity.sharedObserved.len & ")\n\n"

  md.add "## Spread (whole seconds)\n\n"
  md.add "| cohort | phase | n | p50 | sd | variance | IQR | range | max | p95 |\n"
  md.add "|---|---|---:|---:|---:|---:|---:|---:|---:|---|\n"
  for key in PhaseKey:
    let rows = [(c.preSpread[key], "pre"), (c.postSpread[key], "post")]
    for pair in rows:
      let s = pair[0]
      md.add "| " & pair[1] & " | `" & $key & "` | " & $s.n & " | " & fmt2(s.p50) &
             " | " & fmt2(s.sd) & " | " & fmt2(s.variance) & " | " & fmt2(s.iqr) &
             " | " & $s.rangeSeconds & " | " & fmtSec(s.maxSeconds) & " | " &
             (if s.p95Status == "REPORTED": fmt2(s.p95) else: P95Incomplete) & " |\n"
  md.add "\nIQR uses the same estimator family as p50 (Hyndman-Fan 7); variance is" &
         " the sample variance. p95 is INCOMPLETE below n = " & $P95MinN &
         " (max and median are still reported).\n\n"

  md.add "## Headroom (derived, per cohort)\n\n"
  md.add "| cohort | quantity | n | p50 | min | max |\n|---|---|---:|---:|---:|---:|\n"
  let cohortRows = [(c.preRows, "pre"), (c.postRows, "post")]
  for cohort in cohortRows:
    for independent in [false, true]:
      let s = summarizeHeadroom(cohort[0], independent)
      md.add "| " & cohort[1] & " | `" &
             (if independent: "headroom_independent" else: "headroom_second") &
             "` | " & $s.n & " | " & (if s.n > 0: fmt2(s.p50) else: StatusUnknown) &
             " | " & (if s.minSeconds >= 0: fmtSec(s.minSeconds) else: StatusUnknown) &
             " | " & (if s.maxSeconds >= 0: fmtSec(s.maxSeconds) else: StatusUnknown) &
             " |\n"
  md.add "\n`headroom_independent` excludes contexts sharing a `workflow_path` with" &
         " the last finisher, so it is a conservative lower bound. A shared top" &
         " instant yields 0 and is recorded as `TIE_AT_MAX`.\n\n"

  md.add "## Test\n\n"
  md.add "- verdict: **" & $c.verdict & "**\n"
  md.add "- reason: " & c.reason & "\n"
  md.add "- n per arm: pre=" & $c.x.len & ", post=" & $c.y.len & "\n"
  md.add "- Mann-Whitney U: " & fmt2(c.mw.u)
  if c.withheld:
    md.add " (p withheld: cohort invalid)\n"
  else:
    md.add ", exact p = " & c.mw.pExact & " = " & fmt2(c.mw.p) & " (exact=" &
           $c.mw.exact & ", method `" & c.mw.methodName & "`)\n"
  md.add "- ties: " & $c.mw.tieGroups & " group(s), " & $c.mw.tiedValues &
         " pooled value(s)\n"
  md.add "- Hodges-Lehmann shift: " & fmt2(float(c.hlDoubled) / 2.0) & "s\n"
  md.add "- bootstrap: " & c.boot.status & " (" & $c.boot.distinctMedianCount &
         " distinct resample medians over " & $c.boot.reps & " reps, seed " &
         $c.boot.seed & ")\n"
  if c.mde.computed:
    md.add "- MDE: min |U - n1n2/2| = " & fmt2(c.mde.minAbsUDev) &
           " => detectable AUC <= " & fmt2(c.mde.detectableAuc) & " (" &
           c.mde.verdict & ")\n"
  else:
    md.add "- MDE: not computable at this n (" & c.mde.verdict & ")\n"

  md.add "\n## T_charon\n\n"
  let charonRows = [(c.preCharon, "pre"), (c.postCharon, "post")]
  for pair in charonRows:
    md.add "- " & pair[1] & ": " & pair[0].status
    if pair[0].reason.len > 0:
      md.add " (" & pair[0].reason & ")"
    md.add "\n"

  md.add "\n## Limitations (declared, not hidden)\n\n"
  for item in Limitations:
    md.add "- " & item & "\n"
  md

