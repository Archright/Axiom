func preRegisteredVerdict*(validity: CohortVerdict; mw: MwResult; mde: MdeResult;
                           n1, n2: int; alpha: float):
    tuple[verdict: TestVerdict, reason: string] {.raises: [].} =
  if validity != cvValid:
    return (tvRefused, "cohort gate: " & $validity &
            " - no inferential statistic is published for overlapping cohorts")
  if n1 < MinObservedPerArm or n2 < MinObservedPerArm:
    return (tvInconclusive, "sample floor: need >= " & $MinObservedPerArm &
            " observed per arm (pre=" & $n1 & ", post=" & $n2 & ")")
  if not mw.exact:
    return (tvInconclusive, "exact null unavailable at this n (method " & mw.methodName &
            "); the pre-registered primary test is exact, so an approximation is" &
            " never promoted to a verdict")
  if mw.p <= alpha:
    return (tvSignificant, "exact two-sided Mann-Whitney p = " & mw.pExact & " = " &
            fmt2(mw.p) & " <= alpha " & fmt2(alpha))
  if mde.verdict == VerdictUnderpowered:
    return (tvInconclusive, "not significant AND underpowered: the smallest" &
            " detectable effect at this n is larger than the observed separation," &
            " so a null result is absence of evidence, not evidence of no change")
  (tvNotSignificant, "not significant, and the sample could have resolved the" &
    " observed effect size, so the null is informative")

