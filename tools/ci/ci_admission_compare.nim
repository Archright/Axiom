func seqJson*(values: seq[string]): JsonNode {.raises: [].} =
  result = newJArray()
  for v in values:
    result.add %v

func countsJson*(entries: seq[tuple[key: string, count: int]]): JsonNode {.raises: [].} =
  result = newJObject()
  for e in entries:
    result[e.key] = %e.count

func spreadJson*(s: Spread): JsonNode {.raises: [].} =
  let p95: JsonNode = if s.p95Status == "REPORTED": %s.p95 else: %P95Incomplete
  %*{
    "n": s.n,
    "p50": (if s.n > 0: %s.p50 else: %StatusUnknown),
    "min": intOrUnknown(s.minSeconds),
    "max": intOrUnknown(s.maxSeconds),
    "variance": s.variance,
    "sd": s.sd,
    "iqr": s.iqr,
    "range": s.rangeSeconds,
    "p95": p95
  }

func sortedObservedShas*(s: Snapshot): seq[string] {.raises: [].} =
  var shas: seq[string] = @[]
