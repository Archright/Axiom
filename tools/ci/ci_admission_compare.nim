# 9. Hodges-Lehmann, bootstrap, minimum detectable effect
# ===========================================================================

func medianDoubled*(v: seq[int]): int64 {.raises: [].} =
  ## 2 * median of an integer sample, so an even-sized median is exact.
  if v.len == 0:
    return 0'i64
  var s = v
  s.sort()
  if s.len mod 2 == 1:
    return 2'i64 * int64(s[s.len div 2])
  int64(s[s.len div 2 - 1]) + int64(s[s.len div 2])

func hodgesLehmannDoubled*(x, y: seq[int]): int64 {.raises: [].} =
  ## 2 * median of all n1*n2 pairwise differences y_j - x_i.
  if x.len == 0 or y.len == 0:
    return 0'i64
  var diffs = newSeq[int64](x.len * y.len)
  var k = 0
  for a in x:
    for b in y:
      diffs[k] = int64(b) - int64(a)
      inc k
  diffs.sort()
  if diffs.len mod 2 == 1:
    return 2'i64 * diffs[diffs.len div 2]
  diffs[diffs.len div 2 - 1] + diffs[diffs.len div 2]

func hodgesLehmann*(x, y: seq[int]): float {.raises: [].} =
  float(hodgesLehmannDoubled(x, y)) / 2.0

func nextLcg*(state: int64): int64 {.raises: [].} =
  (LcgMultiplier * state + LcgIncrement) mod LcgModulus

type
  BootResult* = object
    reps*: int
    seed*: int64
    alpha*: float
    point*: float
    ciLow*: float
    ciHigh*: float
    width*: float
    distinctMedianCount*: int
    status*: string
    methodName*: string

func bootstrapMedianCi*(x, y: seq[int]; reps: int; seed: int64; alpha: float):
    BootResult {.raises: [].} =
  ## Percentile bootstrap CI on median(y) - median(x) from the fixed LCG stream.
  ## UNINFORMATIVE is emitted whenever the resample median support is too thin to
  ## define an interval: a zero-width CI there reflects missing information, not
  ## confidence.
  result = BootResult(reps: reps, seed: seed, alpha: alpha,
                      status: StatusUninformative,
                      methodName: "lcg-percentile-bootstrap")
  if x.len == 0 or y.len == 0 or reps < 1:
    return
  var state = seed mod LcgModulus
  if state < 0:
    state += LcgModulus
  var bx = newSeq[int](x.len)
  var by = newSeq[int](y.len)
  var shifts = newSeq[int64](reps)
  for r in 0 ..< reps:
    for i in 0 ..< x.len:
      state = nextLcg(state)
      bx[i] = x[int(state mod int64(x.len))]
    for i in 0 ..< y.len:
      state = nextLcg(state)
      by[i] = y[int(state mod int64(y.len))]
    shifts[r] = medianDoubled(by) - medianDoubled(bx)
  shifts.sort()
  var nDistinct = 0
  for i in 0 ..< reps:
    if i == 0 or shifts[i] != shifts[i - 1]:
      inc nDistinct
  result.distinctMedianCount = nDistinct
  result.point = (float(medianDoubled(y)) - float(medianDoubled(x))) / 2.0
  if reps >= 2:
    let loIdx = min(reps - 1, max(0, int(alpha / 2.0 * float(reps))))
    let hiIdx = min(reps - 1, max(0, int((1.0 - alpha / 2.0) * float(reps)) - 1))
    result.ciLow = float(shifts[loIdx]) / 2.0
    result.ciHigh = float(shifts[hiIdx]) / 2.0
    result.width = result.ciHigh - result.ciLow
  result.status = if nDistinct < 3 or result.width == 0.0: StatusUninformative
                  else: StatusInformative

type
  MdeResult* = object
    n1*: int
    n2*: int
    alpha*: float
    minAbsUDoubled*: int64
    minAbsUDev*: float
    detectableAuc*: float
    observedAbsUDoubled*: int64
    verdict*: string
    computed*: bool

func minDetectableEffect*(n1, n2: int; alpha: float): MdeResult {.raises: [].} =
  ## Smallest |U - n1n2/2| whose exact upper tail is <= alpha/2. This is the finest
  ## rank-scale separation the CURRENT n can resolve, expressed as a
  ## common-language AUC so it reads as "the test can only see effects at least
  ## this large". The upper tail comes from suffix sums over the exact U counts, so
  ## the search is O(n1*n2) rather than O((n1*n2)^2).
  result = MdeResult(n1: n1, n2: n2, alpha: alpha, minAbsUDoubled: -1,
                     minAbsUDev: -1.0, detectableAuc: 1.0,
                     verdict: VerdictUnderpowered)
  if n1 <= 0 or n2 <= 0:
    return
  let (ok, counts, total) = exactUDistribution(n1, n2)
  if not ok or total == 0'u64:
    return
  let centerDoubled = int64(n1) * int64(n2)
  var suffix = newSeq[uint64](counts.len + 1)
  for u in countdown(counts.len - 1, 0):
    suffix[u] = suffix[u + 1] + counts[u]
  let need = alpha / 2.0
  var dev = 0'i64
  while dev <= centerDoubled:
    # u >= n1n2/2 + dev  <=>  2u >= n1n2 + 2dev; the ceiling keeps the odd-product
    # case (n1n2 odd) on the correct side of the half-integer centre.
    let startU = int((centerDoubled + 2'i64 * dev + 1'i64) div 2'i64)
    var tail = 0'u64
    if startU <= 0:
      tail = total
    elif startU < suffix.len:
      tail = suffix[startU]
    if float(tail) / float(total) <= need:
      result.minAbsUDoubled = 2'i64 * dev
      result.minAbsUDev = float(dev)
      result.detectableAuc = (float(centerDoubled) / 2.0 - float(dev)) /
                             float(centerDoubled)
      result.computed = true
      return
    inc dev

func applyObservedEffect*(mde: var MdeResult; observedDevDoubled: int64)
    {.raises: [].} =
  ## POWERED means the sample could have resolved an effect of the observed size:
  ## the observed rank separation is at least the minimum detectable one.
  mde.observedAbsUDoubled = observedDevDoubled
  if mde.computed and observedDevDoubled >= mde.minAbsUDoubled:
    mde.verdict = VerdictPowered

