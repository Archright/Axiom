func fmt2*(x: float): string {.raises: [].} =
  ## Two-decimal fixed formatting without std/formatfloat, so no locale or
  ## platform formatting path enters the report.
  if x != x:
    return "nan"
  if x > 1.0e15 or x < -1.0e15:
    return "over-range"
  let scaled = int(x * 100.0 + (if x < 0.0: -0.5 else: 0.5))
  let neg = scaled < 0
  let mag = abs(scaled)
  (if neg: "-" else: "") & $(mag div 100) & "." &
    (if mag mod 100 < 10: "0" else: "") & $(mag mod 100)

func fmtSec*(x: int): string {.raises: [].} =
  if x < 0: "n/a" else: $x & "s"

func jsonOrUnknown*(s: string): JsonNode {.raises: [].} =
  if s.len > 0: %s else: %StatusUnknown

func intOrUnknown*(v: int): JsonNode {.raises: [].} =
  if v >= 0: %v else: %StatusUnknown

