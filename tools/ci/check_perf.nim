import std/[json, os, math]

const
  LatestFile = "data/benchmarks/perf_latest.json"
  BudgetFile = "data/benchmarks/perf_budget.json"

# Fail-open contract: this budget validator is not the perf gate — a missing
# input skips validation, but the skip must stay visibly non-silent (§0.9).
# perf_latest.json is an untracked execution artifact (gitignored) that
# `make perf-check` regenerates; before the first local run it legitimately
# does not exist. perf_budget.json IS tracked — its absence is reported
# separately so the two causes are never conflated.
if not fileExists(LatestFile) or not fileExists(BudgetFile):
  if not fileExists(LatestFile):
    echo "[PERF] latest missing (", LatestFile,
      " — untracked execution artifact, generated by `make perf-check`). Skipping budget validation."
  if not fileExists(BudgetFile):
    echo "[PERF] budget missing (", BudgetFile,
      " — tracked baseline). Skipping budget validation."
  quit(0)

let
  latest = parseJson(readFile(LatestFile))
  budget = parseJson(readFile(BudgetFile))

var hasRegression = false

for key, spec in budget.pairs:
  if latest.hasKey(key):
    let
      actualUs = latest[key].getFloat()
      budgetUs = spec["budget_us"].getFloat()
      maxPct = spec["max_allowed_regression_pct"].getFloat()
      limitUs = budgetUs * (1.0 + maxPct / 100.0)

    if actualUs > limitUs:
      echo "[PERF FAIL] ", key, ": ", int(actualUs), "us exceeded budget limit ", int(limitUs), "us (+", maxPct, "%)"
      hasRegression = true
    else:
      echo "[PERF PASS] ", key, ": ", int(actualUs), "us (Budget: ", int(budgetUs), "us)"
  else:
    echo "[PERF WARN] Unmonitored metric: ", key

if hasRegression:
  quit(1)
