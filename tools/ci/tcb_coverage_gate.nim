## tcb_coverage_gate.nim — TCB Module Test Coverage Enforcer
## Walks src/core/trusted/ and verifies each module has adequate test coverage.
## Reports CRITICAL (no test), WARNING (< 3 assertions), or PASS per module.
##
## Debt-anchored enforcement (mirrors quality_gate_runner / nimtry v2 ratchet):
## a frozen baseline (data/tcb_coverage_baseline.json) anchors the set of
## trusted modules that already lacked tests when the gate was activated.
## Only NEW untested modules fail the gate. The historical state (79/91
## untested at activation) was never satisfied anywhere in CI history and
## bulk-generating per-module stub tests would violate §0.7 (business-only
## test scope) / §0.8 (no stub files); the ratchet activates real
## anti-regression force going forward instead of leaving the gate dead.
## Refresh deterministically via --update-baseline after legitimately adding
## or closing test debt.
##
## Exit code: 1 if any NEW CRITICAL found (not in baseline), 0 otherwise.

import core/trusted/layer_declaration
import core/trusted/axiom_pragmas  ## axiomGate pragma (include chain: axiom_pragmas_macros)
axiomLayer "tools"
import std/[os, json, strutils, algorithm]



const
  trustedDir = "src/core/trusted"
  minAssertions = 3
  BaselinePath = "data/tcb_coverage_baseline.json"

type
  CoverageStatus = enum
    Pass, Warn, Critical

  ModuleReport = object
    name: string
    status: CoverageStatus
    assertionCount: int
    testPath: string

proc findRepoRoot(): string =
  var dir = getAppDir()
  while dir.len > 0:
    if fileExists(dir / ".axiom_root"):
      return dir
    let parent = parentDir(dir)
    if parent == dir:
      break
    dir = parent
  result = getAppDir() / ".." / ".."
  normalizePath(result)

proc isExcluded(filename: string): bool =
  filename.endsWith("_shadow.nim") or filename.endsWith("_types.nim")

proc countAssertions(filePath: string): int =
  let content = try:
    readFile(filePath)
  except IOError:
    return 0
  var count = 0
  for line in content.splitLines():
    let stripped = line.strip()
    if stripped.startsWith("#"):
      continue
    var i = 0
    while i <= stripped.len - 5:
      if stripped[i..i+4] == "check":
        inc count
        i += 5
      elif i <= stripped.len - 8 and stripped[i..i+7] == "doAssert":
        inc count
        i += 8
      else:
        inc i
  result = count

proc findTestFile(repoRoot: string, moduleName: string): string =
  let unitPath = repoRoot / "tests" / "unit" / moduleName & "_test.nim"
  if fileExists(unitPath):
    return unitPath
  let gatewayPath = repoRoot / "tests" / "gateway" / moduleName & "_feature_test.nim"
  if fileExists(gatewayPath):
    return gatewayPath
  return ""

proc loadAnchoredCriticals(repoRoot: string): seq[string] {.raises: [CatchableError].} =
  ## Read the anchored critical-module set from the frozen baseline.
  let path = repoRoot / BaselinePath
  if not fileExists(path):
    return @[]
  let node = parseJson(readFile(path))
  if node{"anchored_criticals"}.kind != JArray:
    return @[]
  for n in node["anchored_criticals"]:
    if n.kind == JString:
      result.add(n.getStr())

proc saveBaseline(repoRoot: string; criticals: seq[string]) {.raises: [CatchableError].} =
  ## Freeze the current critical set as the new baseline (ratchet refresh).
  var anchored = criticals
  anchored.sort()
  var node = newJObject()
  node["version"] = newJInt(1)
  node["note"] = newJString("Auto-generated by tcb_coverage_gate --update-baseline")
  var arr = newJArray()
  for m in anchored:
    arr.add(newJString(m))
  node["anchored_criticals"] = arr
  writeFile(repoRoot / BaselinePath, node.pretty() & "\n")

proc main() =
  let args = commandLineParams()
  var updateBaseline = false
  for a in args:
    if a == "--update-baseline":
      updateBaseline = true

  let repoRoot = findRepoRoot()
  let trustedPath = repoRoot / trustedDir

  if not dirExists(trustedPath):
    echo "ERROR: TCB directory not found: " & trustedPath
    quit(1)

  var reports: seq[ModuleReport]

  for kind, path in walkDir(trustedPath):
    if kind != pcFile:
      continue
    let filename = extractFilename(path)
    if not filename.endsWith(".nim"):
      continue
    if isExcluded(filename):
      continue

    let moduleName = filename[0..^5]  # strip .nim
    var report = ModuleReport(
      name: filename,
      status: Critical,
      assertionCount: 0,
      testPath: ""
    )

    let testFile = findTestFile(repoRoot, moduleName)
    if testFile.len == 0:
      report.status = Critical
    else:
      report.testPath = testFile
      let count = countAssertions(testFile)
      report.assertionCount = count
      if count >= minAssertions:
        report.status = Pass
      else:
        report.status = Warn

    reports.add(report)

  reports.sort(proc(a, b: ModuleReport): int =
    cmp(ord(a.status), ord(b.status))
  )

  var criticalCount = 0
  var criticalModules: seq[string] = @[]
  for r in reports:
    case r.status
    of Critical:
      inc criticalCount
      criticalModules.add(r.name)
      echo "[TCB:CRITICAL] " & r.name & " (no test)"
    of Warn:
      echo "[TCB:WARN] " & r.name & " (" & $r.assertionCount & " assertions)"
    of Pass:
      echo "[TCB:PASS] " & r.name

  echo ""
  echo "Total modules: " & $reports.len
  var passCount = 0
  var warnCount = 0
  for r in reports:
    if r.status == Pass: inc passCount
    elif r.status == Warn: inc warnCount
  echo "PASS: " & $passCount
  echo "WARN: " & $warnCount
  echo "CRITICAL: " & $criticalCount

  if updateBaseline:
    saveBaseline(repoRoot, criticalModules)
    echo "Baseline updated: " & $criticalModules.len & " critical module(s) anchored."
    quit(0)

  # Debt-anchored enforcement: only criticals NOT present in the frozen
  # baseline are regressions. Anchored entries remain visible debt.
  let anchored = loadAnchoredCriticals(repoRoot)
  var newCriticals: seq[string] = @[]
  for m in criticalModules:
    if m notin anchored:
      newCriticals.add(m)

  if newCriticals.len > 0:
    echo ""
    echo "NEW untested TCB module(s) not in baseline: " & $newCriticals.len
    for m in newCriticals:
      echo "  - " & m
    quit(1)
  if criticalCount > 0:
    echo ""
    echo "[TCB] " & $criticalCount & " anchored critical module(s) (baseline data/tcb_coverage_baseline.json); no regression."
  quit(0)

when isMainModule:
  main()
