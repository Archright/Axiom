const
  CriticalGateIds = [
    "gate-self-check",
    "unstaged-guard", "integrity-workflow", "architecture-config-gate"
  ]
type
  CorrectionAction* = enum
    caDisable        ## Disable the gate temporarily
    caAdjustTimeout  ## Increase timeout threshold
    caAlertOnly      ## Alert without auto-correction

  CorrectionCandidate* = object
    gateId*: string
    action*: CorrectionAction
    reason*: string
    healthReport*: GateHealthReport
func isCritical(gateId: string): bool {.raises: [].} =
  gateId in CriticalGateIds
func `$`*(a: CorrectionAction): string =
  case a
  of caDisable: "disable"
  of caAdjustTimeout: "adjust-timeout"
  of caAlertOnly: "alert-only"
proc identifyCandidates(baselinePath: string): seq[CorrectionCandidate] {.axiomIoBoundary.} =
  ## Identify gates that need correction based on telemetry vs baseline.
  let baseline = readJsonFile(baselinePath)
  if baseline.kind == JNull:
    logger.error("Baseline not found: " & baselinePath)
    return @[]

  for gateId, spec in baseline:
    let expectedRate = spec{"expectedPassRate"}.getFloat(0.9)
    let maxDur = spec{"maxDurationMs"}.getInt(5000)
    let crit = spec{"criticality"}.getStr("medium")
    let report = assessHealth(gateId, expectedRate, maxDur)

    if report.health == ghCritical and not isCritical(gateId):
      result.add(CorrectionCandidate(
        gateId: gateId, action: caDisable,
        reason: "Pass rate is 0% (" & $report.consecutiveFailures & " consecutive failures)",
        healthReport: report
      ))
    elif report.health == ghDegraded and crit == "low":
      result.add(CorrectionCandidate(
        gateId: gateId, action: caDisable,
        reason: "Degraded low-criticality gate: pass rate " &
                formatFloat(report.passRate * 100, ffDecimal, 1) & "%",
        healthReport: report
      ))
    elif report.avgDurationMs > maxDur.float * 2.0:
      result.add(CorrectionCandidate(
        gateId: gateId, action: caAdjustTimeout,
        reason: "Average duration " & formatFloat(report.avgDurationMs, ffDecimal, 0) &
                "ms exceeds 2x threshold (" & $(maxDur * 2) & "ms)",
        healthReport: report
      ))
proc sandboxVerify(repoRoot: string): bool {.axiomIoBoundary.} =
  ## Pre-flight: compile the topology generator + orchestrator to verify
  ## all compile-time assertions pass in a clean sandbox.
  logger.info("Sandbox: compiling generate_topology.nim...")
  let (outp1, code1) = execCmdEx(
    "nim c --hints:off --warnings:off " & repoRoot / "tools/build/generate_topology.nim"
  )
  if code1 != 0:
    logger.error("Sandbox: generate_topology.nim FAILED:\n" & outp1)
    return false

  logger.info("Sandbox: compiling gate_orchestrator.nim...")
  let (outp2, code2) = execCmdEx(
    "nim c --hints:off --warnings:off " & repoRoot / "src/core/gate/gate_orchestrator.nim"
  )
  if code2 != 0:
    logger.error("Sandbox: gate_orchestrator.nim FAILED:\n" & outp2)
    return false

  logger.info("Sandbox: all compile-time assertions PASSED")
  return true
func generatePRBody(candidates: seq[CorrectionCandidate]): string {.raises: [].} =
  result = "## [auto-heal] Gate Performance Correction\n\n"
  result &= "Generated: " & $now() & "\n\n"
  result &= "### Degraded Gates\n\n"
  result &= "| Gate | Health | Pass Rate | Avg Duration | Action |\n"
  result &= "|------|--------|-----------|-------------|--------|\n"
  for c in candidates:
    result &= "| " & c.gateId & " | " & $c.healthReport.health & " | " &
              formatFloat(c.healthReport.passRate * 100, ffDecimal, 1) & "% | " &
              formatFloat(c.healthReport.avgDurationMs, ffDecimal, 0) & "ms | " &
              $c.action & " |\n"
  result &= "\n### Reason\n\n"
  for c in candidates:
    result &= "- **" & c.gateId & "**: " & c.reason & "\n"
  result &= "\n> ⚠️ This PR was auto-generated by the self-healing agent.\n"
  result &= "> Compile-time assertions verified in sandbox before PR creation.\n"
proc writePrBody(repoRoot: string; body: string) {.axiomIoBoundary.} =
  let prBodyPath = repoRoot / "logs/self_heal_pr_body.md"
  var f: File
  if open(f, prBodyPath, fmWrite):
    f.write(body)
    f.close()
    logger.info("Self-heal: PR body written to " & prBodyPath)
  else:
    logger.error("Self-heal: failed to write PR body to " & prBodyPath)
proc runSelfHeal*(repoRoot: string; dryRun: bool = true) {.axiomIoBoundary.} =
  let baselinePath = repoRoot / "data/gate_performance_baseline.json"
  let candidates = identifyCandidates(baselinePath)

  if candidates.len == 0:
    logger.info("Self-heal: no degraded gates detected")
    return

  logger.info("Self-heal: found " & $candidates.len & " correction candidates")
  for c in candidates:
    logger.info("  - " & c.gateId & ": " & $c.action & " (" & c.reason & ")")

  let body = generatePRBody(candidates)

  if dryRun:
    logger.info("Self-heal: dry run — not creating PR")
    writePrBody(repoRoot, body)
    return

  # Sandbox verification before PR creation
  if not sandboxVerify(repoRoot):
    logger.error("Self-heal: sandbox verification FAILED — aborting PR creation")
    return

  writePrBody(repoRoot, body)
  logger.info("Self-heal: run 'gh pr create --body-file logs/self_heal_pr_body.md' to create PR")

when isMainModule:
  let repoRoot = getCurrentDir()
  let dryRun = paramCount() < 1 or paramStr(1) != "--execute"
  runSelfHeal(repoRoot, dryRun)

