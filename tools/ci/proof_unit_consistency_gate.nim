func stripLineComment(line: string): string =
  ## Comment-stripped source line (quote-aware). A commented-out writer is not
  ## a writer; keeping it in the scan universe would report documentation as
  ## drift.
  var i = 0
  var inQuote = false
  while i < line.len:
    let ch = line[i]
    if inQuote:
      if ch == '\\':
        inc i
      elif ch == '"':
        inQuote = false
    else:
      if ch == '"':
        inQuote = true
      elif ch == '#':
        return line[0 ..< i]
    inc i
  line

func normalizeToken(t: string): string =
  ## Trim the call/quote punctuation a command operand is wrapped in.
  var s = t.strip()
  while s.len > 0 and s[0] in TokenTrimChars:
    s = s[1 .. ^1].strip()
  while s.len > 0 and s[^1] in TokenTrimChars:
    s = s[0 .. ^2].strip()
  s

func isRedirectToken(t: string): bool =
  ## Shell redirection / pipe operand — carries no configuration value.
  '>' in t or '|' in t or '<' in t

func isAssembledToken(t: string): bool =
  ## Concatenation / interpolation marker: the operand's value is not a literal
  ## the scan can read, so the site's value class is unresolvable.
  '&' in t or '+' in t or '$' in t or '{' in t or '}' in t

func isWordBoundaryBefore(body: string, pos: int): bool =
  if pos == 0:
    return true
  let prev = body[pos - 1]
  prev notin IdentChars and prev != '.' and prev != '-' and prev != '/'

func firstTokenOnLine(line: string, vocabulary: openArray[string]): string =
  ## First vocabulary token on `line`, at an IDENTIFIER boundary. The boundary
  ## is what separates a sink call from a different proc whose name merely ends
  ## in the sink's suffix: `removeFile(p)` contains `moveFile(` and DELETES the
  ## target, so counting it as a writer inverts the check.
  for v in vocabulary:
    var at = 0
    while true:
      let pos = line.find(v, at)
      if pos < 0:
        break
      at = pos + v.len
      if isWordBoundaryBefore(line, pos):
        return v
  ""

func gitTokenStart(body: string, fromPos, direction: int): int =
  ## Start offset of the nearest whitespace-delimited token containing "git"
  ## (case-insensitive) in `direction` from `fromPos`, or -1. The token may be a
  ## bare `git`, a resolved binary path, or an assembled binary variable.
  if direction > 0:
    var i = fromPos
    while i < body.len:
      if body[i] in {' ', '\t'}:
        inc i
        continue
      let start = i
      while i < body.len and body[i] notin {' ', '\t'}:
        inc i
      if body[start ..< i].toLowerAscii.contains("git"):
        return start
  else:
    var i = fromPos - 1
    while i >= 0:
      if body[i] in {' ', '\t'}:
        dec i
        continue
      var j = i
      while j >= 0 and body[j] notin {' ', '\t'}:
        dec j
      if body[j + 1 .. i].toLowerAscii.contains("git"):
        return j + 1
      i = j
  -1

func gitConfigSegmentStarts(body: string): seq[int] =
  ## Start offsets of the git-config invocations on one line. Each `config`
  ## subcommand whose command expression names a git binary contributes the
  ## start of its nearest git-naming token; duplicate starts collapse.
  result = @[]
  var at = 0
  while true:
    let pos = body.find("config", at)
    if pos < 0:
      break
    at = pos + 6
    if not isWordBoundaryBefore(body, pos) or
       (pos + 6 < body.len and body[pos + 6] in IdentChars):
      continue
    let start = gitTokenStart(body, pos, -1)
    if start >= 0 and start notin result:
      result.add(start)
  result.sort()

func gitConfigSegments(body: string): seq[string] =
  ## Every git-config invocation text on one line, in either lexical form: the
  ## bare `git config …` command, or an assembled `<git-binary> … " config …"`
  ## whose command expression still names git (gate_self_check.nim,
  ## infrastructure/git_config.nim). An invocation runs from its command
  ## expression up to the next invocation's, so a VALUE that happens to contain
  ## the letters "git" (e.g. `.githooks`) does not truncate it. A line may carry
  ## several invocations; each is classified on its own.
  let starts = gitConfigSegmentStarts(body)
  for i, start in starts:
    let stop = if i + 1 < starts.len: starts[i + 1] else: body.len
    result.add(body[start ..< stop])

func classifyGitConfigCall(site: string, seg: string): tuple[cls: SiteClass, detail: string] =
  ## Reader/writer rule (deliberate, both directions):
  ##   - an explicit query flag (--get/--list/…) is a READ, whatever else it
  ##     carries — a read can never change the hooks authority;
  ##   - a mutating flag (--replace-all/--unset/--add/…) is a WRITE of the
  ##     hooks authority even with no value operand (unsetting the key disables
  ##     the hook directory just as surely as setting it elsewhere);
  ##   - otherwise a lexically visible dotted key decides: a value operand makes
  ##     it a WRITE, no value operand makes it a READ (`git config <key>` queries).
  ## Anything whose key is not lexically visible AND whose operands are
  ## assembled is unclassified — the scan refuses to guess.
  result = (cls: scInert, detail: "")
  var toks: seq[string] = @[]
  for t in seg.splitWhitespace():
    let n = normalizeToken(t)
    if n.len > 0:
      toks.add(n)
  if toks.len < 2:
    return
  var hasQuery = false
  var hasMutating = false
  for t in toks:
    if t in GitQueryFlags:
      hasQuery = true
    if t in GitMutatingFlags:
      hasMutating = true
  var operands: seq[string] = @[]
  var keyIdx = -1
  var assembledOperand = false
  var i = 2
  while i < toks.len:
    let t = toks[i]
    if t in GitScopeFlags:
      if t in GitValuedFlags:
        inc i
      inc i
      continue
    if t in GitQueryFlags or t in GitMutatingFlags:
      inc i
      continue
    if isRedirectToken(t):
      inc i
      continue
    if t.contains("."):
      # git-config grammar is `<key> <value>`: the FIRST dotted operand is the
      # key. A value such as `.githooks` is itself dotted and must not be
      # mistaken for one.
      if keyIdx < 0:
        keyIdx = operands.len
    if isAssembledToken(t):
      assembledOperand = true
    operands.add(t)
    inc i
  if hasQuery:
    return (cls: scReader, detail: "git config query")
  if operands.len == 0:
    return
  if keyIdx < 0:
    if assembledOperand:
      return (cls: scUnclassified,
              detail: "git config call with assembled arguments and no lexically visible key: " & site)
    return
  if operands[keyIdx].toLowerAscii != HooksPathKey.toLowerAscii:
    return (cls: scInert, detail: "git config key " & operands[keyIdx])
  if hasMutating:
    return (cls: scWriter, detail: "mutating git config flag on " & HooksPathKey)
  var values: seq[string] = @[]
  for t in operands[keyIdx + 1 .. ^1]:
    if not isRedirectToken(t):
      values.add(t)
  if values.len == 0:
    return (cls: scReader, detail: "git config " & HooksPathKey & " query")
  if assembledOperand:
    return (cls: scUnclassified,
            detail: "core.hooksPath writer whose value is assembled, not literal: " & site)
  result = (cls: scWriter, detail: values.join(" "))

func flattenPathExpr(expr: string): string =
  ## Path expression → one comparable text. Parenthesis characters are skipped
  ## rather than terminating the expression, so a call such as
  ## `getCurrentDir() / "config" / "gates.json"` still flattens to its path tail.
  ## An expression assembled by concatenation or interpolation yields "" — an
  ## unresolvable target, which the closed-world rule reports as unclassified
  ## instead of guessing.
  result = ""
  if expr.contains("&") or expr.contains("+") or expr.contains("$"):
    return
  for ch in expr:
    if ch in {' ', '\t', '"', '\'', '`', '\\', '(', ')'}:
      continue
    result.add(ch)

func isPurePathExpr(expr: string): bool =
  ## True iff an initializer is a PATH expression: identifiers, string literals
  ## and `/` operators only — no call, no concatenation, no arithmetic. Only a
  ## pure-path binding may be spliced into another target: a binding whose value
  ## is computed (`let cache = loadHashCache()`, `let json = parseJson(…)`) is
  ## a local variable, and substituting it turns a resolved path into garbage
  ## that no longer names the artifact.
  if expr.contains("&") or expr.contains("+") or expr.contains("$"):
    return false
  for ch in expr:
    if ch in {'(', ')', '[', ']', '{', '}', '=', ';', '!', '~', '^', '@', '#', '%'}:
      return false
    if ch in IdentChars or ch in {' ', '\t', '"', '\'', '/', '.', '\\', '`', ':', '-'}:
      continue
    return false
  true

func parseBindingStatement(stmt: string, bindings: var Table[string, string],
                           rawBindings: var Table[string, string]) =
  ## `NAME = <expr>` / `NAME: T = <expr>` → binding, keyed by NAME. The
  ## flattened form feeds target resolution; the verbatim form feeds the exec
  ## axis (R5), which needs the literals an assembly expression carried.
  ## Only pure-path initializers enter the flattened table (see
  ## isPurePathExpr); the verbatim table keeps every declaration because a
  ## command expression is assembled from all of them.
  var i = 0
  while i < stmt.len and stmt[i] in {' ', '\t'}:
    inc i
  var name = ""
  while i < stmt.len and stmt[i] in IdentChars:
    name.add(stmt[i])
    inc i
  if name.len == 0 or name[0] notin AlphaChars:
    return
  var depth = 0
  var eqAt = -1
  while i < stmt.len:
    let ch = stmt[i]
    if ch in {'(', '[', '{'}:
      inc depth
    elif ch in {')', ']', '}'}:
      dec depth
    elif ch == '=' and depth == 0 and (i + 1 >= stmt.len or stmt[i + 1] != '='):
      eqAt = i
      break
    inc i
  if eqAt < 0:
    return
  let expr = stmt[eqAt + 1 .. ^1]
  let verbatim = expr.strip()
  if verbatim.len == 0:
    return
  rawBindings[name] = verbatim
  if isPurePathExpr(verbatim):
    let flat = flattenPathExpr(verbatim)
    if flat.len > 0:
      bindings[name] = flat

func collectLetBindings(lines: seq[string],
                        rawBindings: var Table[string, string]): Table[string, string] =
  ## Every path binding the file declares, flattened for target resolution.
  ## Covered forms (resolver rule R1/R2):
  ##   - single-line `let` / `var` / `const` declarations,
  ##   - members of multi-line `const` / `let` / `var` BLOCKS (the repository's
  ##     dominant path idiom — a block of module-level constants),
  ##   - `name: T = <expr>` default parameters inside proc signatures.
  ## Block membership is tracked by indentation, and nesting is counted so a
  ## second block opened inside the first does not end it early.
  result = initTable[string, string]()
  var blockDepth = 0
  for line in lines:
    let raw = stripLineComment(line)
    if raw.strip.len == 0:
      continue
    let indented = raw[0] in {' ', '\t'}
    let stmt = raw.strip()
    if blockDepth > 0:
      if indented:
        parseBindingStatement(stmt, result, rawBindings)
        continue
      dec blockDepth
      if blockDepth > 0:
        continue
    var kwLen = 0
    for kw in DeclarationKeywords:
      if stmt == kw:
        kwLen = stmt.len
        break
      if stmt.startsWith(kw) and stmt.len > kw.len and stmt[kw.len] in {' ', '\t'}:
        kwLen = kw.len
        break
    if kwLen == 0:
      continue
    let rest = stmt[kwLen .. ^1].strip()
    if rest.len == 0:
      inc blockDepth
      continue
    parseBindingStatement(rest, result, rawBindings)

func resolvePathExpr(expr: string, bindings: Table[string, string]): string =
  ## Substitute let-bound path fragments into a sink target (bounded depth, so a
  ## cyclic binding table cannot diverge). "" = unresolvable.
  ##
  ## Only PURE-PATH bindings are spliced (see isPurePathExpr), which is what
  ## keeps a later pass from rebinding the segments of an already-literal path:
  ## `.cache/debt/hashes.json` has no computable binding named `cache` to be
  ## rewritten with, so the resolved path survives the next pass intact.
  var cur = flattenPathExpr(expr)
  if cur.len == 0:
    return ""
  for _ in 0 ..< 4:
    var changed = false
    var outBuf = ""
    var i = 0
    while i < cur.len:
      if cur[i] in AlphaChars:
        var j = i
        while j < cur.len and cur[j] in IdentChars:
          inc j
        let ident = cur[i ..< j]
        if bindings.hasKey(ident):
          outBuf.add(bindings.getOrDefault(ident, ""))
          changed = true
        else:
          outBuf.add(ident)
        i = j
      else:
        outBuf.add(cur[i])
        inc i
    cur = outBuf
    if not changed:
      break
  cur

func splitCallArguments(body, sinkToken: string): seq[string] =
  ## Arguments of the sink call on `body`, at depth 0 of the call. Empty when
  ## the token is a bare identifier form (an open-array sink referenced without
  ## a parenthesis) or the call is not present on this line.
  result = @[]
  let openRel = sinkToken.rfind('(')
  if openRel < 0:
    return
  let openPos = body.find(sinkToken)
  if openPos < 0:
    return
  var depth = 0
  var argStart = openPos + openRel + 1
  var j = argStart
  while j < body.len:
    let ch = body[j]
    if ch in {'(', '[', '{'}:
      inc depth
    elif ch in {')', ']', '}'}:
      dec depth
      if depth == 0:
        let arg = body[argStart ..< j]
        if arg.strip.len > 0:
          result.add(arg)
        return
    elif ch == ',' and depth == 0:
      result.add(body[argStart ..< j])
      argStart = j + 1
    inc j

func sinkTargetArgument(body, sinkToken: string): string =
  ## The argument a sink call PERSISTS TO (resolver rule R4). A rename/move
  ## writes its destination — the last argument — while every other sink writes
  ## its first argument. Falls back to the call tail for open-array sinks
  ## invoked without a parenthesis.
  if sinkToken in DestinationSinkTokens:
    let destArgs = splitCallArguments(body, sinkToken)
    if destArgs.len > 1:
      return destArgs[^1]
  let args = splitCallArguments(body, sinkToken)
  if args.len == 0:
    if sinkToken.rfind('(') < 0:
      return body
    return ""
  args[0]

# ── proc signatures and write wrappers (resolver rule R3) ──

func procHeadKeyword(stmt: string): string =
  for head in TopLevelDeclHeads:
    if stmt.startsWith(head):
      return head
  ""

func splitTopLevelCommas(text: string): seq[string] =
  result = @[]
  var depth = 0
  var start = 0
  for i, ch in text:
    if ch in {'(', '[', '{'}:
      inc depth
    elif ch in {')', ']', '}'}:
      dec depth
    elif ch == ',' and depth == 0:
      result.add(text[start ..< i])
      start = i + 1
  result.add(text[start .. ^1])

func leadingParamName(param: string): string =
  var s = param.strip()
  while s.len > 0 and s[0] == '*':
    s = s[1 .. ^1].strip()
  var name = ""
  for ch in s:
    if ch in IdentChars:
      name.add(ch)
    else:
      break
  if name.len > 0 and name[0] notin AlphaChars:
    return ""
  name

func hasDepthZeroAssign(text: string): bool =
  ## True iff `text` carries a `=` outside any bracket nesting — the marker of a
  ## parameter default initializer (`name: string = "…"`).
  var depth = 0
  for i, ch in text:
    if ch in {'(', '[', '{'}:
      inc depth
    elif ch in {')', ']', '}'}:
      dec depth
    elif ch == '=' and depth == 0 and (i + 1 >= text.len or text[i + 1] != '='):
      return true
  false

func collectProcInfos(lines: seq[string]): seq[ProcInfo] =
  ## Every `proc` / `func` / `iterator` / `template` / `method` signature with
  ## its parameter names and body line range. Regex-free; the parameter list may
  ## span lines and its body ends at the next top-level declaration head.
  result = @[]
  var i = 0
  while i < lines.len:
    let stmt = stripLineComment(lines[i]).strip()
    if procHeadKeyword(stmt).len == 0:
      inc i
      continue
    let openAt = stmt.find('(')
    if openAt < 0:
      inc i
      continue
    var depth = 0
    var closeLine = i
    var closeCol = -1
    var k = i
    while k < lines.len:
      let cur = if k == i: stmt else: stripLineComment(lines[k])
      var c = 0
      while c < cur.len:
        if cur[c] == '(':
          inc depth
        elif cur[c] == ')':
          dec depth
          if depth == 0:
            closeLine = k
            closeCol = c
            break
        inc c
      if closeCol >= 0:
        break
      inc k
    if closeCol < 0:
      inc i
      continue
    var sigText = if closeLine == i: stmt[openAt + 1 ..< closeCol]
              else: stmt[openAt + 1 .. ^1]
    if closeLine > i:
      for extra in i + 1 .. closeLine:
        sigText.add(" ")
        sigText.add(stripLineComment(lines[extra]).strip())
    var name = ""
    var c = openAt - 1
    while c >= 0 and stmt[c] in {' ', '\t'}:
      dec c
    var endPos = c
    while c >= 0 and stmt[c] in IdentChars:
      dec c
    for p in c + 1 .. endPos:
      name.add(stmt[p])
    var params: seq[string] = @[]
    var defaulted: seq[bool] = @[]
    for part in splitTopLevelCommas(sigText):
      let pn = leadingParamName(part)
      if pn.len > 0:
        params.add(pn)
        defaulted.add(hasDepthZeroAssign(part))
    var bodyEnd = lines.len - 1
    var e = closeLine + 1
    while e < lines.len:
      let rawNext = stripLineComment(lines[e])
      let nextStmt = rawNext.strip()
      if nextStmt.len > 0 and rawNext.len > 0 and rawNext[0] notin {' ', '\t'} and
         procHeadKeyword(nextStmt).len > 0:
        bodyEnd = e - 1
        break
      inc e
    result.add((name: name, params: params, defaulted: defaulted,
                headerEnd: i, bodyEnd: bodyEnd))
    i = closeLine + 1

func collectWriteWrappers(lines: seq[string]): seq[WriteWrapper] =
  ## Local write wrappers: procs whose body ends in a persistence call whose
  ## target argument is one of the proc's OWN parameters (resolver rule R3).
  ## The target parameter's own default decides WHERE the site is reported:
  ##   - no default → the wrapper's CALL SITES are the sites (one hop), because
  ##     the artifact is only known at the call site;
  ##   - default present → the wrapper's OWN sink line is the site, resolved
  ##     through that default (rules R2 + R3 together).
  result = @[]
  for p in collectProcInfos(lines):
    if p.name.len == 0 or p.params.len == 0:
      continue
    var resolved = -1
    var viaDefault = false
    var body = p.bodyEnd
    while body >= p.headerEnd:
      let lineBody = stripLineComment(lines[body])
      let sinkToken = firstTokenOnLine(lineBody, RawPersistencePatterns)
      if sinkToken.len > 0:
        let rawTarget = sinkTargetArgument(lineBody, sinkToken).strip()
        for pi, pname in p.params:
          if rawTarget == pname and pi > resolved:
            resolved = pi
            viaDefault = pi < p.defaulted.len and p.defaulted[pi]
            body = p.headerEnd
            break
      dec body
    if resolved >= 0:
      result.add((name: p.name, paramIdx: resolved, viaDefault: viaDefault))

func wrapperBodyLineSet(lines: seq[string], wrappers: seq[WriteWrapper]): HashSet[int] =
  ## Line indices belonging to a recognized write wrapper's own signature/body.
  ## A wrapper resolved through its CALL SITES does not also report its internal
  ## sink (one write, one site); a wrapper resolved through a parameter DEFAULT
  ## keeps its internal sink as the site.
  result = initHashSet[int]()
  var names: seq[string] = @[]
  for wrec in wrappers:
    if not wrec.viaDefault:
      names.add(wrec.name)
  for p in collectProcInfos(lines):
    if p.name notin names:
      continue
    for i in p.headerEnd .. p.bodyEnd:
      result.incl(i)

func callTargetIndex(body, procName: string): int =
  ## Start offset of `procName(` on `body` at an identifier boundary, or -1.
  var at = 0
  while true:
    let pos = body.find(procName, at)
    if pos < 0:
      return -1
    at = pos + procName.len
    if not isWordBoundaryBefore(body, pos):
      continue
    var i = pos + procName.len
    while i < body.len and body[i] in {' ', '\t'}:
      inc i
    if i < body.len and body[i] == '(':
      return pos

proc enumerateSinkSites(rel, raw: string): seq[SinkHit] =
  ## Every persistence site in one scanned file, with its resolved target:
  ## direct sink calls, plus ONE hop through every local write wrapper's call
  ## site (resolver rule R3). Sinks inside a wrapper's own body are not listed
  ## separately unless their target parameter carries a default (R2).
  result = @[]
  let lines = raw.splitLines()
  var rawBindings: Table[string, string]
  let bindings = collectLetBindings(lines, rawBindings)
  let wrappers = collectWriteWrappers(lines)
  let skipLines = wrapperBodyLineSet(lines, wrappers)
  for idx, line in lines:
    if idx in skipLines:
      continue
    let body = stripLineComment(line)
    if body.strip.len == 0:
      continue
    let sinkToken = firstTokenOnLine(body, RawPersistencePatterns)
    if sinkToken.len > 0:
      result.add((file: rel, line: idx + 1,
                  target: resolvePathExpr(sinkTargetArgument(body, sinkToken), bindings),
                  body: body))
    for w in wrappers:
      if w.viaDefault:
        continue
      let at = callTargetIndex(body, w.name)
      if at < 0:
        continue
      let args = splitCallArguments(body, w.name & "(")
      var target = ""
      if w.paramIdx < args.len:
        target = resolvePathExpr(args[w.paramIdx], bindings)
      result.add((file: rel, line: idx + 1, target: target, body: body))
  result.sort(proc (a, b: SinkHit): int = cmp(a.line, b.line))

func isStandaloneTokenBefore(body: string, pos: int): bool =
  ## True iff the identifier at `pos` is a WHOLE token of the expression, not a
  ## fragment of a path already spelled out. The `nim` in `/usr/bin/nim` and in
  ## `tools/debt_engine.nim` belongs to the path it sits in; rebinding it
  ## rewrites a path into a different one (`tools/debt_engine./usr/bin/nim`) and
  ## the delegate then resolves to nothing.
  if pos == 0:
    return true
  let prev = body[pos - 1]
  prev notin IdentChars and prev != '.' and prev != '/' and prev != '-'

func expandCommandExpression(body: string,
                             rawBindings: Table[string, string]): string =
  ## The literal text a command expression can be read from: the line plus the
  ## verbatim initializer of each bound identifier it mentions (bounded depth,
  ## so a cyclic binding table cannot diverge).
  var cur = body
  for _ in 0 ..< 3:
    var outBuf = ""
    var changed = false
    var i = 0
    while i < cur.len:
      if cur[i] in AlphaChars:
        var j = i
        while j < cur.len and cur[j] in IdentChars:
          inc j
        let ident = cur[i ..< j]
        if not isStandaloneTokenBefore(cur, i):
          outBuf.add(ident)
          i = j
          continue
        if rawBindings.hasKey(ident):
          outBuf.add(rawBindings.getOrDefault(ident, ""))
          changed = true
        else:
          outBuf.add(ident)
        i = j
      else:
        outBuf.add(cur[i])
        inc i
    cur = outBuf
    if not changed:
      break
  cur

proc enumerateExecSites(rel, raw: string,
                        delegateNames: HashSet[string]): seq[SinkHit] =
  ## Command-execution sites that delegate to another repository tool
  ## (resolver rule R5). A delegate is named either by its repo-relative
  ## source path (`tools/x.nim`) or by its build output (`bin/x`). The target
  ## is the resolved delegate path, so the caller can map it back to the
  ## artifacts that file writes. "" = a command that names no known tool.
  result = @[]
  let lines = raw.splitLines()
  var rawBindings: Table[string, string]
  discard collectLetBindings(lines, rawBindings)
  for idx, line in lines:
    let body = stripLineComment(line)
    if body.strip.len == 0:
      continue
    if firstTokenOnLine(body, ExecDelegateTokens).len == 0:
      continue
    let expanded = expandCommandExpression(body, rawBindings)
    var delegate = ""
    for tok in expanded.splitWhitespace():
      let t = normalizeToken(tok)
      if t.len == 0:
        continue
      if delegateNames.contains(t):
        delegate = t
        break
      if t.startsWith("bin/") and delegateNames.contains(t["bin/".len .. ^1]):
        delegate = t["bin/".len .. ^1]
        break
    result.add((file: rel, line: idx + 1, target: delegate, body: body))
  result.sort(proc (a, b: SinkHit): int = cmp(a.line, b.line))

func hasScannedExtension(rel: string): bool =
  for ext in SourceScanExts:
    if rel.endsWith(ext):
      return true
  false

func isSourceSkipPath(rel: string): bool =
  let wrapped = "/" & rel & "/"
  for seg in SourceSkipDirs:
    if ("/" & seg & "/") in wrapped:
      return true
  false

proc scanSourceFiles(repoRoot: string, unclassified: var seq[string]): seq[string] =
  ## Every tracked-source text file in the (h)/(i) scan universe, repo-root
  ## relative and sorted (deterministic iteration order).
  result = @[]
  for sub in SourceScanDirs:
    let root = repoRoot / sub
    if not dirExists(root):
      continue
    try:
      for path in walkDirRec(root):
        if not fileExists(path):
          continue
        let rel = path[repoRoot.len + 1 .. ^1]
        if isSourceSkipPath(rel):
          continue
        if rel.startsWith(".githooks/") or hasScannedExtension(rel):
          result.add(rel)
    except OSError:
      unclassified.add("unable to walk source dir: " & sub & " (OSError)")
  for name in SourceScanRoots:
    if fileExists(repoRoot / name):
      result.add(name)
  result.sort()

func isRegisteredGatesWriter(rel: string, lineNo: int): bool =
  for e in RegisteredGatesWriters:
    if e.file == rel and e.line == lineNo:
      return true
  false

proc gatesJsonWriteSites(repoRoot: string, files: seq[string],
                         unclassified: var seq[string]): seq[WriteSite] =
  ## Closed-world, sink-anchored enumeration of every site that WRITES
  ## config/gates.json. A site qualifies on the resolved write target (literal,
  ## let-bound path concatenation, or a write-wrapper argument); a gates.json
  ## mention on a sink line whose target does not resolve is unclassified and
  ## fails closed.
  result = @[]
  for rel in files:
    let raw = readFileLenient(repoRoot / rel)
    if raw.len == 0:
      continue
    for hit in enumerateSinkSites(rel, raw):
      let site = rel & ":" & $(hit.line)
      if hit.target.contains("config/gates.json"):
        result.add((file: rel, line: hit.line))
      elif hit.body.contains("gates.json"):
        if hit.target.contains("gates.json"):
          unclassified.add("config/gates.json written outside the config/ artifact: " & site)
        elif hit.target.len == 0:
          unclassified.add("config/gates.json write target unresolved: " & site)
        else:
          unclassified.add("config/gates.json sink line resolves to a different target (" &
                           hit.target & "): " & site)

func clip(s: string): string =
  const Limit = 96
  if s.len <= Limit: s
  else: s[0 ..< Limit] & "…"

func firstDifferenceHint(onDisk, projected: string): string =
  let a = onDisk.splitLines()
  let b = projected.splitLines()
  var idx = 0
  while idx < a.len and idx < b.len and a[idx] == b[idx]:
    inc idx
  if idx >= a.len and idx >= b.len:
    return "trailing byte difference at line " & $(idx + 1) & " (line count " & $a.len & " vs " & $b.len & ")"
  let diskLine = if idx < a.len: a[idx] else: "<eof>"
  let projLine = if idx < b.len: b[idx] else: "<eof>"
  $(idx + 1) & ": on-disk \"" & clip(diskLine) & "\" vs projection \"" &
    clip(projLine) & "\""

