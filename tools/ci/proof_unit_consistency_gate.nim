# (h) config/gates.json projection + writer set
#
# config/gates.json is a machine-generated PROJECTION of the gate topology:
# tools/sync_topology.nim is its generating authority and owns the exact bytes
# (gateRuntimeProjectionJson). Three residual writers remain sanctioned (a frozen
# runtime default and two temp-dir test fixtures); every other writer is a
# competing authority. Both properties are enforced, and neither is redundant:
#
#   h.1 projection equality — a competing writer CAN emit bytes byte-identical to
#       the projection, which satisfies h.1 while still being a competing
#       writer. Byte equality therefore proves nothing about writer cardinality,
#       and h.2/h.3 must not be "simplified" into h.1.
#   h.2/h.3 writer set — the closed-world write set (sink-anchored, see below)
#       must be a SUBSET of the registered set. Any unregistered site is a
#       competing authority; a candidate whose target cannot be resolved is
#       unclassified and fails closed.
#   h.4 registry hygiene — every registered entry must still RESOLVE to the
#       registered artifact at its recorded location, so the residual registry
#       cannot rot silently and any writer removal forces a registry update in
#       the same commit. Liveness alone is not enough: a sink token on the
#       registered line whose resolved target is some OTHER path would satisfy a
#       token-presence test while the registered writer had quietly stopped
#       writing the projection.
# ═══════════════════════════════════════════════════════════════════════════

