func valueOf(line, key: string): string =
  ## Extract `key = "value"` → `value` (empty if not a match). Manifest values
  ## are plain paths; no escape handling needed.
  let s = line.strip()
  let prefix = key & " = \""
  if s.startsWith(prefix):
    for i in prefix.len ..< s.len:
      if s[i] == '"':
        return s[prefix.len ..< i]
  ""

func manifestFileValues(raw: string): seq[string] =
  ## Every `file = "…"` value in the auto-generated gate manifest.
  for line in raw.splitLines():
    let v = valueOf(line, "file")
    if v.len > 0:
      result.add(v)

proc authorityPathExists(repoRoot, p: string): bool =
  ## Plain path → it must exist as a file or directory; a trailing `/**` glob
  ## (setup-axiom-toolchain/** style trust-surface entry) → its directory must
  ## exist. Deterministic, disk-only.
  if p.endsWith("/**"):
    result = dirExists(repoRoot / p[0 ..< p.len - 3])
  else:
    result = fileExists(repoRoot / p) or dirExists(repoRoot / p)

func mergeCliIdsNonEmpty(source: string): bool =
  ## True iff merge_cli.nim's RequiredWorkflowIds initializer declares ≥1 entry
  ## (regex-free: entries are `("job", <int>)` tuples; return on first `("`).
  let mark = source.find("RequiredWorkflowIds")
  if mark < 0:
    return false
  let arr = source.find("@[", mark)
  if arr < 0:
    return false
  var i = arr + 2
  while i < source.len and source[i] != ']':
    if source[i] == '"' and source[i - 1] == '(':
      return true
    inc i
  false

