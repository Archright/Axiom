  ## One discovered or registered (artifact, role) site; the (j) role-set
  ## comparison is stated over exactly this shape.
  RoleEntry = tuple[file: string, line: int, artifact: string, role: string]

  ## Closed-world classification of one scanned site. scUnclassified mirrors the
  ## decUnknown fail-closed rule of core/gate/trust_commit_scope_scan.nim: a
  ## candidate the vocabulary cannot resolve is never silently ignored.
