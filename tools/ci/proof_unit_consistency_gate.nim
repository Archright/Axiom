proc findRepoRoot(cwd: string): string =
  var dir = cwd
  for _ in 0 ..< 10:
    if fileExists(dir / ".axiom_root"):
      return dir
    let parent = dir.parentDir()
    if parent == dir:
      break
    dir = parent
  cwd

proc main() {.axiomEffect: IOEffect.} =
  let cwd = try: getCurrentDir() except CatchableError: "."
  let repoRoot = findRepoRoot(cwd)
  var failures: seq[string] = @[]

  # (a) catalog
  let fA = catalogFailures()
  # (b) selector
  let selectorRaw = readFileLenient(repoRoot / SelectorPath)
  let fB = selectorFailures(selectorRaw)
  # (c) oracle
  let oracleRaw = readFileLenient(repoRoot / OraclePath)
  let fC = oracleFailures(oracleRaw)
  # (d) docs + deleted declaration site
  let specRaw = readFileLenient(repoRoot / TiersSpecPath)
  let adrRaw = readFileLenient(repoRoot / Adr0019Path)
  var fD = docSectionFailures(TiersSpecPath, specRaw, TiersSectionMarker)
  fD.add docSectionFailures(Adr0019Path, adrRaw, AdrSectionMarker)
  if fileExists(repoRoot / DeletedDeclPath):
    fD.add("recreated deleted declaration site: " & DeletedDeclPath &
           " (A0 removed it; catalog is the sole W-axis authority)")
  # (e) manifest
  let manifestRaw = readFileLenient(repoRoot / ManifestPath)
  let fE = manifestFailures(manifestRaw)
  # (f) ghost authority — disk existence of policy/manifest references
  let admissionRaw = readFileLenient(repoRoot / AdmissionPolicyPath)
  let mergeCliRaw  = readFileLenient(repoRoot / MergeCliPath)
  let fF = ghostAuthorityFailures(admissionRaw, manifestRaw, mergeCliRaw, repoRoot)
  # (g) stale contract — normative docs/config prose must not resurrect
  #     deleted workflows; ADR-0017 A1 decision text must stay bound
  var fG = staleContractFailures(repoRoot)
  let adr17Raw = readFileLenient(repoRoot / Adr0017Path)
  fG.add staleBindingTokenFailures(specRaw, adr17Raw)
  # (h) config/gates.json projection + registered writer set — the byte
  #     comparison (h.1) and the writer-set comparison (h.2/h.3) are independent
  #     verdicts; registry hygiene is h.4.
  var uH: seq[string] = @[]
  var fH = gatesJsonProjectionFailures(repoRoot, uH)
  fH.add gatesJsonAuthorityFailures(repoRoot, uH)
  # (i) core.hooksPath writer singularity — two-axis closed-world scan.
  var uI: seq[string] = @[]
  let fI = hooksPathAuthorityFailures(repoRoot, uI)
  # (j) debt registry + projections — per-artifact role sets, plus the exec axis.
  var uJ: seq[string] = @[]
  let fJ = debtRegistryRoleFailures(repoRoot, uJ)

  echo ""
  echo "════════════════════════════════════════════════════════════"
  echo "  A0′ PROOF-UNIT CONSISTENCY GATE (2차 fail-closed 안전장치)"
  echo "════════════════════════════════════════════════════════════"

  template report(name: string, fails: seq[string]) =
    if fails.len == 0:
      echo "  PASS  " & name
    else:
      echo "  FAIL  " & name
      for f in fails:
        echo "        - " & f

  # An unclassified candidate is not a drift verdict but an unclosed scan
  # universe: the gate cannot conclude either way, so the check reports
  # INCONCLUSIVE and the run fails closed at the environment-error exit code
  # instead of printing PASS.
  template reportClosedWorld(name: string, fails: seq[string], uncls: seq[string]) =
    if fails.len == 0 and uncls.len == 0:
      echo "  PASS  " & name
    else:
      echo (if uncls.len > 0: "  INCONCLUSIVE  " else: "  FAIL  ") & name &
        (if uncls.len > 0: " — scan universe not closed (exit 2)" else: "")
      for f in fails:
        echo "        - " & f
      for u in uncls:
        echo "        - " & u

  report "(a) catalog internal integrity", fA
  report "(b) selector ↔ catalog", fB
  report "(c) soundness oracle ↔ catalog", fC
  report "(d) duplicate-declaration reintroduction guard", fD
  report "(e) gate-axis namespace collision", fE
  report "(f) ghost authority (policy/manifest references exist)", fF
  report "(g) stale contract (deleted-workflow prose + A1 binding)", fG
  reportClosedWorld "(h) gates.json projection + registered writer set", fH, uH
  reportClosedWorld "(i) core.hooksPath writer singularity", fI, uI
  reportClosedWorld "(j) debt registry + projections role sets", fJ, uJ

  let total = fA.len + fB.len + fC.len + fD.len + fE.len + fF.len + fG.len +
              fH.len + fI.len + fJ.len
  let unclassifiedTotal = uH.len + uI.len + uJ.len
  echo ""
  if unclassifiedTotal > 0:
    echo "  EXIT 2: " & $unclassifiedTotal & " unclassified candidate(s) — scan universe not closed (fail closed)."
    quit(2)
  elif total == 0:
    echo "  EXIT 0: W-axis projections consistent — proof_unit_catalog is the sole authority."
    quit(0)
  else:
    echo "  EXIT 1: " & $total & " drift violation(s) detected — fail closed."
    quit(1)

when isMainModule:
