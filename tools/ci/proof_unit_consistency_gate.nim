# (c) oracle ↔ Catalog
# ═══════════════════════════════════════════════════════════════════════════

proc oracleFailures(source: string): seq[string] =
  result = @[]
  if source.len == 0:
    result.add("unreadable oracle catalog: " & OraclePath)
    return
  var data: JsonNode
  try:
    data = parseJson(source)
  except CatchableError:
    result.add("oracle JSON parse error: " & OraclePath)
    return
  if data.kind != JArray:
    result.add("oracle catalog root is not a JSON array: " & OraclePath)
    return
  let catIds = catalogIds()
  var failures: seq[string] = @[]
  var reported: seq[string] = @[]
  # iterative walk (deterministic; no recursion depth concerns)
  var stack: seq[JsonNode] = @[data]
  while stack.len > 0:
    let node = stack.pop()
    case node.kind
    of JString:
      for t in extractWTokens(node.str):
        if t notin catIds:
          let shown = node.str
          let ctxLen = if shown.len > 48: 48 else: shown.len
          let msg = "oracle W-id reference outside catalog (\"" &
                    shown[0 ..< ctxLen] & "…\"): " & t
          if msg notin reported:
            reported.add(msg)
            failures.add(msg)
    of JObject:
      for _, v in node:
        stack.add(v)
    of JArray:
      for item in node:
        stack.add(item)
    of JNull, JBool, JInt, JFloat:
      discard
  result.add(failures)

