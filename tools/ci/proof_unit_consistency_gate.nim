proc gatesJsonAuthorityFailures(repoRoot: string,
                                unclassified: var seq[string]): seq[string] =
  ## (h.2/h.3) closed-world writer set + (h.4) registry hygiene.
  result = @[]
  let files = scanSourceFiles(repoRoot, unclassified)
  if files.len == 0:
    unclassified.add("no tracked source files found in the (h)/(i) scan universe (root: " & repoRoot & ")")
    return
  let sites = gatesJsonWriteSites(repoRoot, files, unclassified)
  if sites.len == 0:
    unclassified.add("no " & GatesProjectionPath & " writer found — writer-set extraction returned empty (fail closed)")
    return
  for site in sites:
    if not isRegisteredGatesWriter(site.file, site.line):
      result.add("unregistered " & GatesProjectionPath & " writer (competing authority): " &
                 site.file & ":" & $(site.line))
  # (h.4) registry hygiene — a vanished sink fails, so the residual registry
  # cannot rot and a writer removal forces a registry update. A live sink token
  # is NOT enough: the RESOLVED target on the registered line must still be the
  # registered artifact, otherwise a writer that stopped writing the projection
  # would pass on token presence alone.
  for e in RegisteredGatesWriters:
    if e.line < 1:
      result.add("registered writer has no recorded sink line: " & e.file & " (" & e.role & ")")
      continue
    let raw = readFileLenient(repoRoot / e.file)
    if raw.len == 0:
      result.add("registered writer file unreadable: " & e.file & " (" & e.role & ")")
      continue
    let lines = raw.splitLines()
    if e.line > lines.len:
      result.add("registered writer sink not live — line " & $(e.line) & " is past end of " &
                 e.file & " (" & e.role & ")")
      continue
    var hitsAtLine: seq[SinkHit] = @[]
    for hit in enumerateSinkSites(e.file, raw):
      if hit.line == e.line:
        hitsAtLine.add(hit)
    if hitsAtLine.len == 0:
      result.add("registered writer sink not live at " & e.file & ":" & $(e.line) &
                 " (" & e.role & " — no persistence sink on that line)")
      continue
    var resolvedProjection = false
    for hit in hitsAtLine:
      if hit.target.contains("config/gates.json"):
        resolvedProjection = true
    if not resolvedProjection:
      let seen = hitsAtLine[0].target
      result.add("registered writer target drift at " & e.file & ":" & $(e.line) &
                 " (" & e.role & " — resolved target is '" &
                 (if seen.len > 0: seen else: "<unresolved>") &
                 "', expected the " & GatesProjectionPath & " artifact)")

# ═══════════════════════════════════════════════════════════════════════════
# (i) core.hooksPath writer singularity — closed world, two axes
#
# Axis A (git-config invocation axis): every tracked-source site that runs
# `git config …` through a command-execution API. This axis exists because a
# sink-only scan misses the dominant writer form — `git config` mutates
# .git/config through git itself, so no file-write sink is involved.
#
# Axis B (persistence-sink axis): every tracked-source site that reaches a
# persistence sink whose target resolves to a git config path, or whose written
# content mentions the key. This axis catches an indirect rewrite of
# .git/config that never spells the git-config command.
#
# The only legal classified hit is DeclaredHooksWriter persisting
# DeclaredHooksValue. Everything else that classifies as a writer is a competing
# authority (exit 1). A candidate that matches the vocabulary but cannot be
# classified — ambiguous grammar, a value assembled through concatenation, an
# unresolved write target — fails closed with exit code 2, because the design
# goal is zero undetected writers and a silently ignored candidate is exactly
# the failure mode being removed.
#
# Lexical boundary (stated so a reader does not over-claim coverage): the key
# must be lexically visible in the invocation's argument list. An invocation
# whose key literal lives on another line is reported at that assembly site,
# because the assembly site's operands carry the key and are therefore
# unresolvable — but an invocation assembled from a key held in a variable whose
# literal appears on a non-command line is outside this vocabulary's reach. The
# check makes no claim beyond the vocabulary it scans.
# ═══════════════════════════════════════════════════════════════════════════

const GitConfigPathTokens = [".git/config", ".git/config.worktree"]

func isGitConfigPath(target: string): bool =
  for tok in GitConfigPathTokens:
    if tok in target:
      return true
  false

func declaredHooksValuesFromDoc(raw: string): seq[DocStatement] =
  ## Every value the declared-SSOT document states for core.hooksPath, with its
  ## line. Source-level extraction only: the LIVE git config is deliberately
  ## never read — a static admissibility check must not depend on mutable
  ## per-clone state (the dev clone and the pushed snapshot differ). Both
  ## statement forms are read — `core.hooksPath=<value>` and
  ## "sets `core.hooksPath` to `<value>`" — and EVERY statement must agree, so a
  ## document that contradicts itself is drift rather than being silently
  ## resolved by reading order.
  var ln = 0
  for line in raw.splitLines():
    inc ln
    let s = line.strip()
    if HooksPathKey notin s:
      continue
    let assign = s.find(HooksPathKey & "=")
    if assign >= 0:
      var v = s[assign + HooksPathKey.len + 1 .. ^1].strip()
      if v.len > 0:
        let sp = v.find({' ', '\t'})
        if sp >= 0:
          v = v[0 ..< sp]
        while v.len > 0 and v[0] in {'`', '"'}:
          v = v[1 .. ^1]
        while v.len > 0 and v[^1] in {'`', '"', ',', ';'}:
          v = v[0 .. ^2]
        # A sentence-final period is punctuation; a leading dot is path syntax.
        while v.len > 1 and v[^1] == '.' and v[0] != '.':
          v = v[0 .. ^2]
      if v.len > 0:
        result.add((line: ln, value: v))
    let prose = s.find("to `")
    if prose >= 0:
      let rest = s[prose + 3 .. ^1]
      if rest.len > 0 and rest[0] == '`':
        let endIdx = rest.find('`', 1)
        if endIdx > 1:
          result.add((line: ln, value: rest[1 ..< endIdx]))

func mentionsHooksKey(body: string): bool =
  ## The FULL key literal must be visible. A bare `hooksPath` mention (a JSON
  ## field name, an identifier, log prose) is not a key-visible invocation and
  ## stays out of the writer universe.
  body.toLowerAscii.contains("core.hookspath")

proc hooksPathAuthorityFailures(repoRoot: string,
                                unclassified: var seq[string]): seq[string] =
  result = @[]
  let files = scanSourceFiles(repoRoot, unclassified)
  if files.len == 0:
    unclassified.add("no tracked source files found in the (h)/(i) scan universe (root: " & repoRoot & ")")
    return
  var classifiedSites = 0
  var declaredWriterSeen = false
  for rel in files:
    let raw = readFileLenient(repoRoot / rel)
    if raw.len == 0:
      continue
    let lines = raw.splitLines()
    for idx, line in lines:
      let body = stripLineComment(line)
      let site = rel & ":" & $(idx + 1)
      let mentionsKey = mentionsHooksKey(body)
      # ── Axis A ──
      if mentionsKey and firstTokenOnLine(body, CommandExecutionTokens).len > 0:
        let segments = gitConfigSegments(body)
        if segments.len == 0:
          # Unknown exec wrapper: the key is handed to a command-execution API
          # that does not spell a git-config command, so the site's class is not
          # resolvable from source.
          unclassified.add("Axis A: core.hooksPath reaches a command-execution " &
                           "context with no lexically visible git-config command " &
                           "(unknown exec wrapper): " & site)
        for seg in segments:
          let cls = classifyGitConfigCall(site, seg)
          case cls.cls
          of scInert:
            discard
          of scReader:
            inc classifiedSites
          of scWriter:
            inc classifiedSites
            if rel != DeclaredHooksWriter:
              result.add("competing core.hooksPath writer (Axis A): " & site &
                         " — git config " & HooksPathKey & " " & cls.detail)
            elif cls.detail != DeclaredHooksValue:
              result.add("declared core.hooksPath writer value drift: " & site &
                         " — expected " & DeclaredHooksValue & ", found " & cls.detail)
            else:
              declaredWriterSeen = true
          of scUnclassified:
            unclassified.add("Axis A: " & cls.detail)
    # ── Axis B ── (shared resolver: direct sinks + write-wrapper call sites)
    for hit in enumerateSinkSites(rel, raw):
      let sinkSite = rel & ":" & $(hit.line)
      let sinkMentionsKey = mentionsHooksKey(hit.body)
      if not (sinkMentionsKey or isGitConfigPath(hit.target)):
        continue
      inc classifiedSites
      if isGitConfigPath(hit.target):
        if sinkMentionsKey:
          result.add("competing core.hooksPath writer (Axis B): " & sinkSite &
                     " — persistence sink rewrites a git config path")
        else:
          unclassified.add("Axis B: opaque write to a git config path, key not " &
                           "lexically visible: " & sinkSite)
      elif sinkMentionsKey and hit.target.len == 0:
        unclassified.add("Axis B: core.hooksPath write target unresolved: " & sinkSite)
  if classifiedSites == 0:
    unclassified.add("no core.hooksPath candidate extracted from the scan universe — " &
                     "vocabulary/extraction drift (fail closed)")
  elif not declaredWriterSeen:
    result.add("declared core.hooksPath writer absent: " & DeclaredHooksWriter &
               " must persist " & HooksPathKey & " " & DeclaredHooksValue)
  # Declared value ↔ declared SSOT document (source-level comparison only).
  let docRaw = readFileLenient(repoRoot / HooksValueSpecDoc)
  if docRaw.len == 0:
    unclassified.add("unreadable hooks spec document: " & HooksValueSpecDoc)
  else:
    for stated in declaredHooksValuesFromDoc(docRaw):
      if stated.value != DeclaredHooksValue:
        result.add(HooksValueSpecDoc & ":" & $(stated.line) & " declares " &
                   HooksPathKey & "=" & stated.value & " but the declared writer persists " &
                   DeclaredHooksValue)

