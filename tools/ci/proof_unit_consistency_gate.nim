func selectorFailures(source: string): seq[string] =
  result = @[]
  if source.len == 0:
    result.add("unreadable selector source: " & SelectorPath)
    return
  # Catalog-consumption invariant: the selector must still import the catalog.
  var imported = false
  for line in source.splitLines():
    let s = line.strip()
    if (s.startsWith("import ") or s.startsWith("from ")) and
       "gate/proof_unit_catalog" in s:
      imported = true
  if not imported:
    result.add("selector no longer imports gate/proof_unit_catalog (Catalog consumption broken)")
  # Every W-id string literal in the selector must exist in the catalog
  # (semantic-rule hardcodes; the selector's own static assert is re-verified
  # here independently).
  let catIds = catalogIds()
  var checked: seq[string] = @[]
  for region in extractQuotedRegions(source):
    for t in extractWTokens(region):
      if t notin checked:
        checked.add(t)
        if t notin catIds:
          result.add("selector W-id reference outside catalog: " & t)

