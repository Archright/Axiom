func catalogIds(): seq[string] =
  result = @[]
  for u in ProofUnitCatalog:
    result.add(u.id)

func catalogFailures(): seq[string] =
  result = @[]
  var seen: seq[string]
  for u in ProofUnitCatalog:
    if u.id in seen:
      result.add("duplicate unit id in ProofUnitCatalog: " & u.id)
    seen.add(u.id)
    if u.id notin ExpectedUnitIds:
      result.add("unit id outside expected W1..W11 set: " & u.id)
    if u.name.len == 0:
      result.add("empty name on unit " & u.id)
    if u.tier notin [ptL0, ptL1, ptL2]:
      result.add("invalid tier value on " & u.id & ": " & $u.tier)
    if u.pathPatterns.len == 0:
      result.add("empty pathPatterns on " & u.id)
    if isNaN(u.durationMin) and u.id != "W9":
      result.add("NaN (UNKNOWN) duration on non-W9 unit: " & u.id)
    if not isNaN(u.durationMin) and u.durationMin < 0.0:
      result.add("negative duration on " & u.id & ": " & $u.durationMin)
    # subunits are W4-only sub-stage ids per the catalog schema
    if u.subunits.len > 0 and u.id != "W4":
      result.add("non-empty subunits on non-W4 unit " & u.id & ": " & $u.subunits)
    if u.id == "W4" and u.subunits.len != W4SubStageIds.len:
      result.add("W4 subunits count != " & $W4SubStageIds.len & ": " & $u.subunits)
    for s in u.subunits:
      if s notin W4SubStageIds:
        result.add("unknown sub-stage id on " & u.id & ": " & s)
    var subSeen: seq[string]
    for s in u.subunits:
      if s in subSeen:
        result.add("duplicate subunit in " & u.id & ": " & s)
      subSeen.add(s)
  if seen.len != ExpectedUnitIds.len:
    result.add("unit count " & $seen.len & " != expected " & $ExpectedUnitIds.len)
  for expected in ExpectedUnitIds:
    if expected notin seen:
      result.add("missing unit in ProofUnitCatalog: " & expected)

