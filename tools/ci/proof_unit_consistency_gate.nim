func isRegisteredDebtRoleEntry(rel: string, lineNo: int, artifact, role: string): bool =
  for e in RegisteredDebtRoleEntries:
    if e.file == rel and e.line == lineNo and e.artifact == artifact and e.role == role:
      return true
  false

func artifactBaseName(path: string): string =
  let idx = path.rfind('/')
  if idx >= 0: path[idx + 1 .. ^1] else: path

func targetHitsArtifact(target, artifact: string): bool =
  ## True iff a resolved sink target addresses `artifact`. The match is at a
  ## PATH-SEGMENT boundary: `test_debt_registry.json` and
  ## `tests/specs/algebraic_registry.json` are different files from the
  ## artifact, however similar their names are.
  if target.len == 0:
    return false
  let base = artifactBaseName(artifact)
  if target == base or target == artifact:
    return true
  target.endsWith("/" & base)

func lineMentionsArtifact(body, artifact: string): bool =
  ## Lexical identity of the artifact on the site's own line. Used only to
  ## decide whether an unresolvable site must fail closed (rule R6).
  body.contains(artifactBaseName(artifact))

func targetAddressesRepoRoot(target, artifact: string): bool =
  target == artifact or target.endsWith("/" & artifact)

func targetResolvesIntoTempDir(target, artifact: string): bool =
  ## A temp-dir fixture writes into a SANDBOX root, not into the repo-root
  ## artifact: its target either carries a temp marker or is addressed to a
  ## root that does not spell the artifact's repo-root path at all.
  let lowered = target.toLowerAscii
  for marker in TempDirMarkers:
    if marker in lowered:
      return true
  not targetAddressesRepoRoot(target, artifact)

func debtSiteRole(rel, target: string, artifact: ArtifactSpec): string =
  ## Exactly one role per (site, artifact). A test file that resolves into a
  ## temp dir holds the residual fixture role; everything else — including a
  ## test file that resolves to the repo-root artifact — holds the owner role,
  ## so a test can never launder a competing authority into a fixture.
  if rel.startsWith("tests/") and targetResolvesIntoTempDir(target, artifact.path):
    return RoleTestFixture
  artifact.ownerRole

proc debtRegistryRoleFailures(repoRoot: string,
                              unclassified: var seq[string]): seq[string] =
  result = @[]
  let files = scanSourceFiles(repoRoot, unclassified)
  if files.len == 0:
    unclassified.add("no tracked source files found in the (j) scan universe (root: " & repoRoot & ")")
    return
  var delegateNames = initHashSet[string]()
  for rel in files:
    if rel.startsWith("tools/") and rel.endsWith(".nim"):
      delegateNames.incl(rel)
      delegateNames.incl(rel["tools/".len .. ^1])

  # ── pass 1: persistence sites, bucketed by (artifact, role) ──
  var discovered: seq[RoleEntry] = @[]
  var fileRoles = initTable[string, Table[string, string]]()
  for rel in files:
    let raw = readFileLenient(repoRoot / rel)
    if raw.len == 0:
      continue
    for hit in enumerateSinkSites(rel, raw):
      for artifact in DebtArtifacts:
        if targetHitsArtifact(hit.target, artifact.path):
          let role = debtSiteRole(rel, hit.target, artifact)
          discovered.add((file: hit.file, line: hit.line,
                          artifact: artifact.path, role: role))
          # A file that writes an artifact under its owner role IS that
          # artifact's authority; a mixed file is reported as the owner so the
          # delegate inherits the stricter role (fail closed).
          var perFile = fileRoles.getOrDefault(rel, initTable[string, string]())
          perFile[artifact.path] = role
          fileRoles[rel] = perFile
        elif lineMentionsArtifact(hit.body, artifact.path):
          unclassified.add(artifact.path & " sink target unresolved (resolved '" &
                           (if hit.target.len > 0: hit.target else: "<none>") &
                           "'): " & rel & ":" & $(hit.line))

  # ── pass 2: exec axis (R5) — delegating to a writer is being a writer ──
  for rel in files:
    let raw = readFileLenient(repoRoot / rel)
    if raw.len == 0:
      continue
    for hit in enumerateExecSites(rel, raw, delegateNames):
      let site = rel & ":" & $(hit.line)
      if hit.target.len == 0:
        for artifact in DebtArtifacts:
          if lineMentionsArtifact(hit.body, artifact.path):
            unclassified.add(artifact.path & " reached through a command-execution site " &
                             "with no resolvable repository tool: " & site)
        continue
      let perFile = fileRoles.getOrDefault(hit.target, initTable[string, string]())
      for artifactPath, role in perFile:
        discovered.add((file: rel, line: hit.line, artifact: artifactPath, role: role))

  # ── j.1/j.3/j.4/j.5: per-artifact role-set verdicts ──
  for artifact in DebtArtifacts:
    var ownerCount = 0
    for d in discovered:
      if d.artifact != artifact.path:
        continue
      if d.role == artifact.ownerRole:
        inc ownerCount
      elif d.role != RoleTestFixture:
        # TEST_FIXTURE is the sanctioned residual role; any other role over this
        # artifact is one no registry entry covers.
        result.add("unregistered role '" & d.role & "' over " & artifact.path & ": " &
                   d.file & ":" & $(d.line))
    if ownerCount == 0:
      result.add("no " & artifact.path & " " & artifact.ownerRole & " found — " &
                 "role-set extraction returned empty (fail closed)")
    for d in discovered:
      if d.artifact != artifact.path:
        continue
      if not isRegisteredDebtRoleEntry(d.file, d.line, d.artifact, d.role):
        result.add("unregistered " & artifact.path & " " & d.role & ": " &
                   d.file & ":" & $(d.line) & " (competing authority)")
    # (j.4) registry hygiene — a registered entry must still be a live site of
    # its own artifact under its own role.
    for e in RegisteredDebtRoleEntries:
      if e.artifact != artifact.path:
        continue
      if e.line < 1:
        result.add("registered " & artifact.path & " " & e.role &
                   " has no recorded sink line: " & e.file)
        continue
      let raw = readFileLenient(repoRoot / e.file)
      if raw.len == 0:
        result.add("registered " & artifact.path & " " & e.role &
                   " file unreadable: " & e.file)
        continue
      var liveTarget = ""
      var sawSite = false
      for hit in enumerateSinkSites(e.file, raw):
        if hit.line == e.line:
          sawSite = true
          liveTarget = hit.target
      if not sawSite:
        result.add("registered " & artifact.path & " " & e.role & " sink not live at " &
                   e.file & ":" & $(e.line) & " (no persistence site on that line)")
        continue
      if not targetHitsArtifact(liveTarget, artifact.path):
        result.add("registered " & artifact.path & " " & e.role & " target drift at " &
                   e.file & ":" & $(e.line) & " — resolved target is '" &
                   (if liveTarget.len > 0: liveTarget else: "<unresolved>") &
                   "', expected the " & artifact.path & " artifact")
        continue
      let liveRole = debtSiteRole(e.file, liveTarget, artifact)
      if liveRole != e.role:
        result.add("registered " & artifact.path & " role drift at " & e.file & ":" &
                   $(e.line) & " — recorded " & e.role & ", computed " & liveRole)
      elif e.role == RoleTestFixture and
           not targetResolvesIntoTempDir(liveTarget, artifact.path):
        result.add("registered " & artifact.path & " fixture does not resolve into a " &
                   "temp dir at " & e.file & ":" & $(e.line) & " — resolved target '" &
                   liveTarget & "' addresses the repo-root artifact")

