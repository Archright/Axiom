# (j) debt registry + projections — per-artifact role sets
#
# Three artifacts, one owner role each, compared as role-SETS and not as a
# shared sink count:
#
#   data/debt_registry.json            owner role SSOT_MUTATOR
#   docs/DEBT_REGISTRY.md              owner role SOLE_PROJECTION_GENERATOR
#   src/generated/debt_constants.nim   owner role SOLE_PROJECTION_GENERATOR
#
# tools/debt_engine.nim legitimately holds BOTH the registry-mutation role and
# the projection-generation role; counting its sinks into one total would
# collapse those two roles and make "1 mutator + 1 generator" read as "2
# writers". Each artifact therefore carries its own role-set, and the assertions
# are stated per artifact:
#
#   j.1 discovered ⊆ registered, per (artifact, role) — a site holding a role no
#       registry entry covers is a competing authority (exit 1);
#   j.2 an unregistered-or-unresolvable candidate is INCONCLUSIVE (exit 2);
#   j.3 an artifact whose role-set is empty fails closed (the check would
#       otherwise pass vacuously against an artifact nobody writes);
#   j.4 registry hygiene — every registered entry must still be a live site
#       whose RESOLVED target is its artifact and whose computed role is the
#       recorded role, so a registry entry cannot rot into a claim;
#   j.5 exec axis (R5) — a site that runs a tool which is itself a writer of an
#       artifact is a writer site for the same artifact under the same role.
#
# Identity is by TARGET, never by name: a proc called `RegistryPath` bound to
# tests/specs/algebraic_registry.json is not a writer of the registry SSOT, and
# test_debt_registry.json is not data/debt_registry.json.
# ═══════════════════════════════════════════════════════════════════════════

type
  ArtifactSpec = tuple[path: string, ownerRole: string]

const
  DebtArtifacts: seq[ArtifactSpec] = @[
