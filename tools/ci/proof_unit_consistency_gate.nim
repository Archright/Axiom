func headingLevelOf(line: string): int =
  result = 0
  for ch in line:
    if ch == '#':
      inc result
    else:
      break

func sectionAfter(content, marker: string): string =
  ## Lines from `marker` (inclusive) to the next heading of level <= the
  ## marker's own level (i.e., the end of that section).
  let lines = content.splitLines()
  var start = -1
  for i, line in lines:
    if line.strip().startsWith(marker):
      start = i
      break
  if start < 0:
    return ""
  let level = headingLevelOf(lines[start])
  result = lines[start] & "\n"
  for i in start + 1 ..< lines.len:
    let lvl = headingLevelOf(lines[i].strip())
    if lvl > 0 and lvl <= level:
      break
    result.add(lines[i])
    result.add("\n")

func firstCell(line: string): string =
  ## First cell of a markdown table row (empty if the line is not a row).
  let s = line.strip()
  if s.len == 0 or s[0] != '|':
    return ""
  var i = 1
  while i < s.len and s[i] == ' ':
    inc i
  let startTok = i
  while i < s.len and s[i] != '|':
    inc i
  result = s[startTok ..< i].strip()

func isWToken(s: string): bool =
  ## True iff `s` is a bare `W<digits>` id (e.g. "W1").
  result = true
  if s.len < 2 or s[0] != 'W':
    result = false
  else:
    for ch in s[1 ..^ 1]:
      if ch notin {'0' .. '9'}:
        result = false
        break

func rowCarriesValues(row: string): bool =
  ## False-positive minimization for (d): a row starting with a W id is a
  ## re-introduced id·duration·tier VALUE table only when it also carries a
  ## duration digit or a tier token. Pure-reference rows are not flagged.
  result = false
  for ch in row:
    if ch in {'0' .. '9'}:
      result = true
      break
  if not result and ("L0" in row or "L1" in row or "L2" in row):
    result = true

func wValueTableRows(section: string): seq[string] =
  for line in section.splitLines():
    let cell = firstCell(line)
    if isWToken(cell) and rowCarriesValues(line):
      result.add(line.strip())

func docSectionFailures(path, content, marker: string): seq[string] =
  result = @[]
  if content.len == 0:
    result.add("unreadable doc: " & path)
    return
  let section = sectionAfter(content, marker)
  if section.len == 0:
    result.add("W-membership section not found in " & path & " (marker: " & marker & ")")
    return
  for row in wValueTableRows(section):
    result.add("W-list value table re-introduced in " & path & ": " & row)
  if CatalogAuthorityToken notin section:
    result.add("W-membership section lacks '" & CatalogAuthorityToken &
               "' reference notation: " & path)

