# Shared token extraction (deterministic, regex-free)
# ═══════════════════════════════════════════════════════════════════════════

func extractWTokens(text: string): seq[string] =
  ## Extract every `W<digits>` token (unit-id shaped) from `text`.
  var i = 0
  while i + 1 < text.len:
    if text[i] == 'W' and text[i + 1] in {'0' .. '9'}:
      var j = i + 1
      while j < text.len and text[j] in {'0' .. '9'}:
        inc j
      result.add(text[i ..< j])
      i = j
    else:
      inc i

func extractQuotedRegions(text: string): seq[string] =
  ## Split `text` into the contents of its double-quoted string literals
  ## (backslash-escaped quotes handled; triple-quoted blocks are not tracked).
  var i = 0
  while i < text.len:
    if text[i] != '"':
      inc i
    else:
      var j = i + 1
      var region = ""
      var inEscape = false
      while j < text.len:
        let ch = text[j]
        if inEscape:
          region.add(ch)
          inEscape = false
        elif ch == '\\':
          region.add('\\')
          inEscape = true
        elif ch == '"':
          break
        else:
          region.add(ch)
        inc j
      result.add(region)
      i = j + 1

