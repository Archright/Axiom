  ## Classification is by target, never by identifier spelling.
  SinkHit = tuple[file: string, line: int, target: string, body: string]

  ## One local write wrapper: proc `name` persists the argument at parameter
  ## index `paramIdx` of its own call (resolver rule R3). `viaDefault` says the
  ## site is the wrapper's own sink line (parameter default) rather than the
  ## wrapper's call sites.
  WriteWrapper = tuple[name: string, paramIdx: int, viaDefault: bool]

  ## A proc signature plus the line range of its body. `defaulted[i]` says
  ## whether parameter `i` carries a default initializer.
  ProcInfo = tuple[name: string, params: seq[string], defaulted: seq[bool],
