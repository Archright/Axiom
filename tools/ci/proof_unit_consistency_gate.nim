## proof_unit_consistency_gate.nim — A0′ consistency gate (2차 fail-closed 안전장치)
##
## After the A0 cutover (2026-09-23), ProofUnitCatalog in
## src/gate/proof_unit_catalog.nim is the SINGLE editing authority for the
## W1–W11 CI work-unit axis. This tool is the dedicated second-layer safety
## net for projection drift that a single-authority refactor can leave behind:
##
##   (a) Catalog internal integrity (W1–W11 all present, no duplicates, valid
##       tier, sub-stage set consistent with the schema, path/duration sanity)
##   (b) selector ↔ Catalog
##       (tools/ci/impact_closure_selector.nim: every W-id reference within
##        the catalog set; the selector still imports the Catalog module)
##   (c) oracle ↔ Catalog
##       (data/selector_soundness/mutation_catalog.json: every W-id reference
##        — expectedAffected, derivations, descriptions — within the catalog)
##   (d) duplicate-declaration reintroduction guard (data/ci_required_work_units
##       .json must stay deleted; the tier spec §3 / ADR-0019 §2 must stay in
##       reference-only form — no id·duration·tier value tables)
##   (e) gate-axis namespace (config/gates.manifest.toml): no W-id collision
##       between gate ids and catalog unit ids
##   (f) ghost authority (config/policy/merge_admission.json trustSurface +
##       requiredValidations workflowPath, gates.manifest.toml file= entries must
##       exist on disk; merge_cli.nim RequiredWorkflowIds block non-empty —
##       standing invariant since the 2026-09-24 decision revision that
##       re-registered the admission-check producer alongside the policy)
##   (g) stale contract (docs/agents+docs/spec+config/policy lines mentioning a
##       deleted workflow filename must carry a retro token on the SAME line;
##       Amendment A1 decision-text binding in ADR-0017 / scheduling spec §5)
##   (h) config/gates.json projection + writer set (machine-generated projection
##       equal to tools/sync_topology.gateRuntimeProjectionJson, plus a
##       closed-world REGISTERED writer set with registry-hygiene liveness)
##   (i) core.hooksPath writer singularity (closed-world, two axes: git-config
##       invocation axis and persistence-sink axis; tools/setup_hooks.nim with
##       value .githooks is the sole legal writer)
##   (j) debt registry + projections role sets (closed-world, per artifact:
##       data/debt_registry.json is written by the SSOT mutator only;
##       docs/DEBT_REGISTRY.md and src/generated/debt_constants.nim are
##       generated by the sole projection generator only; sanctioned
##       temp-dir test fixtures are registered separately)
##
## ── Closed-world resolver rules (shared by (h), (i), (j)) ──
##
## The writer universe is built by enumerating sites, never by pattern-guessing
## a target. A site's artifact is decided by its RESOLVED write target, never by
## the identifier that happens to spell it — that is why a proc named
## `RegistryPath` bound to tests/specs/algebraic_registry.json is not a writer
## of data/debt_registry.json.
##
##   R1 binding scope — `let` / `var` / `const` bindings are collected both from
##      single-line declarations and from members of multi-line declaration
##      blocks (block nesting is tracked by indentation), because the repository's
##      dominant path idiom is a block of module-level constants.
##   R2 default parameters — a `name: T = <expr>` declaration inside a proc
##      signature is a binding too; it is how a writer's default target is
##      resolved when the call site passes nothing.
##   R3 write wrappers — a proc whose body ends in a persistence call whose
##      target argument is one of its own parameters is a write wrapper. Exactly
##      ONE hop is followed: the call site, not the wrapper body, is the site,
##      and the parameter is resolved to the call-site argument. A wrapper whose
##      target parameter carries a default instead reports the wrapper's own sink
##      line, resolved through that default (R2 + R3 together).
##   R4 move/rename destination — `moveFile` / `moveFileOpt` / `renameFile`
##      write their DESTINATION argument; every other sink writes its first
##      argument. Taking the first argument of a rename reports the source file.
##   R5 exec axis (j only) — a site that runs another repository tool which is
##      itself a discovered writer of an artifact is a writer site for the same
##      artifacts, with the delegate's role. An exec site that names one of the
##      audited artifacts but resolves to no known tool is UNCLASSIFIED, because
##      a silently ignored candidate is the exact failure mode being removed.
##   R6 unresolvable targets fail closed — a site whose target cannot be
##      resolved is never counted as "not a writer"; it is reported as an
##      unclassified candidate (exit 2) whenever its own line carries the
##      audited artifact's identity.
##
## ── (j) per-artifact ROLE-SET model ──
##
## One tool legitimately holds two different roles over different artifacts
## (tools/debt_engine.nim mutates the registry SSOT and generates both
## projections). Counting sinks into one shared total would collapse those roles
## and make "1 writer + 1 generator" look like "2 writers", so each artifact
## carries its OWN role-set:
##
##   data/debt_registry.json           owner role SSOT_MUTATOR
##   docs/DEBT_REGISTRY.md            owner role SOLE_PROJECTION_GENERATOR
##   src/generated/debt_constants.nim owner role SOLE_PROJECTION_GENERATOR
##
## Every discovered site is assigned exactly one role for each artifact it
## touches, and the role-set of an artifact's owner role must equal its
## registered set exactly. A site that holds a role no registry entry covers is
## a competing authority (exit 1). Sanctioned residual writers are registered
##   under role TEST_FIXTURE and must resolve INTO a temp dir; a fixture that
##   resolves to a repo-root path is a competing authority, not a fixture.
##
## Project conventions:
##   - Audited files are read from disk at run time (manifest_consistency_gate /
##     doc_path_validator pattern), so a prebuilt push-snapshot binary audits
##     the pushed OID's tree rather than a stale embedded copy.
##   - Deterministic: no timestamps, no randomness, no network. Same tree state
##     → same verdict. Exit 0 = consistent, 1 = drift, 2 = environment error.

