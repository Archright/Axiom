import std/[json, os, strutils, math]

## Performance regression gate — fail-closed.
##
## Compares data/benchmarks/perf_latest.json against
## data/benchmarks/perf_baseline.json (schema v2; produced by
## src/engine/profiler.nim and tools/perf_baseline_gen.nim).
## Every degenerate input is an explicit FAIL, never a skip:
##   ① baseline file missing          ② latest file missing
##   ③ unparseable JSON (either file) ④ schema drift (schemaVersion != 2,
##     missing/invalid environment or measurements block)
##   ⑤ measurement-environment mismatch (comparability fields; provenance
##     is deliberately NOT compared)
##   ⑥ zero baseline∩latest key overlap (vacuous pass)
## plus per-metric: budget regression and non-positive baseline values.
## Exit 0 iff no failure and no regression. The baseline is never
## auto-generated here — `make perf-baseline` is the explicit writer.
##
## The latest side (data/benchmarks/perf_latest.json) is an untracked
## execution artifact (gitignored, regenerated by every perf-check run;
## a fresh checkout has none until the first run). Inside this gate that
## changes nothing: failure ② (latest missing) stays an explicit FAIL —
## fail-closed, never a silent pass.

const
  PerfSchemaVersion = 2
  ## COMPARABILITY fields — baseline and latest must agree on all of them.
  EnvFields* = ["nim", "lean", "profileMode", "cacheState"]

func schemaViolation(doc: JsonNode, role: string): string =
  ## "" when doc is a valid schema-v2 perf document; the violation otherwise.
  if doc.kind != JObject:
    return role & ": invalid schema — root must be a JSON object"
  if not doc.hasKey("schemaVersion") or doc["schemaVersion"].kind != JInt or
      doc["schemaVersion"].getInt() != PerfSchemaVersion:
    return role & ": invalid schema — schemaVersion must be " & $PerfSchemaVersion &
      " (stale/legacy file — refresh latest via `make perf-check`, baseline via `make perf-baseline`)"
  if not doc.hasKey("environment") or doc["environment"].kind != JObject:
    return role & ": invalid schema — environment block missing"
  for field in EnvFields:
    if not doc["environment"].hasKey(field) or
        doc["environment"][field].kind != JString or
        doc["environment"][field].getStr().len == 0:
      return role & ": invalid schema — environment." & field &
        " must be a non-empty string"
  if not doc.hasKey("measurements") or doc["measurements"].kind != JObject:
    return role & ": invalid schema — measurements block must be a JSON object"
  return ""

func envDifferences(baselineEnv, latestEnv: JsonNode): seq[string] =
  for field in EnvFields:
    if baselineEnv[field].getStr() != latestEnv[field].getStr():
      result.add field & ": baseline=" & baselineEnv[field].getStr() &
        " latest=" & latestEnv[field].getStr()

func measurementUs(entry: JsonNode): tuple[valid: bool, us: int64] =
  if entry.kind == JObject and entry.hasKey("duration_us") and
      entry["duration_us"].kind == JInt:
    return (true, entry["duration_us"].getInt().int64)
  return (false, 0)

proc runPerfCheckImpl(baselinePath, latestPath: string; maxRegression: float):
    tuple[ok: bool, messages: seq[string]] =
  ## Full decision logic. Its inferred raise set is bounded by the
  ## runPerfCheck wrapper below, which catches ALL CatchableError.

  var msgs: seq[string]

  # ①② Presence — a missing file is a failure, never a skip.
  if not fileExists(baselinePath):
    msgs.add "[PERF FAIL] baseline missing — run `make perf-baseline` (explicit; never auto-generated)"
    return (false, msgs)
  if not fileExists(latestPath):
    msgs.add "[PERF FAIL] latest missing — measurement harness produced no data (perf-check stage 1 failure; rerun `make perf-check`)"
    return (false, msgs)

  # ③ Parseability — corrupt JSON is an explicit failure, not a traceback.
  var baselineRoot, latestRoot: JsonNode
  try:
    baselineRoot = parseJson(readFile(baselinePath))
  except CatchableError as e:
    msgs.add "[PERF FAIL] baseline unparseable JSON (" & baselinePath & "): " & e.msg
    return (false, msgs)
  try:
    latestRoot = parseJson(readFile(latestPath))
  except CatchableError as e:
    msgs.add "[PERF FAIL] latest unparseable JSON (" & latestPath & "): " & e.msg
    return (false, msgs)

  # ④ Schema v2 — comparability metadata must be present and well-formed.
  let baselineViolation = schemaViolation(baselineRoot, "baseline")
  if baselineViolation.len > 0:
    msgs.add "[PERF FAIL] " & baselineViolation
    return (false, msgs)
  let latestViolation = schemaViolation(latestRoot, "latest")
  if latestViolation.len > 0:
    msgs.add "[PERF FAIL] " & latestViolation
    return (false, msgs)

  # ⑤ Environment comparability — provenance is intentionally not compared.
  let envDiffs = envDifferences(baselineRoot["environment"], latestRoot["environment"])
  if envDiffs.len > 0:
    msgs.add "[PERF FAIL] measurement environment differs from baseline environment"
    for diff in envDiffs:
      msgs.add "[PERF FAIL]   " & diff
    return (false, msgs)

  let baselineMeasurements = baselineRoot["measurements"]
  let latestMeasurements = latestRoot["measurements"]

  # ⑥ Vacuous-pass block — zero key overlap must fail, not pass.
  var overlap = 0
  for key, _ in pairs(latestMeasurements):
    if baselineMeasurements.hasKey(key):
      inc overlap
  if overlap == 0:
    msgs.add "[PERF FAIL] vacuous pass blocked — no metric overlap between baseline and latest"
    return (false, msgs)

  var failed = false
  for key, entry in pairs(latestMeasurements):
    if not baselineMeasurements.hasKey(key):
      continue
    let baselineSample = measurementUs(baselineMeasurements[key])
    if not baselineSample.valid:
      msgs.add "[PERF FAIL] " & key & ": invalid baseline measurement — duration_us (int) required"
      failed = true
      continue
    let latestSample = measurementUs(entry)
    if not latestSample.valid:
      msgs.add "[PERF FAIL] " & key & ": invalid latest measurement — duration_us (int) required"
      failed = true
      continue
    if baselineSample.us <= 0:
      msgs.add "[PERF FAIL] " & key & ": baseline duration must be > 0 (got " &
        $baselineSample.us & "us) — refusing division by zero"
      failed = true
      continue
    if latestSample.us < 0:
      msgs.add "[PERF FAIL] " & key & ": latest duration must be >= 0 (got " &
        $latestSample.us & "us)"
      failed = true
      continue
    let regressionPct = (latestSample.us.float - baselineSample.us.float) /
      baselineSample.us.float * 100.0
    if regressionPct > maxRegression:
      msgs.add "[PERF REGRESSION] " & key & ": +" &
        formatFloat(regressionPct, ffDecimal, 1) & "% (max: " &
        formatFloat(maxRegression, ffDecimal, 1) & "%)"
      failed = true
    else:
      msgs.add "[PERF OK] " & key & ": " &
        formatFloat(regressionPct, ffDecimal, 1) & "% change"

  return (not failed, msgs)

proc runPerfCheck*(baselinePath, latestPath: string; maxRegression: float):
    tuple[ok: bool, messages: seq[string]] {.raises: [].} =
  ## Pure decision core of the gate: never raises, never quits. Catches ALL
  ## CatchableError from the decision logic and surfaces it as an explicit
  ## failure message — no traceback can escape. ok is true iff every matched
  ## metric is present, valid and within budget; the CLI wrapper maps ok to
  ## the exit code.
  try:
    return runPerfCheckImpl(baselinePath, latestPath, maxRegression)
  except CatchableError as e:
    return (false, @["[PERF FAIL] checker internal error: " & e.msg])

proc parseCliPath(option, defaultValue: string): string =
  result = defaultValue
  let prefix = "--" & option
  for i in 1 .. paramCount():
    let value = paramStr(i)
    if value.startsWith(prefix):
      let separator = if value.startsWith(prefix & "="): '=' else: ':'
      if separator != '\0':
        result = value[prefix.len + 1 ..^ 1]

when isMainModule:
  var exitCode = QuitSuccess
  try:
    let baselinePath = parseCliPath("baseline", "data/benchmarks/perf_baseline.json")
    let latestPath = parseCliPath("latest", "data/benchmarks/perf_latest.json")
    let maxRegression = parseFloat(parseCliPath("max-regression", "5.0"))
    echo "[PERF] gate: baseline=" & baselinePath & " latest=" & latestPath &
      " max-regression=" & formatFloat(maxRegression, ffDecimal, 1) & "%"
    let (ok, messages) = runPerfCheck(baselinePath, latestPath, maxRegression)
    for message in messages:
      echo message
    echo (if ok: "[PERF] gate passed" else: "[PERF] gate failed")
    if not ok:
      exitCode = QuitFailure
  except CatchableError as e:
    echo "[PERF FAIL] checker error: " & e.msg
    exitCode = QuitFailure
  quit(exitCode)
