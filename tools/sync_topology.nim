proc findProjectRoot(): string =
  var dir = getCurrentDir()
  while true:
    if fileExists(dir / ProjectRootAnchor):
      return dir
    if fileExists(dir / "axiom.toml"):
      return dir
    let parent = dir.parentDir()
    if parent == dir:
      quit("ERROR: " & ProjectRootAnchor & " not found. Run from Axiom project directory.")
    dir = parent

func stagesToJson(stages: seq[StageKind]): JsonNode =
  result = newJArray()
  for s in stages:
    result.add(%($s))

func stringsToJson(items: seq[string]): JsonNode =
  result = newJArray()
  for item in items:
    result.add(%item)

func entryToJson(entry: TopologyEntry): JsonNode =
  result = newJObject()
  result["id"] = %entry.id
  result["name"] = %entry.name
  result["layer"] = %($entry.layer)
  result["entry"] = %entry.entry
  result["stages"] = stagesToJson(entry.stages)
  if entry.filesPattern.len > 0 or entry.passFilenames:
    result["filesPattern"] = %entry.filesPattern
  result["passFilenames"] = %entry.passFilenames
  result["weight"] = %($entry.weight)
  result["category"] = %($entry.category)
  if entry.argsTemplate.len > 0:
    result["argsTemplate"] = stringsToJson(entry.argsTemplate)
  if entry.after.len > 0:
    result["after"] = stringsToJson(entry.after)
  if entry.tier != 1:
    result["tier"] = %entry.tier
  result["severity"] = %($entry.severity)
  if entry.executionMode != emAOT:
    result["execution_mode"] = %($entry.executionMode)
  if entry.hermeticity != hkHermetic:
    result["hermeticity"] = %($entry.hermeticity)
  if entry.priority != 0:
    result["priority"] = %entry.priority
  if entry.alwaysRun:
    result["always_run"] = %entry.alwaysRun
  if entry.depsDirs.len > 0:
    result["depsDirs"] = stringsToJson(entry.depsDirs)
  if entry.timeoutSeconds != 0:
    result["timeout_seconds"] = %entry.timeoutSeconds

proc syncManifests(spec: openArray[TopologyEntry]; root: string) =
  let manifestDir = root / ManifestDir
  if not dirExists(manifestDir):
    createDir(manifestDir)

  var written = 0
  var unchanged = 0

  for entry in spec:
    let entryJson = entryToJson(entry)
    let content = pretty(entryJson) & "\n"
    let filePath = manifestDir / entry.id & ".json"
    if fileExists(filePath):
      let old = readFile(filePath)
      if old == content:
        inc unchanged
        continue
    writeFile(filePath, content)
    inc written
    echo "  Wrote: ", entry.id & ".json"

  echo "  Manifests: ", written, " written, ", unchanged, " unchanged"

proc syncGateManifestTOML(spec: openArray[TopologyEntry]; root: string) =
  var lines: seq[string] = @[]
  lines.add("# Auto-generated by tools/sync_topology.nim - DO NOT EDIT")
  lines.add("# Single Source of Truth for Gate Registry")
  lines.add("")
  
  for entry in spec:
    lines.add("[[gates]]")
    lines.add("id = \"" & entry.id & "\"")
    # Use entry field directly; append .nim for source paths (not bin/ binaries)
    let filePath = if not entry.entry.endsWith(".nim") and not entry.entry.startsWith("bin/"):
                     entry.entry & ".nim"
                   else:
                     entry.entry
    lines.add("file = \"" & filePath & "\"")
    # Map category to type
    let gateType = case entry.category
      of ckPolicy: "security"
      of ckRule: "quality"
      of ckTheorem: "verification"
      of ckValidation: "core"
    lines.add("type = \"" & gateType & "\"")
    lines.add("")
  
  let content = lines.join("\n")
  let tomlPath = root / "config/gates.manifest.toml"
  
  if fileExists(tomlPath):
    let old = readFile(tomlPath)
    if old == content:
      echo "  Manifest TOML: unchanged"
      return
  writeFile(tomlPath, content)
  echo "  Manifest TOML: written (", spec.len, " entries)"

proc syncIndex(spec: openArray[TopologyEntry]; root: string) =
  var ids: seq[string]
  for e in spec:
    ids.add(e.id)
  let sorted = ids.sorted()

  let content = sorted.join("\n") & "\n"
  let indexPath = root / IndexPath
  if fileExists(indexPath):
    let old = readFile(indexPath)
    if old == content:
      echo "  Index: unchanged"
      return
  writeFile(indexPath, content)
  echo "  Index: written (", sorted.len, " entries)"

proc syncRegistry(spec: openArray[TopologyEntry]; root: string) =
  var lines: seq[string] = @[]

  for entry in spec:
    lines.add("  (\"" & entry.id & "\", \"" & entry.entry & "\")")

  let body = lines.join(",\n")
  let content = "# Auto-generated by tools/sync_topology.nim - DO NOT EDIT\n" &
                "const ManifestRegistry* = [\n" & body & "\n]\n"

  let regPath = root / RegistryPath
  if fileExists(regPath):
    let old = readFile(regPath)
    if old == content:
      echo "  Registry: unchanged"
      return
  writeFile(regPath, content)
  echo "  Registry: written"

proc generateGateRegistryCode*(): string =
