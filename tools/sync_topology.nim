proc gateRuntimeProjectionJson*(repoRoot: string): string =
  ## Renders config/gates.json exactly as syncGateRuntimeConfig writes it, so a
  ## machine check can diff the projection against the on-disk file without
  ## touching it. repoRoot is accepted for call-site symmetry with the other
  ## sync procs and deliberately unused: the projection reads only TopologySpec
  ## and GateEnablement, so no path is embedded and the bytes stay free of any
  ## environment input.
  var lines: seq[string] = @[]
  # The `//` header is kept because config/gates.json has always carried one and
  # its readers go through parseJson, which skips line comments. Only the
  # "controls enabled per gate independently of manifest.d" line is replaced —
  # it states the opposite of the new authority model, so carrying it forward
  # would be a false claim. The `axiom:gate-config` marker is preserved.
  lines.add("// axiom:gate-config")
  lines.add("// Auto-generated by tools/sync_topology.nim - DO NOT EDIT")
  lines.add("// Gate enablement is a pure projection of TopologySpec + GateEnablement.")
  lines.add("// Runtime severity demotion is handled by analyzer.resolveEffectiveSeverity.")
  lines.add("// Format: {\"phase3c\": true, \"gates\": {\"<gate-id>\": {\"enabled\": true}}}")
  lines.add("{")
  lines.add("  \"phase3c\": true,")
  lines.add("  \"gates\": {")
  # TopologySpec order, not Table iteration order: the key order stays derived
  # from the topology rather than from a second, independent sort authority.
  for i, entry in TopologySpec:
    let enabled = GateEnablement.getOrDefault(entry.id, true)
    let comma = if i < TopologySpec.len - 1: "," else: ""
    lines.add("    \"" & entry.id & "\": {\"enabled\": " &
      (if enabled: "true" else: "false") & "}" & comma)
  lines.add("  }")
  lines.add("}")
  result = lines.join("\n") & "\n"

proc syncGateRuntimeConfig(root: string) =
  let content = gateRuntimeProjectionJson(root)
  let configPath = root / GateConfigPath

  if fileExists(configPath):
    let old = readFile(configPath)
    if old == content:
      echo "  Gate config: unchanged"
      return
  writeFile(configPath, content)
  echo "  Gate config: written (", TopologySpec.len, " gates)"

proc main() =
  let root = findProjectRoot()

  echo "[sync_topology] Root: ", root
  echo "[sync_topology] Syncing manifest.d/*.json..."
  syncManifests(TopologySpec, root)

  echo "[sync_topology] Syncing _index.json..."
  syncIndex(TopologySpec, root)

  echo "[sync_topology] Syncing manifest_registry.nim..."
  syncRegistry(TopologySpec, root)

  echo "[sync_topology] Syncing gate_registry.nim..."
  syncGateRegistry(root)

  echo "[sync_topology] Syncing helper_registry.nim..."
  syncHelperRegistry(root)

  echo "[sync_topology] Syncing gates.manifest.toml..."
  syncGateManifestTOML(TopologySpec, root)

  echo "[sync_topology] Syncing config/gates.json..."
  syncGateRuntimeConfig(root)

  echo "[sync_topology] Done."

when isMainModule:
  main()
