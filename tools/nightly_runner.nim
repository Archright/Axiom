import std/[os, osproc, strutils, sequtils]

## Nightly suite runner — single source of truth for the full nightly pipeline.
## Executes: make verify-all, integration tests, orphan tests (tests/nightly).
## Local (`make nightly`) and CI (`gate-nightly`) both invoke this runner so
## the two environments cannot drift. Exit 0 = all steps passed, exit 1 = any failed.

type StepResult = object
  name: string
  ok: bool

const NimBin = "nim"

proc runStep(name, cmd: string): bool =
  echo "\n=== [nightly] " & name & " ==="
  echo "$ " & cmd
  let (output, exitCode) = execCmdEx(cmd, options = {poStdErrToStdOut})
  if output.len > 0:
    echo output
  if exitCode == 0:
    echo "--- PASS: " & name
  else:
    echo "--- FAIL(" & $exitCode & "): " & name
  result = exitCode == 0

proc integrationTests(): seq[StepResult] =
  let tests = [
    "tests/integration/test_prelude.nim",
    "tests/integration/test_vc_pipeline.nim",
    "tests/integration/test_lean_lsp_document_symbol_integration.nim",
    "tests/integration/test_policy_validator_cli.nim",
    "tests/integration/test_unstaged_guard.nim",
    "tests/integration/test_nimtry_fixtures.nim",
    "tests/integration/test_vc_complete_integration.nim",
  ]
  for t in tests:
    result.add(StepResult(
      name: t,
      ok: runStep("integration: " & t, NimBin & " c -d:axiomIntegration -r " & t),
    ))

proc orphanTests(): seq[StepResult] =
  ## verify_trajectory is intentionally excluded: it depends on the prove
  ## trajectory artifact generated by CI (`ax prove --limit`) / nightly
  ## orchestration, so it must run after artifact production, not inside
  ## this runner. CI runs it as a standalone step.
  let tests = [
    "tests/nightly/test_tactic_solver.nim",
    "tests/nightly/test_4tier_pipeline.nim",
    "tests/nightly/test_fault_injection.nim",
    "tests/nightly/validate_registry.nim",
  ]
  for t in tests:
    result.add(StepResult(
      name: t,
      ok: runStep("orphan: " & t, NimBin & " c -d:axiomIntegration -r " & t),
    ))

proc main() =
  echo "=== Axiom Nightly Suite (SSOT runner) ==="
  var results: seq[StepResult] = @[]

  results.add(StepResult(
    name: "make verify-all",
    ok: runStep("make verify-all", "make verify-all"),
  ))

  if dirExists("tests/integration"):
    results.add integrationTests()
  else:
    echo "[WARN] tests/integration not found — skipped"

  if dirExists("tests/nightly"):
    results.add orphanTests()
  else:
    echo "[WARN] tests/nightly not found — skipped"

  echo "\n=== Nightly Summary ==="
  var failed = 0
  for r in results:
    echo (if r.ok: "PASS  " else: "FAIL  ") & r.name
    if not r.ok: inc failed
  echo ""
  if failed == 0:
    echo "ALL NIGHTLY STEPS PASSED (" & $results.len & " steps)"
    quit(0)
  else:
    echo "NIGHTLY FAILED — " & $failed & " of " & $results.len & " steps failed"
    quit(1)

when isMainModule:
  main()
