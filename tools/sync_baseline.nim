## tools/sync_baseline.nim
## Mutation command: reads baseline_revisions.json → validates → materializes → writes
## config/policy/baseline_current.json (idempotent).
## P0-1: Baseline is NOT a Decision input.
## P0-2/P0-3: shared revision algebra with policy chain.
## SSOT for baseline materialization pipeline.

import std/[json, os, strutils, tables, options]
import policy/revision_chain

# ══════════════════════════════════════════════════════════════════════
# Constants
# ══════════════════════════════════════════════════════════════════════

const BaselineRevisionsPath = "config/policy/baseline_revisions.json"
const BaselineCurrentOut    = "config/policy/baseline_current.json"

# ══════════════════════════════════════════════════════════════════════
# Helpers
# ══════════════════════════════════════════════════════════════════════

proc loadJsonc(path: string): JsonNode {.raises: [CatchableError].} =
  if not fileExists(path):
    echo "ERROR: " & path & " not found"; quit(1)
  let content = readFile(path)
  let stripped = stripJsonComments(content)
  try:
    result = parseJson(stripped)
  except JsonParsingError:
    echo "ERROR: Invalid JSON in " & path & ": " & getCurrentExceptionMsg(); quit(1)

proc idempotentWrite(path, content: string) {.raises: [CatchableError].} =
  ## Write only if content differs (idempotency).
  if fileExists(path):
    let existing = readFile(path)
    let existingStripped = stripJsonComments(existing)
    if existingStripped.strip() == content.strip():
      echo "  [skip] " & path & " unchanged"
      return
  let dir = path.parentDir()
  if not dirExists(dir): createDir(dir)
  writeFile(path, content)
  echo "  [write] " & path & " (" & $content.len & " bytes)"

# ══════════════════════════════════════════════════════════════════════
# Main
# ══════════════════════════════════════════════════════════════════════

proc main() {.raises: [CatchableError].} =
  echo "sync_baseline: read baseline_revisions.json → validate → materialize → write baseline_current.json"
  echo ""

  # Step 1: Load and validate the revision chain
  echo "[1/4] Loading " & BaselineRevisionsPath & "..."
  let chainJson = loadJsonc(BaselineRevisionsPath)

  echo "[2/4] Validating revision chain invariants (P0-2)..."
  let validation = validateLinear(chainJson)
  if validation.len == 0:
    echo "  ✅ Revision chain is valid (linear, single genesis, single head, all reachable)"
  else:
    echo "  ❌ Revision chain validation FAILED:"
    for err in validation:
      echo "    - " & err
    quit(1)

  # Step 2: Find head and extract genesis payload
  echo "[3/4] Finding head and materializing baseline (P0-3)..."
  let headId = findHead(chainJson)
  if headId.isNone():
    echo "  ❌ No head found in revision chain"; quit(1)
  echo "  Head revision: " & headId.get()

  # Extract genesis payload as the initial state
  var genesisState: JsonNode
  let revisions = chainJson{"revisions"}
  for rev in revisions:
    let parentId = rev{"parentRevisionId"}
    if parentId.kind == JNull:
      genesisState = rev{"payload"}
      break

  if genesisState.kind != JObject:
    echo "  ❌ Genesis payload not found or invalid"; quit(1)

  # Materialize: apply all patches from genesis to head
  let materialized = materialize(chainJson, genesisState)

  echo "  Materialized baseline:"
  echo "    metricId:          " & materialized.metricId
  echo "    contractRevision:  " & materialized.contractRevision
  echo "    subjectScope:      " & materialized.subjectScope
  echo "    currentValue:      " & materialized.currentValue

  # Step 3: Build baseline_current.json from materialized state
  echo ""
  echo "[4/4] Writing baseline_current.json..."

  var recordsObj = newJObject()
  # Include per-metric baseline encoder fields with contractRevision
  let records = genesisState{"records"}
  if records != nil and records.kind == JObject:
    for metricName, recordNode in records:
      var recObj = newJObject()
      recObj["baseline"] = recordNode{"baseline"}
      recObj["target"] = recordNode{"target"}
      recObj["current"] = recordNode{"current"}
      recObj["contractRevision"] = %materialized.contractRevision
      recObj["subjectScope"] = %materialized.subjectScope
      recordsObj[metricName] = recObj

  var output = newJObject()
  output["version"] = %"1.0.0"
  output["schema"] = %"baseline_current"
  output["materializedCurrent"] = %true
  output["freshness"] = %"fresh"
  output["contractRevision"] = %materialized.contractRevision
  output["records"] = recordsObj

  let jsonOutput = output.pretty()
  let jsoncOutput = "// Auto-generated by tools/sync_baseline - DO NOT EDIT\n// Baseline snapshot: per-metric baseline encoder fields incl. contractRevision.\n// P0-1: Baseline is NOT a Decision input.\n\n" & jsonOutput

  idempotentWrite(BaselineCurrentOut, jsoncOutput)

  # Verify freshness
  echo ""
  echo "Freshness check:"
  let freshStatus = verifyContentFreshness(jsonOutput, BaselineCurrentOut)
  echo "  " & freshStatus

  echo ""
  echo "Done."

when isMainModule:
  main()
