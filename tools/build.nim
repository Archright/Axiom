# ── Helpers ──────────────────────────────────────────────────────────────────

proc timestamp(): string =
  ## UTC ISO-8601 timestamp for structured logs
  let dt = now().utc()
  result = $int(dt.year) & "-" &
           align($dt.month.ord, 2, '0') & "-" &
           align($dt.monthday, 2, '0') & "T" &
           align($dt.hour, 2, '0') & ":" &
           align($dt.minute, 2, '0') & ":" &
           align($dt.second, 2, '0') & "Z"

# ── CLI Argument Parsing ─────────────────────────────────────────────────────

var usePipeline {.global.} = false

proc parseArgs(): Config =
  ## Parse command line: --autoRaises, --dryRun, --verify, --jsonLog
  ## Defaults: srcDir="src", entryPoint="src/cli/axiom.nim", outputPath="bin/axiom"
  result = Config(
    srcDir:      "src",
    entryPoint:  "src/cli/axiom.nim",
    outputPath:  "bin/axiom",
    overlayDir:  "build/tmp",
    nimcacheDir: "build/tmp/nimcache",
    hashFile:    "data/.build_hash",
    autoRaises:  false,
    dryRun:      false,
    verify:      false,
    jsonLog:     false
  )
  for i in 1..paramCount():
    let arg = paramStr(i)
    if   arg == "--autoRaises": result.autoRaises = true
    elif arg == "--dryRun":     result.dryRun     = true
    elif arg == "--verify":     result.verify     = true
    elif arg == "--jsonLog":    result.jsonLog    = true
    elif arg == "--pipeline":   usePipeline = true

# ── Structured Logging ───────────────────────────────────────────────────────

proc logJson(stage, action: string, details: string = "") =
  ## JSON structured log: {"ts":"...","stage":"...","action":"...","details":"..."}
  let entry = %*{
    "ts":      timestamp(),
    "stage":   stage,
    "action":  action,
    "details": details
  }
  echo entry.pretty()

# ── Layer 2: Side-Effect Functions ───────────────────────────────────────────

proc createOverlay(config: Config): bool =
  ## cp -r src build/tmp/src using osproc.execCmdEx
  let dest = config.overlayDir / "src"
  logJson("overlay", "create", config.srcDir & " → " & dest)

  # Ensure parent directory exists
  try:
    createDir(config.overlayDir)
  except OSError as e:
    logJson("overlay", "createDir FAILED", e.msg)
    return false

  # Remove existing overlay src if present (clean slate)
  if dirExists(dest):
    try:
      removeDir(dest)
    except OSError as e:
      logJson("overlay", "removeDir FAILED", e.msg)
      return false

  # Copy source tree into overlay
  let (output, exitCode) = execCmdEx("cp -r " & config.srcDir & " " & dest)
  if exitCode != 0:
    logJson("overlay", "cp FAILED", "exit=" & $exitCode & " " & output)
    return false

  logJson("overlay", "created", dest)
  true

proc generateNimCfg(manifest: Manifest, config: Config): bool =
  ## Generate nim.cfg with --path entries, excluding quarantined module directories
  logJson("nimcfg", "generate", "quarantine_entries=" & $manifest.entries.len)

  # Collect quarantined directory prefixes
  var quarantinedDirs: seq[string] = @[]
  for entry in manifest.entries:
    let dir = entry.path.parentDir()
    if dir.len > 0 and dir notin quarantinedDirs:
      quarantinedDirs.add(dir)

  # Collect all subdirectories under src/ (breadth-first)
  var allDirs: seq[string] = @[]
  for kind, path in walkDir(config.srcDir):
    if kind == pcDir:
      allDirs.add(path)

  var i = 0
  while i < allDirs.len:
    for kind, path in walkDir(allDirs[i]):
      if kind == pcDir:
        allDirs.add(path)
    inc i

  # Deterministic ordering
  allDirs.sort(proc (a, b: string): int = cmp(a, b))

  # Build nim.cfg content — include only non-quarantined directories
  var lines: seq[string] = @[]
  lines.add("# Auto-generated by build.nim — do not edit")
  lines.add("# Quarantined directories excluded from --path")

  for dir in allDirs:
    var excluded = false
    for qDir in quarantinedDirs:
      if dir.startsWith(qDir):
        excluded = true
        break
    if not excluded:
      lines.add("--path:" & dir)

  # Write nim.cfg to overlay root (picked up by Nim via source-file ancestry)
  let cfgPath = config.overlayDir / "nim.cfg"
  try:
    writeFile(cfgPath, lines.join("\n") & "\n")
  except IOError as e:
    logJson("nimcfg", "write FAILED", e.msg)
    return false

  logJson("nimcfg", "generated", cfgPath & " (" & $lines.len & " lines)")
  true

proc compileEntryPoint(config: Config): bool =
  ## Run: nim c --hints:off --nimcache:<nimcacheDir> --path:<overlayDir> -o:<outputPath> <entryFile>
  let entryFile = config.overlayDir / config.entryPoint
  logJson("compile", "start", "entry=" & entryFile)

  # Ensure nimcache directory exists
  try:
    createDir(config.nimcacheDir)
  except OSError:
    discard

  let cmd = "nim c --hints:off" &
            " --nimcache:" & config.nimcacheDir &
            " --path:" & config.overlayDir &
            " -o:" & config.outputPath &
            " " & entryFile
  logJson("compile", "cmd", cmd)

  let (output, exitCode) = execCmdEx(cmd)

  if exitCode != 0:
    logJson("compile", "FAILED",
            "exit=" & $exitCode & "\n" & output)
    return false

  logJson("compile", "OK", "output=" & config.outputPath)
  true

proc commitBuild(config: Config): bool =
  ## Copy binary from overlay to bin/, remove overlay directory
  logJson("commit", "start")

  # Ensure bin/ directory exists
  try:
    createDir("bin")
  except OSError:
    discard

  let srcBin = config.overlayDir / config.outputPath
  let dstBin = config.outputPath

  if not fileExists(srcBin):
    logJson("commit", "binary NOT FOUND", srcBin)
    return false

  let (output, exitCode) = execCmdEx("cp " & srcBin & " " & dstBin)
  if exitCode != 0:
    logJson("commit", "cp FAILED", output)
    return false

  # Remove overlay (transaction complete)
  try:
    removeDir(config.overlayDir)
  except OSError as e:
    logJson("commit", "removeDir FAILED", e.msg)
    # Non-fatal: binary was already copied
    return false

  logJson("commit", "done", "binary=" & dstBin)
  true

proc rollbackBuild(config: Config) =
  ## Remove overlay directory (abort transaction)
  logJson("rollback", "start", "removing " & config.overlayDir)
  try:
    removeDir(config.overlayDir)
    logJson("rollback", "done")
  except OSError as e:
    logJson("rollback", "FAILED", e.msg)

# ── Layer 4: Orchestrator ────────────────────────────────────────────────────

proc build(config: Config): bool =
  ## Main pipeline:
  ## 1. Hash check (skip if unchanged)
  ## 2. Stage 1: Analysis (dep_graph.buildGraph + computeQuarantine)
  ## 3. Stage 2: Overlay + Quarantine (createOverlay + generateNimCfg)
  ## 4. Stage 3: Normalize (if autoRaises, run raises_normalizer.normalizeLoop)
  ## 5. Stage 4: Compile
  ## 6. Commit or Rollback
  logJson("build", "start", "entry=" & config.entryPoint)

  # ── Stage 0: Incremental hash check ──
  # --pipeline mode: use ProjectMap (single-pass scan, Merkle root)
  # Default mode: use dep_graph.computeSourceHash (separate walkDirRec)
  var currentHash: uint64
  if usePipeline:
    logJson("build", "scan", "using ProjectMap (single-pass)")
    let pm = scanForBuild(config.srcDir)
    # Convert Merkle root string to uint64 for hash comparison compatibility
    currentHash = hash(pm.sourceHash).uint64
    logJson("build", "scanned",
            "files=" & $pm.fileCount &
            " duration=" & $(pm.scanDurationMs.int) & "ms")
  else:
    currentHash = dep_graph.computeSourceHash(config.srcDir)
  let storedHash  = dep_graph.loadStoredHash(config.hashFile)

  if currentHash == storedHash and not config.dryRun:
    logJson("build", "skip", "unchanged (hash=" & $currentHash & ")")
    return true

  if currentHash != storedHash:
    logJson("build", "hash_changed",
            "old=" & $storedHash & " new=" & $currentHash)

  # ── Stage 1: Dependency Analysis ──
  logJson("analysis", "start")
  let graph = dep_graph.buildGraph(config.srcDir)
  logJson("analysis", "done",
          "modules=" & $graph.modules.len &
          " orphans=" & $graph.orphans.len &
          " entryPoints=" & $graph.entryPoints.len)

  let manifest = dep_graph.computeQuarantine(graph)
  logJson("quarantine", "computed",
          "entries=" & $manifest.entries.len)

  # ── Stage 2: Overlay + Quarantine ──
  if not config.dryRun:
    if not createOverlay(config):
      rollbackBuild(config)
      return false

    if not generateNimCfg(manifest, config):
      rollbackBuild(config)
      return false
  else:
    logJson("overlay", "dryRun", "skipped")

  # ── Stage 3: Normalize ({.raises: [].} auto-insertion) ──
  if config.autoRaises:
    logJson("normalize", "start", "maxIterations=5")
    let normResult = raises_normalizer.normalizeLoop(config)
    if normResult.isErr():
      let e = normResult.error
      logJson("normalize", "FAILED", e.message)
      rollbackBuild(config)
      return false
    logJson("normalize", "OK")

  # ── Stage 4: Compile ──
  if not config.dryRun:
    if not compileEntryPoint(config):
      rollbackBuild(config)
      return false
  else:
    logJson("compile", "dryRun", "skipped")

  # ── Stage 5: Commit or Rollback ──
  if not config.dryRun:
    if not commitBuild(config):
      rollbackBuild(config)
      return false

    # Persist hash for incremental builds
    try:
      dep_graph.saveHash(config.hashFile, currentHash)
    except IOError:
      discard  # Non-fatal: hash save failure doesn't break the build

    logJson("build", "DONE")

  true

# ── Idempotency Verification ────────────────────────────────────────────────

proc verifyIdempotency(config: Config): bool =
  ## Build twice, compare output binaries with cmp
  logJson("verify", "start")

  # ── First build ──
  logJson("verify", "build_1")
  if not build(config):
    logJson("verify", "first build FAILED")
    return false

  let firstBin = config.outputPath
  if not fileExists(firstBin):
    logJson("verify", "binary missing after build_1", firstBin)
    return false

  # Save first binary for comparison
  let tmpBin = firstBin & ".verify.1"
  let (_, cp1) = execCmdEx("cp " & firstBin & " " & tmpBin)
  if cp1 != 0:
    logJson("verify", "cp first binary FAILED")
    return false

  # Reset stored hash to force second build
  try:
    dep_graph.saveHash(config.hashFile, 0'u64)
  except IOError:
    discard

  # ── Second build ──
  logJson("verify", "build_2")
  if not build(config):
    logJson("verify", "second build FAILED")
    # axiom:best-effort(cleanup after build failure)
    try: removeFile(tmpBin)
    except OSError as e: logJson("verify", "cleanup FAILED", e.msg)
    return false

  # ── Compare binaries ──
  let (cmpOut, cmpCode) = execCmdEx("cmp " & firstBin & " " & tmpBin)
  # axiom:best-effort(cleanup temp binary)
  try: removeFile(tmpBin)
  except OSError as e: logJson("verify", "cleanup FAILED", e.msg)

  if cmpCode != 0:
    logJson("verify", "FAILED", "binaries differ: " & cmpOut)
    return false

  logJson("verify", "OK", "binaries identical")
  true

# ── Main ─────────────────────────────────────────────────────────────────────

proc main() =
  let config = parseArgs()

  if config.verify:
    if verifyIdempotency(config):
      echo "VERIFY: OK"
    else:
      echo "VERIFY: FAILED"
      quit(1)
  else:
    if build(config):
      echo "BUILD: OK"
    else:
      echo "BUILD: FAILED"
      quit(1)

main()
