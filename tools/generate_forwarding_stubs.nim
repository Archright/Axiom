## generate_forwarding_stubs.nim — Generate forwarding stub files for relocated modules.
##
## Reads data/migration_map.json and creates forwarding stubs at old paths
## that re-export from the new location. Follows Axiom's Forwarding Stub
## design principles (AGENTS.md §1.3b).
##
## Usage:
##   nim c -r tools/generate_forwarding_stubs.nim
##   nim c -r tools/generate_forwarding_stubs.nim --dry-run
##   nim c -r tools/generate_forwarding_stubs.nim --force

import core/trusted/layer_declaration
axiomLayer "tools"
import std/json
import std/os
import std/strutils
import std/times

const
  DefaultMapPath = "data/migration_map.json"
  SrcDir = "src"

func nimImportPath(filePath: string): (string, string) =
  ## Convert a file path like 'src/core/solver/wrappers.nim' to a
  ## Nim-style dotted import path and module name.
  var path = filePath.replace("\\", "/")

  # Strip 'src/' prefix
  if path.startsWith(SrcDir & "/"):
    path = path[SrcDir.len + 1 .. ^1]
  elif path.startsWith(SrcDir):
    path = path[SrcDir.len .. ^1]

  # Strip '.nim' extension
  if path.endsWith(".nim"):
    path = path[0 .. ^5]

  # Convert filesystem separators
  let importPath = path.replace("\\", "/").strip(chars = {'/'})
  let moduleName = if "/" in importPath:
    importPath.rsplit('/', 1)[1]
  else:
    importPath

  (importPath, moduleName)

func makeStubContent(newImportPath, moduleName, generatedAt, oldImportPath, mapPath: string): string =
  var deprecatedMsg = ""
  if oldImportPath.len > 0:
    deprecatedMsg = "{.deprecated: \"Forwarding stub: '" & oldImportPath &
      "' deprecated. Use '" & newImportPath & "' directly.\".}\n"

  "## AUTO-GENERATED by tools/generate_forwarding_stubs.nim — DO NOT EDIT\n" &
  "## Source: " & mapPath & "\n" &
  "## Generated: " & generatedAt & "\n" &
  "## To regenerate: nim c -r tools/generate_forwarding_stubs.nim\n" &
  "## WARNING: This stub will be auto-deleted when reference count reaches 0.\n" &
  deprecatedMsg &
  "import " & newImportPath & "\n" &
  "export " & moduleName & "\n"

proc loadMigrationMap(mapPath: string): seq[(string, string)] =
  ## Load and validate migration_map.json.
  if not fileExists(mapPath):
    stderr.writeLine("Error: migration map not found at ", mapPath)
    quit(1)

  var data: JsonNode
  try:
    data = parseJson(readFile(mapPath))
  except JsonParsingError as e:
    stderr.writeLine("Error: malformed JSON in migration map: ", e.msg)
    quit(1)

  let mappings = data.getOrDefault("mappings")
  if mappings.isNil or mappings.kind != JArray:
    stderr.writeLine("Error: 'mappings' key missing or not a list in migration map")
    quit(1)

  for i in 0..<mappings.len:
    let entry = mappings[i]
    if entry.kind != JObject:
      stderr.writeLine("Error: mapping[", i, "] is not an object")
      quit(1)
    if not entry.hasKey("old") or not entry.hasKey("new"):
      stderr.writeLine("Error: mapping[", i, "] must have 'old' and 'new' keys")
      quit(1)
    let oldPath = entry["old"].getStr().replace("\\", "/")
    let newPath = entry["new"].getStr().replace("\\", "/")
    result.add((oldPath, newPath))

proc main() =
  var dryRun = false
  var force = false
  var mapPath = DefaultMapPath

  for i in 1 .. paramCount():
    let arg = paramStr(i)
    if arg == "--dry-run":
      dryRun = true
    elif arg == "--force":
      force = true
    elif arg == "--map" and i < paramCount():
      mapPath = paramStr(i + 1)

  let mappings = loadMigrationMap(mapPath)
  echo "Loaded ", mappings.len, " mapping(s) from ", mapPath
  echo ""

  let generatedAt = now().utc().format("yyyy-MM-dd'T'HH:mm:ss'Z'")

  var generated = 0
  var skipped = 0
  var errors = 0

  for (oldPath, newPath) in mappings:
    let (importPath, moduleName) = nimImportPath(newPath)
    let (oldImportPath, _) = nimImportPath(oldPath)
    let stubContent = makeStubContent(importPath, moduleName, generatedAt, oldImportPath, mapPath)

    # Skip / overwrite logic
    if fileExists(oldPath) and not force:
      echo "  SKIP  ", oldPath, " (already exists, use --force to overwrite)"
      inc skipped
      continue

    if dryRun:
      let action = if fileExists(oldPath): "OVERWRITE" else: "CREATE"
      echo "  ", action.alignLeft(9), " ", oldPath
      inc generated
      continue

    # Write stub
    try:
      let parent = parentDir(oldPath)
      if parent.len > 0 and not dirExists(parent):
        createDir(parent)
      writeFile(oldPath, stubContent)
      echo "  CREATE  ", oldPath
      inc generated
    except CatchableError as e:
      stderr.writeLine("  ERROR   ", oldPath, " — ", e.msg)
      inc errors

  # Summary
  echo ""
  let mode = if dryRun: "dry-run" elif force: "force" else: "default"
  echo "[generate_forwarding_stubs] mode=", mode
  echo "  Generated: ", generated
  echo "  Skipped:   ", skipped
  echo "  Errors:    ", errors

when isMainModule:
  main()
