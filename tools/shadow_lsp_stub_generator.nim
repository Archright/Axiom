## Phase D1-B: Generate LSP forwarding stubs for deleted shadow files.
## After proc_to_func_standardizer deletes shadows, this tool creates minimal
## forwarding stubs so LSP navigation still works.
##
## Usage:
##   nim c -o:bin/shadow_lsp_stub_generator tools/shadow_lsp_stub_generator.nim
##   bin/shadow_lsp_stub_generator --dry-run
##   bin/shadow_lsp_stub_generator --apply

import core/trusted/layer_declaration
axiomLayer "tools"
import std/[algorithm, os, strutils]

const
  ShadowSuffix = "_shadow.nim"

type
  StubInfo = object
    shadowPath: string
    origPath: string
    modulePath: string  # e.g. "verification/reporter"

proc log(msg: string) =
  stderr.writeLine("shadow_lsp_stub_generator: ", msg)

proc findShadowFiles(srcDir: string): seq[string] =
  for path in walkDirRec(srcDir):
    if path.endsWith(ShadowSuffix):
      result.add(path)
  result.sort()

proc shadowToOriginal(shadowPath: string): string =
  let (dir, name, ext) = splitFile(shadowPath)
  if name.endsWith("_shadow"):
    result = dir / (name[0 .. ^("_shadow".len + 1)] & ext)
  else:
    result = shadowPath

proc modulePathFromOriginal(origPath: string, srcDir: string): string =
  let rel = origPath.relativePath(srcDir)
  result = rel.changeFileExt("").replace('/', '/')

proc generateStubContent(modulePath: string): string =
  let moduleName = modulePath.split('/')[^1]
  result = "## LSP forwarding stub for deleted shadow file.\n"
  result &= "## Auto-generated by shadow_lsp_stub_generator.\n"
  result &= "import " & modulePath & "\n"
  result &= "export " & moduleName & "\n"

proc main() =
  var dryRun = true
  var apply = false

  for i in 1 .. paramCount():
    let arg = paramStr(i)
    if arg == "--dry-run":
      dryRun = true
      apply = false
    elif arg == "--apply":
      apply = true
      dryRun = false

  if not apply:
    dryRun = true

  let toolDir = parentDir(currentSourcePath())
  let repoRoot = parentDir(toolDir)
  let srcDir = repoRoot / "src"

  log("Scanning " & srcDir & " for shadow files...")
  let shadows = findShadowFiles(srcDir)
  log("Found " & $shadows.len & " shadow files")

  var stubs: seq[StubInfo]
  var existingStubs = 0
  var missingOrig = 0

  for shadowPath in shadows:
    let origPath = shadowToOriginal(shadowPath)
    if not fileExists(origPath):
      inc missingOrig
      continue

    let origLines = readFile(origPath).splitLines().len
    if origLines <= 5:
      # Already a stub or tiny file
      inc existingStubs
      continue

    let stub = StubInfo(
      shadowPath: shadowPath,
      origPath: origPath,
      modulePath: modulePathFromOriginal(origPath, srcDir)
    )
    stubs.add(stub)

  log($stubs.len & " shadows need LSP stubs")
  log($existingStubs & " already tiny files skipped")
  log($missingOrig & " missing originals")

  if dryRun:
    log("")
    log("=== DRY RUN - no changes will be made ===")
    log("")
    for stub in stubs:
      let rel = stub.shadowPath.relativePath(repoRoot)
      log("  STUB: " & rel & " -> " & stub.modulePath)
    log("")
    log("Run with --apply to generate stubs.")
  else:
    log("")
    log("=== APPLY MODE ===")
    var generated = 0
    for stub in stubs:
      let stubContent = generateStubContent(stub.modulePath)
      writeFile(stub.shadowPath, stubContent)
      inc generated
    log("Generated " & $generated & " LSP stubs")

  echo "{"
  echo "  \"stubsNeeded\": ", $stubs.len, ","
  echo "  \"dryRun\": ", $dryRun, ","
  echo "  \"stubFiles\": ["
  for i, stub in stubs:
    let comma = if i < stubs.len - 1: "," else: ""
    echo "    \"", stub.shadowPath.relativePath(repoRoot), "\"", comma
  echo "  ]"
  echo "}"

when isMainModule:
  main()
